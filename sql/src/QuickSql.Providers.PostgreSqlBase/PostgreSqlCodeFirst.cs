using QuickSql.Metadata;
using QuickSql.Providers;
using QuickSql.Sql;

namespace QuickSql.Providers.PostgreSqlBase;

/// <summary>PG 系的 DDL。与查询文本共用同一份标识符策略（双引号一漏，QuickSqlOrder 就变成 quicksqlorder，
/// 建出来的表与查的表不是同一张）。五处与 T-SQL 不同：默认模式 public；没有 CLUSTERED（聚簇是
/// WITH (fillfactor) 加 CLUSTER 命令）而 FULLTEXT 报错（真语法是 USING gin (to_tsvector(…))）；
/// 改类型与改可空性是两条语句（ALTER COLUMN … TYPE 不碰 NOT NULL）；列注释是原生 COMMENT ON COLUMN；
/// DROP INDEX 吃带模式的索引名、没有 ON（索引是独立对象），索引名必须与建它时同一套模式限定，
/// 否则在 search_path 不等于 public 的会话上会删不掉、或删到同名另一张。</summary>
public class PostgreSqlCodeFirst(PostgreSqlTypes types) : ICodeFirstDialect
{
    public IdentifierPolicy Identifiers => IdentifierPolicy.PostgreSQL;

    /// <summary>自增写法：GENERATED BY DEFAULT AS IDENTITY（SQL 标准那一支；更通用的 SERIAL 是金仓行点名的分岔）。
    /// 选它两条理由：序列挂在列上（改名删列不留孤儿序列）、BY DEFAULT 允许显式写值（补上没有 IDENTITY_INSERT 开关那一格）。
    /// 代价：这一型要 PG 10+；叶子们（9.2 内核一档）认不认是内核代数推断而非厂商读数，
    /// 按"文档明写的分岔才配覆写"至今无人覆写——且血统构造直 new 本类，覆写入口本来就不存在
    /// （三族里只有 Oracle 留了 CreateCodeFirst 虚口）。真库到场第一问仍是这句 CREATE TABLE 收不收。</summary>
    protected virtual string IdentityClause => " GENERATED BY DEFAULT AS IDENTITY";

    public void EmitCreateTable(SqlWriter writer, EntityContract contract)
    {
        writer.Append("CREATE TABLE ");
        EmitTable(writer, contract.Table);
        writer.Append(" (");

        var parts = new List<string>(contract.Columns.Length + 1);

        foreach (var column in contract.Columns)
            parts.Add(Definition(column));

        if (contract.PrimaryKey.Length > 0)
        {
            var key = string.Join(", ", contract.PrimaryKey.Select(c => Identifiers.Quote(c.ColumnName)));

            parts.Add($"CONSTRAINT {Identifiers.Quote("PK_" + contract.Table.Name)} PRIMARY KEY ({key})");
        }

        writer.Append(string.Join(", ", parts)).Append(')');

        foreach (var index in contract.Indexes)
        {
            writer.Append(" ; ");
            EmitCreateIndex(writer, contract.Table, index);
        }
    }

    public void EmitAddColumn(SqlWriter writer, TableInfo table, ColumnContract column)
    {
        writer.Append("ALTER TABLE ");
        EmitTable(writer, table);
        writer.Append(" ADD COLUMN ").Append(Definition(column));
    }

    /// <summary>这一家的 ALTER COLUMN … TYPE 不会顺带重置可空性（与 T-SQL 相反，那一家会），
    /// 所以要独立一句把契约声称的那一侧写回去。漏掉它不会报错，只会让"改了精度"顺带改了约束——
    /// 约束是 NOT NULL 时那一句 SET NOT NULL 在有历史 NULL 的行上会失败，这失败才是它该出现的地方。</summary>
    public void EmitAlterColumnPrecision(SqlWriter writer, TableInfo table, ColumnContract column)
    {
        var stored = types.ApplyStorageDefaults(column);

        writer.Append("ALTER TABLE ");
        EmitTable(writer, table);
        writer.Append(" ALTER COLUMN ").Append(Identifiers.Quote(column.ColumnName));
        writer.Append(" TYPE ").Append(types.GetStoreType(stored));

        writer.Append(" ; ");

        writer.Append("ALTER TABLE ");
        EmitTable(writer, table);
        writer.Append(" ALTER COLUMN ").Append(Identifiers.Quote(column.ColumnName));
        // 与建表那一句读同一格（NullableInStore）：全站只留一条规则——DDL 里的可空性不读 IsNullable。
        writer.Append(stored.NullableInStore ? " DROP NOT NULL" : " SET NOT NULL");
    }

    public bool TryEmitColumnComment(SqlWriter writer, TableInfo table, ColumnContract column)
    {
        writer.Append("COMMENT ON COLUMN ");
        EmitTable(writer, table);
        writer.Append('.').Append(Identifiers.Quote(column.ColumnName)).Append(" IS ");
        writer.AppendStringLiteral(column.Comment ?? string.Empty, unicode: false);

        return true;
    }

    /// <summary>COMMENT ON TABLE 本身就是"设值"而不是"追加"，所以第二趟重发不会撞"属性已存在"（幂等免费），
    /// 而写空串等于把备注清掉——与列注释那一句同一个语义。</summary>
    public bool TryEmitTableComment(SqlWriter writer, TableInfo table, string? comment)
    {
        writer.Append("COMMENT ON TABLE ");
        EmitTable(writer, table);
        writer.Append(" IS ");
        writer.AppendStringLiteral(comment ?? string.Empty, unicode: false);

        return true;
    }

    public void EmitCreateIndex(SqlWriter writer, TableInfo table, IndexContract index)
    {
        // 聚簇在这一家不是索引的一种而是一条命令（CLUSTER），NonClustered/Clustered 都落成普通索引；
        // 全文检索要的是另一个访问方法 + 一个表达式，悄悄发成 btree 会建出查不了全文的索引。
        if (index.Kind == IndexKind.FullText)
            throw new QuickSqlException($"PG 系不支持 CREATE INDEX … FULLTEXT 这种写法，全文索引要 USING gin (to_tsvector(…))，尚未接线（§9.2）");

        writer.Append(index.Kind == IndexKind.Unique ? "CREATE UNIQUE INDEX " : "CREATE INDEX ");
        writer.Append(Identifiers.Quote(index.Name)).Append(" ON ");
        EmitTable(writer, table);
        writer.Append(" (");

        for (var i = 0; i < index.ColumnNames.Length; i++)
        {
            if (i > 0)
                writer.Append(',');

            writer.Append(' ').Append(Identifiers.Quote(index.ColumnNames[i]));
            writer.Append(index.Descending ? " DESC" : " ASC");
        }

        writer.Append(" )");
    }

    /// <summary>索引名按它所在的那个模式限定（读回来的是 pg_class.relname，不带模式）。
    /// 不带 ON 表名：这一家的索引是目录里的独立对象，T-SQL 那种 DROP INDEX … ON … 在这儿是语法错。
    /// 唯一约束不走这一句：它的支撑索引与约束同名，删同名索引会失败，计划层把 IsConstraint 归进"要人工"；
    /// 这里不做二次判断——判断已在上游做完一次，再判一遍只会变成两条可能分岔的规则。</summary>
    public bool TryEmitDropIndex(SqlWriter writer, TableInfo table, SchemaIndex index)
    {
        writer.Append("DROP INDEX ");
        writer.Append(Identifiers.Quote(table.Schema ?? "public")).Append('.');
        writer.Append(Identifiers.Quote(index.Name));

        return true;
    }

    string Definition(ColumnContract column)
    {
        var writer = new SqlWriter(new(), [], '@');

        EmitColumnDefinition(writer, column);

        return writer.ToString();
    }

    void EmitColumnDefinition(SqlWriter writer, ColumnContract column)
    {
        var stored = types.ApplyStorageDefaults(column);

        writer.Append(Identifiers.Quote(column.ColumnName)).Append(' ').Append(types.GetStoreType(stored));

        if (column.IsIdentity)
            writer.Append(IdentityClause);

        // 主键列上的 NOT NULL 由表级 PRIMARY KEY 保证，但契约说它非空就得写：没有主键的表走不到约束那一段，
        // 漏写就得到一个可空列。可空性读 NullableInStore（五族同一句形状，才不需要一家一份解释）。
        writer.Append(stored.NullableInStore ? " NULL" : " NOT NULL");

        EmitDefault(writer, stored);
    }

    void EmitTable(SqlWriter writer, TableInfo table)
    {
        writer.Append(Identifiers.Quote(table.Schema ?? "public")).Append('.');
        writer.Append(Identifiers.Quote(table.Name));
    }

    /// <summary>列默认值。原生 BOOLEAN 落 TRUE/FALSE；字符串走 AppendStringLiteral——
    /// standard_conforming_strings 默认档上反斜杠不是转义，与谓词侧同一条依据。</summary>
    void EmitDefault(SqlWriter writer, ColumnContract column)
    {
        if (column.DefaultValue is not {} value)
            return;

        writer.Append(" DEFAULT ");

        switch (value)
        {
            case string text:
                writer.AppendStringLiteral(text, unicode: false);
                break;
            case bool flag:
                writer.Append(flag ? "TRUE" : "FALSE");
                break;
            default:
                writer.Append(ColumnDefaultText.Number(value));
                break;
        }
    }
}
