using QuickSql.Metadata;
using QuickSql.Providers;
using QuickSql.Sql;

namespace QuickSql.Providers.PostgreSqlBase;

/// <summary>PG 系的主键策略（§4 的 IKeyStrategy）。这一家与 T-SQL 在这一格上是同一档能力：
/// <c>INSERT … VALUES (…), (…) RETURNING "Id"</c> 一次拿回全部主键，所以 §16.9 那个"保持数据库自增"
/// 的决定在 PG 系上没有额外痛感 —— 但 <c>SupportsBulkKeyRetrieval</c> 的真值来自厂商文档，
/// 现场没有实例跑过（§13.5 的出处台账）。</summary>
public sealed class PostgreSqlKeys : IKeyStrategy
{
    public bool SupportsBulkKeyRetrieval => true;

    /// <summary>这一家没有 <c>SET IDENTITY_INSERT</c> 这种会话开关。要给自增列显式写值有两条路：
    /// <c>OVERRIDING SYSTEM VALUE</c>（只管 <c>INSERT … SELECT</c>）与直接写值（<c>GENERATED BY DEFAULT</c>
    /// 本来就允许）—— 两条都不是"两侧各发一条语句"的形状，所以这里返回 null 让 Core 走"没有开关"那一支。
    /// 能力位 <c>Identity_ExplicitInsert</c> 也因此不声明。</summary>
    public bool SupportsExplicitIdentityInsert => false;

    /// <summary>调用方负责自己那侧的空格（<c>DialectBase</c> 在 <c>VALUES</c> 与整句末尾各补一次）。</summary>
    public void EmitReturning(SqlWriter writer, IReadOnlyList<ColumnContract> returning)
    {
        writer.Append("RETURNING ");

        for (var i = 0; i < returning.Count; i++)
        {
            if (i > 0)
                writer.Append(", ");

            writer.AppendIdentifier(IdentifierPolicy.PostgreSQL, returning[i].ColumnName);
        }
    }

    public string? IdentityInsertToggle(SqlWriter writer, TableInfo table, bool on) => null;

    /// <summary>这一家发得出句尾 <c>RETURNING</c>，"语句后回读"那一档（v0.34 的口子上）用不到 ——
    /// Core 只在批量位为 false 时才会问它，所以这里 false 不是"没有那条路"而是"用不上那条路"。</summary>
    public bool SupportsPostStatementKeyRead => false;

    /// <summary>不可达（<see cref="SupportsBulkKeyRetrieval"/> 为 true 时 Core 不会走到这里）；
    /// 留抛不留空体，理由与 <c>SqlServerKeys</c> 同一条。</summary>
    public void EmitPostStatementKeyRead(SqlWriter writer, ColumnContract key)
        => throw new QuickSqlException("PG 系走批量 RETURNING，语句后回读那一档在这一家不可达。");
}
