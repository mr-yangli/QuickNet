/// 而这是第一次换在<b>版本</b>而不是<b>代数或参照物</b>上：另五家的问题是"这台库认得这句吗"，本家的问题是
/// "这台库是那一型引入之前还是之后"。判据不因此改：文档明写的分岔才配覆写，而本行没有任何一处明写的分岔。</para>
