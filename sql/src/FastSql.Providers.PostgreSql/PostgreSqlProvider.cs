/// 另两处（PG 血统模板串里那层 CAST、Oracle 血统 <c>IdentityClause</c> 那句 12c）的理由仍然埋在家族层，
/// 读产出看不出来。而这一格由此第一次有了一句可数的话：<b>明示这件事本身是正典叶的动作</b>——派生叶
