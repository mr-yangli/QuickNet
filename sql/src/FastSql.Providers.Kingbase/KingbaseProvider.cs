using System.Data.Common;
using FastSql.Metadata;
using FastSql.Providers.PostgreSqlBase;

namespace FastSql.Providers.Kingbase;

/// <summary>金仓 KES V8 的驱动槽位（§9.1 的 PG 系那一行）。
///
/// <b>它今天一个字都不覆写</b>，而这一格形状本身就是交付物：§2 那句"provider 之间禁止互引"禁的是
/// 兄弟 provider 互相伸手拿实现，共用的东西只能往上一层（<c>DialectBase</c> 与
/// <c>PostgreSqlProviderBase</c> 都在那一层）。金仓挂到血统基类上之后产出与基类逐字同形，
/// 于是"70% 的国产库方言是 PG 的一个变体"（§9.1 那句判断）第一次有了一个可数的证据：一层空壳。
///
/// <b>三件已知会变的东西</b>（§9.1 金仓那一行的"主要坑"，逐条对到今天的状态）：
/// <list type="bullet">
/// <item>双引号大小写敏感 —— 已经落进 <see cref="IdentifierPolicy.PostgreSQL"/>，由血统基类拿着，不覆写。</item>
/// <item><c>SERIAL</c> 与 <c>IDENTITY</c> —— 基类选了 <c>GENERATED BY DEFAULT AS IDENTITY</c>，
/// 理由与代价写在 <see cref="PostgreSqlCodeFirst"/>；金仓 V8 的内核版本决定它认不认这一型，<b>未实测</b>。</item>
/// <item>Oracle 兼容模式开关会改变分页与 <c>NVARCHAR2</c> 行为 —— 这是<b>今天没有建模的那一个</b>：
/// 一个连接串参数就能换掉本 provider 的方言假设，而 §4 的 SPI 里没有一个"兼容模式"槽位。
/// 缺口与重开条件记在 §14。</item>
/// </list></summary>
[FastSqlProvider(DbKind.Kingbase)]
public sealed class KingbaseProvider : PostgreSqlProviderBase
{
    /// <summary>清单里的 <c>key</c>。<c>assembly</c> 按厂商文档是 <c>Kdbndp</c>（金仓自研驱动），
    /// 现场也可以注 <c>Npgsql</c>（§9.1 那句"兼容 Npgsql"）—— 两条都走同一份注入路径，本程序集编译期都不认识。</summary>
    public const string DriverKey = "kingbase";

    public KingbaseProvider(DbProviderFactory driverFactory)
        : base(DbKind.Kingbase, driverFactory)
    {
    }
}
