using FastSql.Metadata;
using FastSql.Providers;
using FastSql.Sql;

namespace FastSql.Providers.OracleBase;

/// <summary>Oracle 血统的 DDL（§9.2、§10.4，第三家）。与两族同一纪律：P0 只产出文本与黄金样本比对，
/// <b>不执行</b>，而 DDL 与运行时查询共用同一个 <see cref="IdentifierPolicy.OracleFamily"/> ——
/// 在这一族这件事比落地另两家更要紧：折叠发生在策略里，所以建出来的表名与查的表名<em>只能</em>是同一个字形
/// （v0.31 的第五家把这一格推得更紧：它的折叠字形由 <c>COMPATIBLE_MODE</c> 决定，见 <c>XuguCodeFirst</c> 类注释第一条）。
///
/// <para>四处与两族不同，每处都不是换个关键字：
/// <list type="bullet">
/// <item><b>默认模式是"当前会话用户"，不是一个写死的名字</b>。T-SQL 那一家写 <c>dbo</c>、PG 系写 <c>public</c>，
/// 而这一家没有那种"所有人都能进"的公共模式：<c>CREATE TABLE t</c> 落在连接所带的那个模式下。
/// 所以 <c>Schema</c> 为 null 时这里<em>什么都不写</em>，而不是补一个假名字 —— 补 <c>"DBO"</c> 会得到一条
/// <c>schema does not exist</c>，而那正是 §9.2 说的"联调第一天浪费半天"的形状。</item>
/// <item><b>加列没有 <c>ADD COLUMN</c> 这种写法</b>：那一家是 <c>ALTER TABLE t ADD (col type)</c>，
/// 括号是语法的一部分而不是可选的分组（它同时也是多列一次加完的那个写法）。漏掉括号在达梦上可能侥幸过，
/// 在 Oracle 上对某些子句就是错。</item>
/// <item><b>改类型是 <c>MODIFY</c> 而且一句带得上可空性</b>：金仓那一族要两条语句（<c>TYPE</c> 不碰
/// <c>NOT NULL</c>），T-SQL 的 <c>ALTER COLUMN</c> 会<em>顺带重置</em>可空性所以必须把定义整列重写，
/// 而这一族的 <c>MODIFY</c> 说的是"这一列改成这个形状"，两半一起改。于是这一家不需要那个 <c> ; </c> 串联 ——
/// 而它恰好是 §9.4 那句"没有 <c>MultiStatement</c> 的库要按 <c>;</c> 拆开逐条发"唯一真正躲不掉的地方。
/// <b>这句"唯一"是本版写下的，而它活得最短</b>：v0.30 的第四家（建表句尾那条 <c> ; </c> 串索引，
/// 而它其实有内联形没选）与 v0.31 的第五家（同一处、同一条串联）各顶了一次。<b>今天可重数的分布是：
/// 五家的 <c>CodeFirst</c> 全都产出过 <c> ; </c> 串，而五家里只有 T-SQL 一家声明 <c>MultiStatement</c></b>
/// （<c>SqlServerProvider.cs:43</c>，而 <c>grep -rn DbCapabilities.MultiStatement src/</c> 在 src 下
/// 只命中那一处声明 + 枚举自己），所以"拆的时候没有'顺手就对了'的可能"这一句今天对<b>四家</b>成立。
/// "唯一"那半句要按<em>库侧退路</em>读才仍然成立，而这一格今天只有一家有那条退路：<b>五家里只有 MySQL 血统
/// 的建表句语法上带得上 <c>INDEX (...)</c> 那一形，而它的代码没选</b> —— 理由写在 §9.4 那一格
/// （"选独立句是为了让 <c>EmitCreateIndex</c> 一个出口同时服务'建表带索引'与'单独建索引'两个入口"），
/// 而它的 <c>EmitCreateTable</c> 尾段发的确实是 <c> ; </c> 串；金仓那一家同一处同一形
/// （<c>PostgreSqlCodeFirst.cs:54</c>）。于是"把索引并入建表句"这一档在五家里是<b>零家</b>，
/// 而 §9.4 里那句"不能像 PG 系那样并入建表句"是本仓库自己的一处存量错账（它把"PG 系能并"当成了事实，
/// 而 PG 的产出与这一族同形），本版回写 §9.4 时按这一格改。这一族自己则是语法里<em>没有</em>那一形 ——
/// 它不是"没选"，是没有。</item>
/// <item><b>主键没有 <c>CLUSTERED</c></b>：那一颗是 T-SQL 的存储布局开关，这一族的聚簇由
/// <c>CLUSTER KEY</c>（IOT，索引组织表）决定而它与主键约束是两件事，所以这里只写 <c>PRIMARY KEY</c>。</item>
/// </list></para>
///
/// <para><see cref="IdentityClause"/> 是这一版<em>唯一一处有真实覆写者的虚口</em>：Oracle 12c 起是
/// <c>GENERATED BY DEFAULT AS IDENTITY</c>，而 §9.1 记的达梦那一列写的是 <c>IDENTITY</c> —— 它长成
/// T-SQL 那个 <c>IDENTITY(1,1)</c> 的形状（两家在这一点上同形不是巧合：达梦的语法表大量取自 SQL Server）。
/// 覆写在 <c>FastSql.Providers.Dameng</c>，而它也是"为什么这颗是虚的不是常量"的见证：
/// 与 <c>PostgreSqlCodeFirst</c> 里那颗至今没有覆写者的同名虚口相对，那一格记在 §14。
/// <b>【v0.31】那个"两家同形"今天是三家，而第三家没有那条归因</b>：第五家发的也是
/// <c>IDENTITY(1,1)</c>（<c>XuguCodeFirst.cs:69</c> 那颗 <c>const</c>，判据是
/// <c>grep -rn 'IDENTITY\(1,1\)' src/ --include=*.cs | grep -v "///"</c> 交出三处产出点），
/// 而它的内核是自研的、没有"语法表取自 SQL Server"这条来历可指 —— 所以这一格从"同形有原因"
/// 变成了"同形有两家有原因、一家没有"。<b>这不动摇上面那句"唯一一处有真实覆写者的虚口"</b>：
/// 第五家是单层类，它那份是自家的常量而不是对这颗 <c>virtual</c> 的覆写（那一格与
/// "它为什么不留覆写点"一起写在 <c>XuguCodeFirst</c> 类注释第二条）。</para>
///
/// <para>一处今天<em>不判</em>的东西：这一族的标识符长度上限在 12.1 之前是 30 字节，而
/// <c>PK_</c> + 表名与 <c>IX_</c> 前缀的索引名都由契约生成，长表名会超。判它要先知道库的版本，
/// 而 SPI 里没有那一格（同一个缺口形状见 §14 的"兼容模式"那一行）。
/// <b>【v0.37 第三笔】这一格今天仍然不判，但它第一次与上面那颗 <see cref="IdentityClause"/> 落在同一颗叶子上</b>：
/// 本尊到场之前，这一族"按版本分岔"的两格读数是分开挂的（IDENTITY 那一形挂在达梦/神通两份厂商读数上，
/// 30 字节挂在一份没有住户的通用说法上），而本笔让"同一句 CREATE TABLE 里两处各自按区间成立不成立"
/// 第一次成为一句可跑的断言（<c>OracleDialectTests</c> 那条点名的用例：一条语句同时发
/// <c>GENERATED BY DEFAULT AS IDENTITY</c> 与一颗超过 30 字节的约束名，逐字吐出不加截断）。
/// 于是这一格的<em>推断</em>侧写清了：<b>12.1 之前那一区间这一句是两处语法错，12.1 起是两句一起满足</b>——
/// 而这仍然只是推断，因为它没有在一台 12.1 之前的库上跑过；缺口照旧记 §14，本笔不替它升档。</para></summary>
public class OracleCodeFirst(OracleTypes types) : ICodeFirstDialect
{
    public IdentifierPolicy Identifiers => IdentifierPolicy.OracleFamily;

    /// <summary>自增写法（见类注释那一段）。带 <c>BY DEFAULT</c> 而不是 <c>ALWAYS</c>：后者显式写值要
    /// <c>OVERRIDING SYSTEM VALUE</c>，而 §4 的 <see cref="IKeyStrategy.SupportsExplicitIdentityInsert"/>
    /// 在这一族是 false —— 那句 false 说的是"没有会话开关"，不是"这一列绝对不能被写"。
    /// 【v0.36 第五笔：这一口第一次遇到"第二颗叶子而它不走"—— <c>ShenTongProvider</c> 不继承
    /// <c>CreateCodeFirst</c>，覆写者数照旧是一（只有达梦那颗 <c>IDENTITY(1,1)</c>），而这一格从此有了
    /// 第三种读法：另两族那两颗同样零覆写者的虚口是<em>没人可走</em>（没有缝），本这颗是<em>有缝而没人走</em>。
    /// "先开好再等人"这句到本笔才要改读成"等的是差异不是人"，而它第一次有了可跑的见证：
    /// <c>ShenTongDialectTests</c> 那句 <c>Assert.Same(typeof(OracleCodeFirst), …)</c> 与同族异形对读。
    /// 神通真实例到场的第一问仍是这一句 —— 这台库认不认 <c>GENERATED BY DEFAULT AS IDENTITY</c>
    /// （§9.1 行 902、§14 行 2044）。
    /// <b>【v0.37 第三笔】上面那句"第三颗叶子而它不走"今天是第四颗，而新来的这一颗不走的原因与前三颗都不同</b>：
    /// PG 与 MySQL 两族那几颗是<em>没有缝</em>，神通是<em>有缝而没有读数所以不赌</em>，本尊是
    /// <em>有缝、有读数，而那份读数就是这段默认值自己</em>——它是这一族里第一颗"覆写点与自家语法表同源"的叶子，
    /// 所以"零覆写"在它身上不是裁决（裁决要有可裁的两端），是<em>无案可立</em>。这一档是那句判据的
    /// 第三种落点，与前两档（"文档明写分岔而裁不落" ∶ "无明写分岔可裁"）并列。
    /// 于是上面那句"覆写者数照旧是一"从今天起要多读一层：<b>一颗挂着覆写者的虚口，它的覆写者数
    /// 与它的住户数从此不是一回事</b>（这一族三颗叶子、一个覆写者），而"等的是差异不是人"那一句
    /// 在本笔之后剩下的等的是金仓那一支 Oracle 模式。</summary>
    protected virtual string IdentityClause => " GENERATED BY DEFAULT AS IDENTITY";

    public void EmitCreateTable(SqlWriter writer, EntityContract contract)
    {
        writer.Append("CREATE TABLE ");
        EmitTable(writer, contract.Table);
        writer.Append(" (");

        var parts = new List<string>(contract.Columns.Length + 1);

        foreach (var column in contract.Columns)
            parts.Add(Definition(column));

        if (contract.PrimaryKey.Length > 0)
        {
            var key = string.Join(", ", contract.PrimaryKey.Select(c => Identifiers.Quote(c.ColumnName)));

            parts.Add($"CONSTRAINT {Identifiers.Quote("PK_" + contract.Table.Name)} PRIMARY KEY ({key})");
        }

        writer.Append(string.Join(", ", parts)).Append(')');

        foreach (var index in contract.Indexes)
        {
            writer.Append(" ; ");
            EmitCreateIndex(writer, contract.Table, index);
        }
    }

    public void EmitAddColumn(SqlWriter writer, TableInfo table, ColumnContract column)
    {
        writer.Append("ALTER TABLE ");
        EmitTable(writer, table);
        writer.Append(" ADD (").Append(Definition(column)).Append(')');
    }

    /// <summary><c>MODIFY (col 类型 NOT NULL)</c>：这一家一句就能把类型与可空性一起说完
    /// （见类注释第三条），所以这里没有金仓那一条 <c> ; </c> 串联的第二句。
    /// 整列定义重写而不是只写类型：<c>MODIFY</c> 会按新定义重建那一列，漏写可空性就等于把它交回库的默认
    /// （可空），那与 T-SQL 上"漏写 <c>NULL</c> 被顺带重置"是同一个事故的两种来路。</summary>
    public void EmitAlterColumnPrecision(SqlWriter writer, TableInfo table, ColumnContract column)
    {
        writer.Append("ALTER TABLE ");
        EmitTable(writer, table);
        writer.Append(" MODIFY (").Append(Definition(column)).Append(')');
    }

    /// <summary>原生 <c>COMMENT ON COLUMN</c>，与金仓那一族同形（那一家也是标准语法），
    /// 与 T-SQL 的 <c>sp_addextendedproperty</c> 分岔。表名不带模式时注释落在当前模式的同名表上 ——
    /// 与建表那一句同一个默认，所以两侧不会指到两张表。</summary>
    public bool TryEmitColumnComment(SqlWriter writer, TableInfo table, ColumnContract column)
    {
        writer.Append("COMMENT ON COLUMN ");
        EmitTable(writer, table);
        writer.Append('.').Append(Identifiers.Quote(column.ColumnName)).Append(" IS ");
        writer.AppendStringLiteral(column.Comment ?? string.Empty, unicode: false);

        return true;
    }

    public void EmitCreateIndex(SqlWriter writer, TableInfo table, IndexContract index)
    {
        // Oracle Text 是完全另一套东西：域索引（CREATE INDEX … INDEXTYPE IS CTXSYS.CONTEXT）+ 一套
        // CONTAINS 谓词，而且那是一个独立安装的组件。把 FULLTEXT 悄悄发成普通 btree 索引会得到一个
        // "建好了但查不了全文"的索引，所以这里抛（§9.2 那句"宁可报错也不看着能用"）。
        if (index.Kind == IndexKind.FullText)
            throw new FastSqlException($"{nameof(OracleCodeFirst)} 不支持 CREATE INDEX … FULLTEXT：这一族的全文检索要 Oracle Text 域索引（CTXSYS.CONTEXT），尚未接线（§9.2）");

        writer.Append(index.Kind == IndexKind.Unique ? "CREATE UNIQUE INDEX " : "CREATE INDEX ");
        writer.Append(Identifiers.Quote(index.Name)).Append(" ON ");
        EmitTable(writer, table);
        writer.Append(" (");

        for (var i = 0; i < index.ColumnNames.Length; i++)
        {
            if (i > 0)
                writer.Append(',');

            writer.Append(' ').Append(Identifiers.Quote(index.ColumnNames[i]));
            writer.Append(index.Descending ? " DESC" : " ASC");
        }

        writer.Append(" )");
    }

    string Definition(ColumnContract column)
    {
        var writer = new SqlWriter(new(), [], ':');

        EmitColumnDefinition(writer, column);

        return writer.ToString();
    }

    void EmitColumnDefinition(SqlWriter writer, ColumnContract column)
    {
        var stored = types.ApplyStorageDefaults(column);

        writer.Append(Identifiers.Quote(column.ColumnName)).Append(' ').Append(types.GetStoreType(stored));

        if (column.IsIdentity)
            writer.Append(IdentityClause);

        // 与两族同一形状：可空那一侧也写出来。这一家确实接受列定义里的 NULL（它是 NOT NULL 的反面，
        // 不是"未写约束"），而写出来才不用在改精度那一句里重新推断 —— 少一处推断就少一处能猜错的地方。
        // 读 NullableInStore 与两族同句：本家那一型（触发器给值）在契约里没有对应的存储类型名，
        // 今天与 IsNullable 同值，改的是读的哪一格。
        writer.Append(stored.NullableInStore ? " NULL" : " NOT NULL");
    }

    /// <summary>模式为空就<em>不写限定</em>（见类注释第一条）：这一家没有 <c>dbo</c>/<c>public</c> 那种
    /// 人人可用的公共模式，裸名说的是"连接所带的那个模式"，那正是契约没写模式时唯一诚实的落点。</summary>
    void EmitTable(SqlWriter writer, TableInfo table)
    {
        if (table.Schema is { Length: > 0 } schema)
        {
            writer.Append(Identifiers.Quote(schema)).Append('.');
        }

        writer.Append(Identifiers.Quote(table.Name));
    }
}
