using System.Text;
using QuickSql.Metadata;
using QuickSql.Providers;
using QuickSql.Sql;

namespace QuickSql.Providers.OracleBase;

/// <summary>Oracle 血统的主键策略（§4 的 IKeyStrategy，第三家）。这一家是本仓库<b>第一份真的把
/// "批量回读主键"这一档答成"没有"的 provider</b>，而它不是一个实现漏洞，是三件事实叠出来的：
/// <list type="bullet">
/// <item>那一家没有 <c>OUTPUT inserted.*</c>（T-SQL）也没有 <c>RETURNING</c> 落在语句末尾当结果集发
/// （金仓那一族）。Oracle 的 <c>INSERT … RETURNING … INTO :x</c> 是<b>绑定输出</b>，不是结果集 ——
/// 而 <see cref="AdoParameter"/> 只带 <c>Name/Value/DbType/Size</c>，<b>没有方向位</b>，
/// 所以"这一颗是 OUT"这件事今天在这套 SPI 里说不出来。</item>
/// <item>另一条路是语句后再读一次当前值（<c>IDENTITYCURRVAL</c> / <c>@@IDENTITY</c> 那一档），
/// 而 <see cref="IKeyStrategy"/> 只有 <see cref="EmitReturning"/> 这一个"跟着语句一起发"的口子，
/// <b>没有"语句之后回读"这一格</b>。<b>【v0.34 改判】"没有这一格"半句作废：口子已经立在
/// <see cref="SupportsPostStatementKeyRead"/> 上了，这一家仍然 false 的原因换成了"回读表达式没有出处"
/// —— 那句改判的逐字账记在两颗新成员自己的注释与 §14 本行里，原话照抄不删。</b></item>
/// <item>于是 §12.4 第 1 项那句"L3 → L5：没有批量 RETURNING 的库要回填就退到逐条"在这一家只完成了一半 ——
/// 逐条是必要的，<em>不充分</em>：逐条之后仍然要有一个地方接住那一颗键。Core 的降级分支今天会把
/// <c>Returning</c> 照发，所以它在 <see cref="EmitReturning"/> 这一句上红，而不是悄悄发出回填不上的 SQL。</item>
/// </list>
/// <b>缺的是槽位而不是实现</b>，所以这一格记进 §14 的那一份缺口清单（与"两个已落地家族都有批量 RETURNING"
/// 那条事实并排读：§16.9 选"保持数据库自增"时写下的代价，到第三家才第一次有了可指的形状）。
/// <b>"两个"那句是 v0.23 的口径，照录不改；到 v0.31 它是三个</b>：这一格的分岔从 2 发 ∶ 1 抛 变成
/// <b>3 发 ∶ 2 抛</b>（发的是 T-SQL 的 <c>OUTPUT</c>、金仓的句尾 <c>RETURNING</c>、第五家那句
/// 带 <c>[BULK COLLECT]</c> 出处的 <c>RETURNING</c>；抛的是这一族与 MySQL 血统），
/// 而<em>缺的那一格没变</em>：三家里没有一家走"语句之后回读"，因为 SPI 到今天还是没有那一个口子。
/// 【v0.31】那句"三家"是 v0.23 的口径，五家数下来这一格仍然是<b>零</b>：五份 <c>IKeyStrategy</c> 实现里没有
/// 一处把 <c>LAST_INSERT_ID</c> / <c>IDENTITYCURRVAL</c> / <c>@@IDENTITY</c> 发进 SQL 文本，
/// 那三颗字符串今天只出现在六个地方，其中两处是抛出的异常文案（这里 <c>EmitReturning</c> 那一句、
/// <c>MySqlKeys</c> 同位那一句），其余四处是注释。也就是说"有那条路"的两家（这一族与 MySQL 血统）
/// 都只把路<em>写进了文案</em>，第五家更特别：它的一份产物真的这么发（<c>XuguKeys</c> 类注释第三条），
/// 而这里的代码仍然选了 <c>RETURNING</c> 那一边。位数变了而缺口原地不动，正是这一格该记 §14 而不是记"某家少实现"的理由。
///
/// <para><see cref="SupportsExplicitIdentityInsert"/> 在血统基类上取 false：Oracle 自己给自增列显式写值
/// 走的是 <c>GENERATED BY DEFAULT</c>（写值即覆盖，不需要开关），而 §9.1 记的达梦那一格是
/// <c>SET IDENTITY_INSERT ON</c> —— 那颗开关是<em>库种</em>的事，形状上与 <c>SqlServerKeys</c> 同一档。
/// 但这里<em>不</em>为它留覆写点，理由是实测出来的：<see cref="IdentityInsertToggle"/> 在 Core 里
/// <b>没有任何调用点</b>（今天只有 <c>InsertEngine</c> 与 <c>UpdateEngine</c> 的两条"未接"文案提到它，
/// 写自增列在问到 provider 之前就已经抛了），所以在达梦那一层覆写它会得到一颗永远不被调用的虚函数。
/// 缺口与它的前置条件（Core 先要有那条调用路径）一起记在 §14。</para></summary>
public sealed class OracleKeys : IKeyStrategy
{
    public bool SupportsBulkKeyRetrieval => false;

    public bool SupportsExplicitIdentityInsert => false;

    /// <summary>抛，而不是发一条"看着像在回填"的语句。调用方是 <c>DialectBase.EmitReturning</c>
    /// （它把这一格转交给这里），所以 INSERT 与 UPDATE 两档、前置与后置两种位置共用同一条文案 ——
    /// 两族的空格差异由调用方补，这一家两边都到不了这里。
    /// <b>这一口刻意不是 <c>virtual</c></b>：能让它成立的唯一条件是"这家有了 OUT 绑定或语句后回读"，
    /// 而那一天要改的是 <c>IKeyStrategy</c> 本身（§14 那一格），不是在这里留一颗没人覆写的虚函数。</summary>
    public void EmitReturning(SqlWriter writer, IReadOnlyList<ColumnContract> returning)
        => throw new QuickSqlException($"Oracle 血统没有可作为结果集发出的 OUTPUT/RETURNING，而本次请求要回填（{Columns(returning)}）。"
            + "两条路各缺一个东西：RETURNING … INTO 要的是 OUT 绑定（AdoParameter 没有方向位，那一格照旧缺）；"
            + "语句后回读那口子 v0.34 已经立在 IKeyStrategy 上，但这一家拿哪颗表达式回读（IDENTITYCURRVAL 那一档）"
            + "从未被本仓库的任何一台实例问证过，所以这一位也声明不了。"
            + "今天请自己生成主键（Guid/雪花）并直接用 ExecuteAffrowsAsync，或等那一颗表达式有出处（§14 记着重开条件）。");

    static string Columns(IReadOnlyList<ColumnContract> returning)
    {
        var names = new StringBuilder(returning.Count * 12);

        for (var i = 0; i < returning.Count; i++)
        {
            if (i > 0)
                names.Append(", ");

            names.Append(returning[i].ColumnName);
        }

        return names.ToString();
    }

    /// <summary>没有开关，而且这一口刻意不是 <c>virtual</c>（理由见类注释末段：Core 今天没有调用点）。
    /// 返回 null 让 Core 走"这条语句不需要前置/后置语句"那一支，与金仓那一族同一条路。</summary>
    public string? IdentityInsertToggle(SqlWriter writer, TableInfo table, bool on) => null;

    /// <summary>v0.34 把"语句后回读"那颗口子立起来了，而这一家今天答 <b>false</b> —— 缺的从"口子"改成了"表达式"：
    /// <c>IDENTITYCURRVAL</c> 那一档回读【推断】自厂商文档，本仓库没有任何一台 Oracle 血统实例问证过它
    /// （§13.4 的授权清单里没有第三族的真库，v0.23 到本版都是这台库不存在）。判据与 §9.1 的出处纪律同一条：
    /// 能力位声明的是"代码走到且成立的那一档"，不是"库里可能有那件事"。重开条件写在 §14 本行：
    /// 第一次有真库把那颗表达式问出来、且单行插入后回读对上号。</summary>
    public bool SupportsPostStatementKeyRead => false;

    /// <summary>与 <see cref="EmitReturning"/> 同一族立场：发不出一条有出处的回读句，就抛，
    /// 而不是发一条"看着像在回填"的。Core 只在 <see cref="SupportsPostStatementKeyRead"/> 为 true 时才调这里，
    /// 所以今天这一句不可达 —— 留抛不留空体。</summary>
    public void EmitPostStatementKeyRead(SqlWriter writer, ColumnContract key)
        => throw new QuickSqlException("Oracle 血统的语句后回读表达式从未被本仓库问证过，这一位不可达（理由见 SupportsPostStatementKeyRead）。");
}
