using FastSql.Metadata;
using FastSql.Providers;
using FastSql.Sql;

namespace FastSql.Providers.PostgreSqlBase;

/// <summary>PG 系的 DDL（§9.2、§10.4）。与查询文本同一个标识符策略（§9.2 那句"DDL 与运行时查询共用
/// 一份 <c>QuoteSqlName</c>"在这一家尤其要紧：双引号一漏，<c>FastSqlOrder</c> 就变成 <c>fastsqlorder</c>，
/// 建出来的表与查的表不是同一张）。P0 只产出文本与黄金样本比对，<b>不执行</b>。
///
/// 四处与 T-SQL 不同，每处都不是换个关键字：
/// <list type="bullet">
/// <item>默认模式是 <c>public</c> 而不是 <c>dbo</c>。</item>
/// <item>没有 <c>CLUSTERED</c>：这一家的聚簇是建表时的 <c>WITH (fillfactor)</c> 加 <c>CLUSTER</c> 命令，
/// 与主键定义无关，所以主键约束只写 <c>PRIMARY KEY</c>。反过来 <c>FULLTEXT</c> 是真的另一套语法
/// （<c>USING gin (to_tsvector(…))</c>），所以它<b>报错</b>而不是悄悄发一个普通索引。</item>
/// <item>改类型与改可空性是两条语句：<c>ALTER COLUMN … TYPE</c> 不碰 <c>NOT NULL</c>，
/// 所以要独立一句。两侧用 <c> ; </c> 串起来与索引那一段同一个形状 —— 运行时执行器要么按语句拆，
/// 要么走 §9.5 那条"生产默认走脚本"的路子（这一家没声明 <c>MultiStatement</c>，§9.4）。</item>
/// <item>列注释是原生语法：<c>COMMENT ON COLUMN</c>，不需要 <c>sp_addextendedproperty</c> 那种存储过程调用。</item>
/// </list></summary>
public class PostgreSqlCodeFirst(PostgreSqlTypes types) : ICodeFirstDialect
{
    public IdentifierPolicy Identifiers => IdentifierPolicy.PostgreSQL;

    /// <summary>自增写法。<c>GENERATED BY DEFAULT AS IDENTITY</c> 是 SQL 标准那一支，而这一族更早、
    /// 更通用的写法是 <c>SERIAL</c>（§9.1 金仓那一行点名的分岔）。选前者的两条理由：它把序列挂在列上，
    /// 改名与删列不留孤儿序列；<c>BY DEFAULT</c> 允许显式写值，正好补上"没有 <c>IDENTITY_INSERT</c> 开关"那一格。
    /// <b>代价</b>：<c>IDENTITY</c> 要 PG 10+，openGauss 那一档（9.2 内核）不认，覆写点留给它（还没建）。
    /// 【v0.36 第二笔：叶子到场，而这一格裁成<em>不覆写</em>——"9.2 内核不认"是从内核代数推的【推断】，
    /// §9.1 厂商行明列的分岔里没有这一句，按 TiDB／OceanBase 两笔同一判据（文档明写的分岔才配覆写）；
    /// 且"留给它"这条路从来不存在——<c>PostgreSqlProviderBase</c> 构造直 new 本类，三族血统里只有 Oracle
    /// 那一族有 <c>CreateCodeFirst</c> 虚口可挂子类。真库到场第一问仍是这句 CREATE TABLE 收不收（§14）。
    /// 【v0.36 第三笔：第二颗分叉叶子（GaussDB）到场，对这一格重裁仍<em>不覆写</em>——共行的厂商读数
    /// 对两家是同一句，两颗叶子的裁据不分叉；PG 血统今天是一基类三叶子，而这一口的覆写者数还是零、
    /// "从未可达"也没变（§14 行 2044 复点，不新增）。
    /// 【v0.36 第四笔：瀚高叶子到场，"一基类三叶子"改读四叶子，而本口覆写者数照旧零、"从未可达"照旧没变；
    /// 本家带来的新档在裁决问句上：它的厂商行（§9.1 行 907）零方言级点名，那颗 IDENTITY 问题对它
    /// 不是"重裁、不落"而是问都不成立——判据的另一半，全文记行 2044。】
    /// 【v0.37 第二笔：第六颗叶子是 PG 血统的<b>本尊</b>，它对这一格的问法与前五颗都不同——不问"认不认"
    /// （openGauss／GaussDB 那一档）、不问"像到哪一层"（8c 那一档）、也不落进"问都不成立"（瀚高那一档），
    /// 而是问<em>现场那台是几</em>：这一支 SQL 标准写法要 PG 10+，而同一份文本层在
    /// <c>PostgreSqlExpressions</c> 里为 <c>ROUND/CEIL/FLOOR</c> 按"最老的内核"包了 <c>CAST(… AS numeric)</c>
    /// （那是 14 之前的读法），两句朝相反方向指。五叶时两格各由别家兜住、无人需要同时满足，本尊到场后同一台库
    /// 必须同时吃下两句，于是三段区间（&lt;10 语法错 ∶ 10–13 恰合 ∶ ≥14 冗余）第一次算得出来——本仓库自己算的
    /// 【推断】，厂商行里没有这一句。本口的覆写者数照旧零、"从未可达"照旧没变（六颗叶子各验一次）。】</summary>
    protected virtual string IdentityClause => " GENERATED BY DEFAULT AS IDENTITY";

    public void EmitCreateTable(SqlWriter writer, EntityContract contract)
    {
        writer.Append("CREATE TABLE ");
        EmitTable(writer, contract.Table);
        writer.Append(" (");

        var parts = new List<string>(contract.Columns.Length + 1);

        foreach (var column in contract.Columns)
            parts.Add(Definition(column));

        if (contract.PrimaryKey.Length > 0)
        {
            var key = string.Join(", ", contract.PrimaryKey.Select(c => Identifiers.Quote(c.ColumnName)));

            parts.Add($"CONSTRAINT {Identifiers.Quote("PK_" + contract.Table.Name)} PRIMARY KEY ({key})");
        }

        writer.Append(string.Join(", ", parts)).Append(')');

        foreach (var index in contract.Indexes)
        {
            writer.Append(" ; ");
            EmitCreateIndex(writer, contract.Table, index);
        }
    }

    public void EmitAddColumn(SqlWriter writer, TableInfo table, ColumnContract column)
    {
        writer.Append("ALTER TABLE ");
        EmitTable(writer, table);
        writer.Append(" ADD COLUMN ").Append(Definition(column));
    }

    /// <summary>这一家的 <c>ALTER COLUMN … TYPE</c> 不会顺带重置可空性（与 T-SQL 相反，那一家会），
    /// 所以要独立一句把契约声称的那一侧写回去。漏掉它不会报错，只会让"改了精度"顺带改了约束 ——
    /// 而约束是 <c>NOT NULL</c> 时那一句 <c>SET NOT NULL</c> 在有历史 NULL 的行上会失败，
    /// 这失败才是它该出现的地方。</summary>
    public void EmitAlterColumnPrecision(SqlWriter writer, TableInfo table, ColumnContract column)
    {
        var stored = types.ApplyStorageDefaults(column);

        writer.Append("ALTER TABLE ");
        EmitTable(writer, table);
        writer.Append(" ALTER COLUMN ").Append(Identifiers.Quote(column.ColumnName));
        writer.Append(" TYPE ").Append(types.GetStoreType(stored));

        writer.Append(" ; ");

        writer.Append("ALTER TABLE ");
        EmitTable(writer, table);
        writer.Append(" ALTER COLUMN ").Append(Identifiers.Quote(column.ColumnName));
        // 与建表那一句读同一格（NullableInStore），否则"改一次精度"会把值归库给的列改回可空 ——
        // 全站只留一条规则：DDL 里的可空性不读 IsNullable。本家今天没有 true 的 StoreFillsValue，
        // 而自增列的 IsNullable 本来就 false，所以这一处改的是判据、产出文本与改之前逐字相同。
        writer.Append(stored.NullableInStore ? " DROP NOT NULL" : " SET NOT NULL");
    }

    public bool TryEmitColumnComment(SqlWriter writer, TableInfo table, ColumnContract column)
    {
        writer.Append("COMMENT ON COLUMN ");
        EmitTable(writer, table);
        writer.Append('.').Append(Identifiers.Quote(column.ColumnName)).Append(" IS ");
        writer.AppendStringLiteral(column.Comment ?? string.Empty, unicode: false);

        return true;
    }

    public void EmitCreateIndex(SqlWriter writer, TableInfo table, IndexContract index)
    {
        // 聚簇在这一家不是索引的一种而是一条命令（CLUSTER），所以 NonClustered/Clustered 都落成普通索引；
        // 而全文检索要的是另一个访问方法 + 一个表达式，悄悄发成 btree 索引会建出一个查不了全文的索引。
        if (index.Kind == IndexKind.FullText)
            throw new FastSqlException($"PG 系不支持 CREATE INDEX … FULLTEXT 这种写法，全文索引要 USING gin (to_tsvector(…))，尚未接线（§9.2）");

        writer.Append(index.Kind == IndexKind.Unique ? "CREATE UNIQUE INDEX " : "CREATE INDEX ");
        writer.Append(Identifiers.Quote(index.Name)).Append(" ON ");
        EmitTable(writer, table);
        writer.Append(" (");

        for (var i = 0; i < index.ColumnNames.Length; i++)
        {
            if (i > 0)
                writer.Append(',');

            writer.Append(' ').Append(Identifiers.Quote(index.ColumnNames[i]));
            writer.Append(index.Descending ? " DESC" : " ASC");
        }

        writer.Append(" )");
    }

    string Definition(ColumnContract column)
    {
        var writer = new SqlWriter(new(), [], '@');

        EmitColumnDefinition(writer, column);

        return writer.ToString();
    }

    void EmitColumnDefinition(SqlWriter writer, ColumnContract column)
    {
        var stored = types.ApplyStorageDefaults(column);

        writer.Append(Identifiers.Quote(column.ColumnName)).Append(' ').Append(types.GetStoreType(stored));

        if (column.IsIdentity)
            writer.Append(IdentityClause);

        // 主键列上的 NOT NULL 由表级 PRIMARY KEY 保证，但契约说它非空就得写：
        // 没有主键的表（§13.11 那张 AuditRow）走不到约束那一段，漏写就得到一个可空列。
        // 可空性读 NullableInStore：本家没有"库自己给值且永不为空"的那一型（StoreFillsValue 无人为 true），
        // 所以这一格今天与 IsNullable 同值，改的是<em>读的哪一格</em> —— 五族同一句形状，才不需要一家一份解释。
        writer.Append(stored.NullableInStore ? " NULL" : " NOT NULL");
    }

    void EmitTable(SqlWriter writer, TableInfo table)
    {
        writer.Append(Identifiers.Quote(table.Schema ?? "public")).Append('.');
        writer.Append(Identifiers.Quote(table.Name));
    }
}
