using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace FastSql.Generators;

/// <summary>把 <see cref="EntityModel"/> 排成 C# 文本。这里不做任何判定——判定在
/// <see cref="EntityFactsBuilder"/>，收尾在运行期的 <c>EntityContractFactory</c>。</summary>
static class EntityFactsWriter
{
    const string Metadata = "global::FastSql.Metadata.";
    const string Schema = "global::FastSql.Schema.";
    const string Reader = "global::System.Data.Common.DbDataReader";
    const string Plan = "global::FastSql.Schema.ReadPlan";
    const string Converter = "global::FastSql.Materialization.ValueConverter";
    const string Direct = "global::FastSql.Materialization.DirectRead.";
    const string Failures = "global::System.Collections.Generic.List<global::FastSql.ValidationFailure>";

    public static string Render(EntityModel model)
    {
        var b = new StringBuilder();

        b.AppendLine("// <auto-generated/>")
         .AppendLine("// 由 FastSql.Generators 生成（§12.7 A 的 G1 级）。手改会被下一次生成覆盖。")
         .AppendLine("// 列序 = 契约列序（§10.3）：按实体里的声明顺序写入，不按名字排序。")
         .AppendLine("#nullable enable")
         .AppendLine();

        if (model.Namespace.Length > 0)
            b.AppendLine("namespace " + model.Namespace + ";").AppendLine();

        RenderSchema(b, model);
        b.AppendLine();
        RenderValidator(b, model);
        b.AppendLine();
        RenderFacts(b, model);

        return b.ToString();
    }

    static void RenderSchema(StringBuilder b, EntityModel m)
    {
        var type = m.Entity;

        b.AppendLine("/// <summary>实体的物化与读写器：属性直读直写，没有 PropertyInfo、没有表达式树、")
         .AppendLine("/// 也没有「委托数组按下标取」那一层间接（§12.7 A）。读取按票走：有臂的列不进装箱口（§16.21）。</summary>")
         .AppendLine("sealed class " + m.Name + "Schema : " + Schema + "IEntityTypeSchema<" + type + ">, " + Schema + "IBoxedEntityTypeSchema")
         .AppendLine("{")
         .AppendLine("    readonly " + Metadata + "EntityContract _contract;")
         .AppendLine("    readonly global::System.Func<" + Reader + ", " + Plan + ", " + type + "> _reader;")
         .AppendLine("    readonly global::System.Func<" + Reader + ", " + Plan + ", object> _boxed;")
         .AppendLine()
         .AppendLine("    public " + m.Name + "Schema(" + Metadata + "EntityContract contract)")
         .AppendLine("    {")
         .AppendLine("        _contract = contract;")
         .AppendLine("        _reader = FromRow;")
         .AppendLine("        _boxed = (reader, plan) => FromRow(reader, plan);")
         .AppendLine("    }")
         .AppendLine()
         .AppendLine("    public " + Metadata + "EntityContract Contract => _contract;")
         .AppendLine()
         .AppendLine("    public " + type + " New() => new " + type + "();")
         .AppendLine()
         .AppendLine("    public object? GetValue(" + type + " entity, int ordinal) => ordinal switch")
         .AppendLine("    {");

        for (var i = 0; i < m.Columns.Count; i++)
            b.AppendLine("        " + i + " => entity." + m.Columns[i].Member + ",");

        b.AppendLine("        _ => throw OutOfRange(ordinal),")
         .AppendLine("    };")
         .AppendLine()
         .AppendLine("    public void SetValue(" + type + " entity, int ordinal, object? value)")
         .AppendLine("    {")
         .AppendLine("        switch (ordinal)")
         .AppendLine("        {");

        for (var i = 0; i < m.Columns.Count; i++)
            b.AppendLine("            case " + i + ": entity." + m.Columns[i].Member + " = " + Converter + ".To<" + m.Columns[i].ClrType + ">(value); break;");

        b.AppendLine("            default: throw OutOfRange(ordinal);")
         .AppendLine("        }")
         .AppendLine("    }")
         .AppendLine()
         .AppendLine("    public " + type + " Read(" + Reader + " reader, " + Plan + " plan) => FromRow(reader, plan);")
         .AppendLine()
         .AppendLine("    public global::System.Func<" + Reader + ", " + Plan + ", " + type + "> Reader => _reader;")
         .AppendLine()
         .AppendLine("    global::System.Func<" + Reader + ", " + Plan + ", object> " + Schema + "IBoxedEntityTypeSchema.BoxedReader => _boxed;")
         .AppendLine()
         .AppendLine("    " + type + " FromRow(" + Reader + " reader, " + Plan + " plan)")
         .AppendLine("    {");

        // 序号是"起点 + 列位"这一个加法（票上只有起点与档位，§16.21），先各拷一颗局部：下面每一列都要用一次，
        // 而 plan.Offset + i 那种写法每格多一次属性取用。整表没有一列有臂时不写 ops 那颗局部，
        // 免得生成的文件里留一个没人读的局部。
        b.AppendLine("        var from = plan.Offset;");

        if (m.Columns.Any(c => c.DirectArm is not null))
            b.AppendLine("        var ops = plan.Ops;");

        b.AppendLine("        var entity = new " + type + "();")
         .AppendLine();

        for (var i = 0; i < m.Columns.Count; i++)
        {
            var column = m.Columns[i];

            b.AppendLine(column.DirectArm is { } arm
                ? "        entity." + column.Member + " = " + Direct + arm + "(reader, from + " + i + ", ops[" + i + "]);"
                : "        entity." + column.Member + " = " + Converter + ".Read<" + column.ClrType + ">(reader, from + " + i + ");");
        }

        b.AppendLine()
         .AppendLine("        return entity;")
         .AppendLine("    }")
         .AppendLine()
         .AppendLine("    static global::FastSql.FastSqlException OutOfRange(int ordinal) => new($\"列序 {ordinal} 不在 0.." + (m.Columns.Count - 1) + " 内（契约列数 " + m.Columns.Count + "）\");")
         .AppendLine("}");
    }

    static void RenderValidator(StringBuilder b, EntityModel m)
    {
        var type = m.Entity;

        b.AppendLine("/// <summary>契约档校验器（§10.6 的 ContractOnly）：尺子全部来自 ColumnContract，")
         .AppendLine("/// 取值直接走属性、不装箱。再往上一档要读注解实例，那是运行期的东西，由 G2 承担。</summary>")
         .AppendLine("sealed class " + m.Name + "Validator : " + Schema + "IEntityValidator<" + type + ">, " + Schema + "IBoxedEntityValidator")
         .AppendLine("{")
         .AppendLine("    readonly " + Metadata + "EntityContract _contract;")
         .AppendLine()
         .AppendLine("    public " + m.Name + "Validator(" + Metadata + "EntityContract contract) => _contract = contract;")
         .AppendLine()
         .AppendLine("    public " + Schema + "ValidationMode Mode => " + Schema + "ValidationMode.ContractOnly;")
         .AppendLine()
         .AppendLine("    public bool TryValidate(" + type + " entity, " + Failures + " failures)")
         .AppendLine("    {")
         .AppendLine("        var before = failures.Count;")
         .AppendLine("        var columns = _contract.Columns;")
         .AppendLine();

        for (var i = 0; i < m.Columns.Count; i++)
        {
            var column = m.Columns[i];

            // 与 ReflectionEntityValidator 同一组判定、同一个消息出口（ContractRules）。
            // 非空值类型装箱后不可能是 null，所以那条必填检查在这一列上是死代码，不写。
            if (!column.IsNullable && column.CanBeNull)
                b.AppendLine("        if (entity." + column.Member + " is null) " + Metadata + "ContractRules.Required(columns[" + i + "], failures);")
                 .AppendLine();

            if (column.IsString)
                b.AppendLine("        if (entity." + column.Member + " is { } text" + i + ") " + Metadata + "ContractRules.Length(columns[" + i + "], text" + i + ", failures);")
                 .AppendLine();
        }

        b.AppendLine("        return failures.Count == before;")
         .AppendLine("    }")
         .AppendLine()
         .AppendLine("    void " + Schema + "IBoxedEntityValidator.Validate(object entity, " + Failures + " failures)")
         .AppendLine("        => TryValidate((" + type + ")entity, failures);")
         .AppendLine("}");
    }

    static void RenderFacts(StringBuilder b, EntityModel m)
    {
        b.AppendLine("/// <summary>编译期算好的实体事实。provider 那一半（storage defaults、自增约定、索引与外键的列名换算）")
         .AppendLine("/// 由运行期的 EntityContractFactory 补上——只有 provider 知道自己是 nvarchar 还是 VARCHAR2(n BYTE)（§10.4）。</summary>")
         .AppendLine("static class " + m.Name + "Metadata")
         .AppendLine("{")
         .AppendLine("    public static " + Schema + "GeneratedEntityMetadata Facts { get; } = new(")
         .AppendLine("        typeof(" + m.Entity + "),")
         .AppendLine("        new " + Metadata + "TableInfo(" + Lit(m.TableSchema) + ", " + Lit(m.TableName) + "),")
         .AppendLine("        [");

        foreach (var column in m.Columns)
        {
            b.AppendLine("            new " + Metadata + "ColumnFacts")
             .AppendLine("            {")
             .AppendLine("                MemberName = " + Lit(column.Member) + ",")
             .AppendLine("                ClrType = typeof(" + column.ClrType + "),")
             .AppendLine("                ColumnName = " + Lit(column.ColumnName) + ",")
             .AppendLine("                ColumnNameLayer = " + Metadata + "MetadataLayer." + column.ColumnNameLayer + ",")
             .AppendLine("                ColumnNameNote = " + Lit(column.ColumnNameNote) + ",")
             .AppendLine("                MaxChars = " + Num(column.MaxChars) + ",")
             .AppendLine("                LengthNote = " + Lit(column.LengthNote) + ",")
             .AppendLine("                IsNullable = " + Bool(column.IsNullable) + ",")
             .AppendLine("                NullableNote = " + Lit(column.NullableNote) + ",")
             .AppendLine("                IsPrimary = " + Bool(column.IsPrimary) + ",")
             .AppendLine("                DeclaredIdentity = " + Bool(column.DeclaredIdentity) + ",")
             .AppendLine("                Precision = " + Num(column.Precision) + ",")
             .AppendLine("                Scale = " + Num(column.Scale) + ",")
             .AppendLine("                StoreTypeName = " + Lit(column.StoreType) + ",")
             .AppendLine("                Comment = " + Lit(column.Comment) + ",")
             .AppendLine("                IsConcurrencyToken = " + Bool(column.IsConcurrencyToken) + ",")
             .AppendLine("                ConcurrencyNote = " + Lit(column.ConcurrencyNote) + ",")
             .AppendLine("            },");
        }

        b.AppendLine("        ],")
         .AppendLine("        [");

        foreach (var index in m.Indexes)
            b.AppendLine("            new " + Metadata + "IndexFacts(" + Lit(index.Name) + ", [" + string.Join(", ", index.Members.Select(Lit)) + "], " + Bool(index.Unique) + ", " + Bool(index.Clustered) + ", " + Bool(index.Descending) + "),");

        b.AppendLine("        ],")
         .AppendLine("        [");

        // 只抄声明：外键成员名 → 列名的换算在运行期的 EntityContractFactory，与索引同一份。
        foreach (var relationship in m.Relationships)
            b.AppendLine("            new " + Metadata + "RelationshipFacts")
             .AppendLine("            {")
             .AppendLine("                MemberName = " + Lit(relationship.Member) + ",")
             .AppendLine("                TargetType = typeof(" + relationship.TargetType + "),")
             .AppendLine("                ForeignKeyMembers = [" + string.Join(", ", relationship.Members.Select(Lit)) + "],")
             .AppendLine("                Layer = " + Metadata + "MetadataLayer." + relationship.Layer + ",")
             .AppendLine("                Note = " + Lit(relationship.Note) + ",")
             .AppendLine("            },");

        b.AppendLine("        ],")
         .AppendLine("        contract => new " + m.Name + "Schema(contract),")
         .AppendLine("        contract => new " + m.Name + "Validator(contract));")
         .AppendLine("}");
    }

    /// <summary>整个程序集共用的取数口。展开成一串引用相等比较而不是字典：
    /// §12.8 的「G1 路径 0 字典查找」要的正是这个形状，实体再多也该先量过再换。</summary>
    public static string RenderLookup(IReadOnlyList<EntityModel> models)
    {
        var b = new StringBuilder();

        b.AppendLine("// <auto-generated/>")
         .AppendLine("// 由 FastSql.Generators 生成（§12.7 A 的 G1 级）。手改会被下一次生成覆盖。")
         .AppendLine("#nullable enable")
         .AppendLine("namespace FastSql.Generated;")
         .AppendLine()
         .AppendLine("/// <summary>本程序集里被标注过的实体的 G1 取数口。把它交给 GeneratedEntitySchemaRegistry")
         .AppendLine("/// 就接入 G1；返回 false 的实体（未标注、有基类、被 Fluent 配置过）走 G2 反射解析（§12.7）。</summary>")
         .AppendLine("public static class FastSqlGeneratedMetadata")
         .AppendLine("{")
         .AppendLine("    public static bool TryGet(global::System.Type clrType, out " + Schema + "GeneratedEntityMetadata? metadata)")
         .AppendLine("    {");

        foreach (var model in models)
        {
            b.AppendLine("        if (clrType == typeof(" + model.Entity + "))")
             .AppendLine("        {")
             .AppendLine("            metadata = global::" + (model.Namespace.Length > 0 ? model.Namespace + "." : "") + model.Name + "Metadata.Facts;")
             .AppendLine("            return true;")
             .AppendLine("        }")
             .AppendLine();
        }

        b.AppendLine("        metadata = null;")
         .AppendLine("        return false;")
         .AppendLine("    }")
         .AppendLine("}");

        return b.ToString();
    }

    static string Lit(string? value) => value is null ? "null" : SymbolDisplay.FormatLiteral(value, quote: true);

    static string Num(int? value) => value?.ToString() ?? "null";

    static string Bool(bool? value) => value?.ToString().ToLowerInvariant() ?? "null";
}
