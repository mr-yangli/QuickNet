using QuickSql.Metadata;
using QuickSql.Providers;
using QuickSql.Sql;

namespace QuickSql.Providers.Xugu;

/// <summary>虚谷的主键策略（§4 的 IKeyStrategy，第五家）。<b>这是这一版最需要被读清楚的一格</b>，
/// 因为它是四家分布从 <c>2 真 ∶ 2 抛</c> 变成 <c>3 真 ∶ 2 抛</c> 的那一票，而三档出处各说一半：
/// <b>【v0.34 真库改判：那一票收回，分布回到 <c>2 真 ∶ 3 抛</c>，而这一家多出一位带真库见证的
/// <see cref="SupportsPostStatementKeyRead"/>。下面整段是 v0.31 立这一格时的原文与理由，照录不删；
/// 它被推翻的是"取 RETURNING 那一边"这一个选择，推翻它的证据（N-06/N-07 两形全空）与逐格账
/// 写在 <see cref="SupportsBulkKeyRetrieval"/> 上。】</b>
/// <list type="bullet">
/// <item>【文档·支持到某个形状】厂商那一页写的是 <c>INSERT … RETURNING &lt;列&gt; [BULK COLLECT] [INTO :变量]</c>
/// —— <c>RETURNING</c> 这一族<em>有</em>，而且是三张写语句都能带。但请注意那半颗 <c>INTO</c>：
/// 那一页的示例全都在 PL/SQL 块里，把结果集<em>绑进宿主变量</em>，而不是当结果集发给客户端。</item>
/// <item>【产物·支持】一家已发布的适配器为这一家发的语句里逐字带着 <c> RETURNING </c> 那一段
/// （它的 <c>MERGE INTO</c> 与 <c>limit … offset … returning</c> 也在同一份产物里）—— 这一条是"shipped 代码
/// 把它当结果集发过"，比文档那一页更接近 <see cref="EmitReturning"/> 所假设的那件事。</item>
/// <item>【产物·反对】同一家库的<em>另一份</em>适配器压根不走这条路：发完 <c>INSERT</c> 之后追一句
/// <c>;SELECT LAST_INSERT_ID();</c>（MySQL 血统那一族的写法，一次只回一颗），而它<em>回填</em>的那一段
/// 取的是第三条路 —— 重新 <c>SELECT</c> 一次刚插入的行、按 <c>"ROWID"</c> 限定。
/// 三档里最硬的一档（可运行的代码）因此指向的是<b>"语句之后回读"</b>，而不是 <c>RETURNING</c>。</item>
/// </list>
/// 于是这一格的真实状态不是"这一家有 RETURNING"，而是<b>"有 RETURNING 的语法，而两份独立实现里只有一份
/// 把它当成发给客户端的结果集用；另一份走的是语句后回读"</b>。这里取前者，三条理由按可核性排：
/// 其一，它是 SPI <em>表达得出</em>的那一条 —— 后一条路要"语句之后回读"那一颗口子，
/// 而 <see cref="IKeyStrategy"/> 今天没有（§14 那一格，Oracle 血统与 MySQL 血统两家已经卡在这里，
/// 这一家若走那条路是<b>第三家</b>，且这一家给的理由最具体：已发布实现真的这么发了）；
/// 其二，它与 T-SQL、金仓两族同形，三家的 <c>Returning</c> 都是"跟着语句一起发、当结果集读回"，
/// 而共用的 <c>InsertEngine</c> 只有这一种消费方式；其三，选错的方向是<em>可数的</em>：
/// <see cref="SupportsBulkKeyRetrieval"/> 若为真而库里实际不支持，红在"这一句直接被库驳回"，
/// 而不是红在"回填悄悄少几行"。
///
/// <para><b>但第三理由只在单行插入上成立，这一格要写的欠账正是那一半</b>：<c>InsertEngine</c> 在
/// <see cref="SupportsBulkKeyRetrieval"/> 为真时走 L3 多值语句（一条 <c>INSERT</c> 带 N 行 <c>VALUES</c>）
/// 并要求一次拿回 N 颗键。多行 <c>VALUES … RETURNING</c> 在这一家回几行【没有任何一份产物能证】——
/// 支持它的那份产物只在逐条路径上带 <c>RETURNING</c>，而文档那一页给出的批量形是
/// <c>BULK COLLECT INTO</c>（绑定输出，不是结果集）。
/// 更要紧的是第二颗：<b>没有 <c>INTO</c> 的那一形（我们发的就是这一形）在两档出处里都没出现过</b>，
/// 它是从"这份适配器这么发而且 shipped 了"推出来的。两格一起记进 §14，与"MySQL 血统那一家多行插入的
/// id 连续性"并排读：那一条是"回读机制在但只回一颗"，这一条是"结果集那一形只有一份产物用过、且批量从没被用过"。
/// <b>两者都不是"已适配"</b>。</para>
///
/// <para><see cref="SupportsExplicitIdentityInsert"/> 取 false，与金仓、Oracle、MySQL 三家同一条路：
/// 这一家的自增写法是 <c>IDENTITY(1,1)</c>【产物】，而产物里<em>没有</em> <c>SET IDENTITY_INSERT</c> 那一类
/// 会话开关（写值即覆盖 = <c>GENERATED BY DEFAULT</c> 的语义）。刻意不为它留覆写点：<see cref="IdentityInsertToggle"/>
/// 在 Core 里至今没有任何调用点（第三家已经把它记成 §14 的一格），覆写它会得到一颗永远不被调用的虚函数。</para></summary>
public sealed class XuguKeys : IKeyStrategy
{
    /// <summary><b>【v0.34 真库改判】true → false</b>。上一版这里取 true 的理由（三档出处、"红在被库驳回
    /// 而不是红在悄悄少几行"的方向性判断）逐字保留在下面 —— 它错在第三档：实测不是"被驳回"而是
    /// <b>"执行成功、行进去了、回包 FIELDS=0 ROWS=0"</b>（<c>obj/logs/v32-recon-keys-1.log</c> 的 N-06 单行
    /// 与 N-07 多行，两形全空），比"红在被驳回"更险的正是这种"绿着交出 0"。那颗 <c>ReadBackAsync</c>
    /// 的 0/N 行数判（v0.32 补的）把这件事钉成了当场红，而本版把形状改对：批量位假了就是假了，
    /// 退到 L5 逐条，键走 <see cref="SupportsPostStatementKeyRead"/> 那条<b>有真库见证</b>的路
    /// （同一份日志 N-09 交 <c>Int64</c>；<c>v32-recon-txn-3.log</c> 的 T-03 把"INSERT … ; SELECT LAST_INSERT_ID()"
    /// 这种多语句批在这一家跑通过、T-04 证它答的就是本会话刚插的那一颗、T-01/T-02 证事务里同样成立）。
    /// 原注释（v0.31 立，摘录）："这一格取前者（RETURNING 当结果集发），三条理由按可核性排……
    /// 选错的方向是可数的：SupportsBulkKeyRetrieval 若为真而库里实际不支持，红在'这一句直接被库驳回'"——
    /// 三条理由里前两条仍然成立（后一条路当时确实无处落），第三条的<b>预测</b>被实测换掉了：
    /// 红不在驳回，在空结果集。今天这一格走的就是当初"第三条理由"指向的那条后路。</summary>
    public bool SupportsBulkKeyRetrieval => false;

    /// <summary>取 true 而且<b>是六格里唯一带真库出处的一位</b>：回读句 <c>SELECT LAST_INSERT_ID()</c>
    /// 与多语句批的接收形状都在虚谷活库上量过（出处逐格见 <see cref="SupportsBulkKeyRetrieval"/> 注释）。
    /// 覆盖面仍窄：单颗自增列、逐条形（每块一行）、同命令同会话 —— 带并发列的回填撞不出去，
    /// 那一格红在 <c>EmitReturning</c> 的 <c>RETURNING</c> 交空结果集上，与 <c>SELECT "VERSION"</c>
    /// 的 <c>DataOutOfBindException</c>（<c>v32-recon-mat-4.log</c> A-06c）一起记在并发那颗契约格里。</summary>
    public bool SupportsPostStatementKeyRead => true;

    /// <summary>发 <c>SELECT LAST_INSERT_ID()</c> —— 与夹具裁判 <c>Database.InsertId</c> 在虚谷上跑通的是
    /// 同一颗函数、同一种多语句批形状（那一条是裸 ADO 独立裁判，这一条是被测产出，两边各走各路）。
    /// 不带参数、不引列名；前面的 <c>;</c> 与空格由 Core 补。</summary>
    public void EmitPostStatementKeyRead(SqlWriter writer, ColumnContract key) => writer.Append("SELECT LAST_INSERT_ID()");

    public bool SupportsExplicitIdentityInsert => false;

    /// <summary>【产物】：<c>RETURNING</c> 落在<em>语句末尾</em>，与金仓那一族同一位置（所以
    /// <see cref="DialectBase.ReturningPrecedesValues"/> 在这一家保持 false，与 T-SQL 的 <c>OUTPUT</c> 分岔）。
    /// 这里发的是<em>裸</em> <c>RETURNING &lt;列&gt;</c>，不带文档那一页示范的 <c>INTO :变量</c> ——
    /// 那一形要的是 OUT 绑定，而 <c>AdoParameter</c> 没有方向位（类注释末段第一颗，与 Oracle 血统同一格缺口）。
    /// 调用方负责自己那侧的空格（<c>DialectBase</c> 在 <c>VALUES</c> 与整句末尾各补一次 —— 少一个就得到
    /// <c>…WHERE :p0 = 1RETURNING "Id"</c>，那一格是第二个方言族接出来才现形的）。
    /// 列名过 <see cref="IdentifierPolicy.Xugu"/> 而不是硬编码双引号：折叠与引号由策略给，
    /// 所以回填清单与建表清单不可能写出两个字形（§9.2 那条"共用一份实现"在这一格上是同一件事）。</summary>
    public void EmitReturning(SqlWriter writer, IReadOnlyList<ColumnContract> returning)
    {
        writer.Append("RETURNING ");

        for (var i = 0; i < returning.Count; i++)
        {
            if (i > 0)
                writer.Append(", ");

            writer.AppendIdentifier(IdentifierPolicy.Xugu, returning[i].ColumnName);
        }
    }

    /// <summary>没有开关，而且这一口刻意不是 <c>virtual</c>（理由见类注释末段：Core 今天没有调用点）。
    /// 返回 null 让 Core 走"这条语句不需要前置/后置语句"那一支，与金仓、Oracle、MySQL 三族同一条路。</summary>
    public string? IdentityInsertToggle(SqlWriter writer, TableInfo table, bool on) => null;
}
