/// <summary>openGauss 的驱动槽位（§9.1 的 openGauss/GaussDB 那一行，PG 血统的第二颗叶子、分叉库第一颗）。
///
/// <para><b>零覆写</b>：产出自本类的每一颗字节都出自 <c>PostgreSqlProviderBase</c> 那一份文本层，
