/// <para><b>本家唯一一颗被点名过的方言分岔，对完裁决是"不落"</b>：自增写法。血统那一份发
/// <c>GENERATED BY DEFAULT AS IDENTITY</c>，而 <c>PostgreSqlCodeFirst</c> 的类注释自己写着
/// "IDENTITY 要 PG 10+，openGauss 那一档（9.2 内核）不认，覆写点留给它（还没建）"。逐层对完：
/// §9.1 厂商行明列的分岔是 <c>QuickSqlDrivers.json</c> 那一族语法（RETURNING 受限、ON CONFLICT 列约束
/// 差异、无 MERGE 直到 5.x），<em>没有</em>"IDENTITY 不认"这一句 —— 那颗"不认"是从内核代数
/// （PG 9.2 一线）推出来的【推断】，不是厂商文档读出来的。按 TiDB/OceanBase 两笔同一判据
/// （文档明写的分岔才配覆写，推断的分岔不改文本），本类对 <c>IdentityClause</c> 一个字都不覆写，
/// 而这一格【推断】连同它的证伪路径记 §14 与本行，真库到场第一问就是它。
/// 另有一格结构事实比裁决更硬，本笔读出：即使要覆写也<b>无从下手</b> ——
/// <c>PostgreSqlProviderBase</c> 构造里 <c>CodeFirst = new PostgreSqlCodeFirst(_types)</c> 是硬接线，
/// 三族血统里只有 Oracle 那一族有 <c>CreateCodeFirst</c> 虚口（达梦的 <c>IDENTITY(1,1)</c> 靠它落地），
/// MySQL 与 PG 两族都是直 new。所以"金仓零覆写"里混着一句它从来没有过覆写入口，这句话记进 §14。</para>
///
/// <para><b>真正的分岔在语义层，文本一个字不替它们说话</b>（§9.1 那一行逐条对）：
/// <list type="bullet">
/// <item><c>RETURNING 受限</c>——PG 血统的键回填整族走 <c>INSERT … RETURNING</c>（<c>PostgreSqlKeys</c>），
/// 这一家在哪些列约束下收这一句今天没有任何见证；"受限"的具体形状 §9.1 只给了半句，追问归真实例。</item>
/// <item>分布式 DN 下序列不连续——§12.4"不要拿主键当业务流水号"在这一家与 TiDB 同档成立而更甚【推断】。</item>
/// <item><c>DISTRIBUTED BY</c> 建表分片——本仓库不在契约里表达分片（§5 的取舍），所以这一条分岔
/// 落在"库会不会按你的意图摆数据"那一侧，不改产出。</item>
/// </list></para>
///
/// <para><b>清单那颗 <c>assembly</c> 的名字来路要说准</b>（本笔读数口径，§9.1 行 2045 那格同一族坑）：
/// 指向 <c>Npgsql</c>，取的是 §9.1 金仓行"兼容 Npgsql"与清单金仓行 $comment"现场也可以注 Npgsql"
/// 这两句本仓库已入账的说法。openGauss 厂商自己分发的那份是 Npgsql 的 fork（§9.1 行 904 第四列），
/// 而 fork 的托管程序集名本次没有任何可引的厂商文档读数——与其往清单里塞一颗猜的名字
/// （DmProvider 那一行 $comment 立过的纪律），不如用两条真实存在的路里与血统同源的那一条。
/// 与 mysql/tidb/oceanbase 那三键一 assembly 的读法同构而不对称：那三颗键指向<b>同一族协议</b>的
/// 同一颗驱动，这里指向的是<b>邻家库种</b>那一行的兼容臂，金仓那一行的 primary（Kdbndp）不共享过来。
/// 【v0.36 第三笔：本段那颗"不对称"从一次记例长成了 PG 血统的系统形状——gaussdb 这颗键落在本行隔壁，
/// 填的还是同一颗 Npgsql，"两颗键共享兼容臂"照进了"三键一 assembly"的同构侧，而"共享的不是真 primary"
/// 这一句至今没有翻案。】</para>
///
/// <para><b>"已适配"三句在这里的读法</b>（§9.1 (丁)）：本家与金仓、TiDB 同档——驱动从未解析成功过
/// （现场清单那一行从未在场）、覆盖面只有文本层、没有任何一台授权实例（§13.4 三台里没有它，官方镜像
/// 在 §13.1 第 4 项与 openGauss 一起点名过而未起），所以三句里第二句都立不全；今天能说的只有文本层那一句。
/// 与 OceanBase 那家相比本家少一层悬空：这里没有"先问模式"的前件，
/// <c>DbKind.OpenGauss</c> 赌的是血统按 PG 假设说话，而这一赌注与金仓那颗是同一颗。</para></summary>
