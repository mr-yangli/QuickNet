/// "leaf == kingbase leaf == blood" 三段逐字相等链。这一根缝接得住第二颗叶子这件事在金仓（v0.22）
/// 已经证过，本类带来的<em>不是</em>同一个证明的复件，而是 MySQL 血统那两笔（TiDB v0.35 第三笔、
/// OceanBase v0.35 第四笔）在同一仓库里立起的判据"叶子到场 ≠ 覆写到场"在 <b>PG 侧的第一次适用</b>。</para>
