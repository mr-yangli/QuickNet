using System.Text;
using QuickSql.Metadata;
using QuickSql.Providers;
using QuickSql.Sql;

namespace QuickSql.Providers.MySqlBase;

/// <summary>MySQL 血统的主键策略（§4 的 IKeyStrategy，第四家）。<b>第二份把"批量回读主键"答成"没有"的
/// provider</b>，而它缺的东西与第三家不是同一件，这一格值得单独写清：
/// <list type="bullet">
/// <item>这一家没有 <c>RETURNING</c>（<b>MariaDB 10.5 起有</b>，而那是分支不是主干 —— 所以它是这一族将来
/// 第一颗真有覆写者的叶子，形状与达梦那颗 <c>IDENTITY(1,1)</c> 对称）。</item>
/// <item>但它<em>有</em>第三家那条"另一条路"：<c>SELECT LAST_INSERT_ID()</c> 是语句后回读，而且厂商语义明确 ——
/// 它给的是<em>最近一条 <c>INSERT</c> 产生的第一个</em>自增值，多行 <c>VALUES</c> 时其余各值可由
/// "连续递增"推出。也就是说 Oracle 那一档缺的是"两个口子都没有"，这一家缺的只是
/// <see cref="IKeyStrategy"/> 上<em>第二个口子</em>（语句之后回读）没有建模。</item>
/// <item>而"由连续性推出"这一半在两个条件下不成立：<c>innodb_autoinc_lock_mode = 2</c>（interleaved，
/// 批量插入的 id 允许不连续）与主键冲突/忽略行。这两件事都不是 provider 单方能判的，
/// 所以这里不接一个"看起来能用"的回读，等 §14 那一格连同锁模式一起建模。</item>
/// </list>
/// 于是 §12.4 第 1 项那句"L3 → L5：没有批量 RETURNING 的库要回填就退到逐条"在这一家同样只走完一半 ——
/// 逐条是必要的，不充分：逐条之后仍然没有一个地方接住那一颗键。Core 的降级分支照发 <c>Returning</c>，
/// 所以它在这里红，而不是悄悄发出回填不上的 SQL。
///
/// <para><b>【v0.34 改判】上面那段"仍然没有一个地方接住"从今天起作废</b>：SPI 长出了
/// <see cref="SupportsPostStatementKeyRead"/> 那一档，这一家接上 <c>SELECT LAST_INSERT_ID()</c>，
/// 键逐块（单行）回读。<b>原话不删</b>，因为它是 v0.30 立这一格时的真实状态。当年"不接一个看起来能用的
/// 回读"留的两个条件今天都齐了：口子有了形状；锁模式那一格被"每块单行 + 同一条命令"的建模绕开 ——
/// 连续性推断根本不需要发生，而不是发生但可疑。<b>欠的那一半要说清：这一家没有授权真库（§13.4），
/// 这一位的全部凭据是离线文本 + 厂商文档，"已接上"不等于"已实测"。</b></para>
///
/// <para><see cref="SupportsExplicitIdentityInsert"/> 取 false 的理由与另两家不同：这一家没有 <c>SET IDENTITY_INSERT</c>
/// 这种会话开关，而 <c>AUTO_INCREMENT</c> 列<em>本来就允许</em>显式写值（写了就不占序列），
/// 那是 <c>GENERATED BY DEFAULT</c> 的语义而不是"开关"的语义 —— 与金仓那一族同一条路，返回 null 让 Core 走
/// "没有开关"那一支。<see cref="IdentityInsertToggle"/> 同样不为它留覆写点：那一口在 Core 里至今
/// <b>没有任何调用点</b>（第三家已经把它记成 §14 的一格），覆写它会得到一颗永远不被调用的虚函数。
/// <b>【v0.31】那句"另两家"今天是"另三家"</b>：第五家也落在 <c>false</c> 这一边
/// （<c>grep -rn "SupportsExplicitIdentityInsert =>" src/QuickSql.Providers* | grep -v "///"</c> 五处，
/// 只有 <c>SqlServerKeys</c> 那处是 true），而三家的理由各不同一条 —— 金仓是"没有那一档"、
/// Oracle 血统是"写值即覆盖，不需要开关"、这一家与它是同一形而<em>不同来路</em>（那句 <c>GENERATED BY DEFAULT</c>
/// 在这一家叫 <c>AUTO_INCREMENT</c>）、第五家是"连开关的语法都没读到"。位数涨了而 Core 那条
/// "没有任何调用点"的原地不动。</para></summary>
public sealed class MySqlKeys : IKeyStrategy
{
    public bool SupportsBulkKeyRetrieval => false;

    public bool SupportsExplicitIdentityInsert => false;

    /// <summary>抛，而不是发一条"看着像在回填"的语句。调用方是 <see cref="MySqlDialect"/> 的
    /// <see cref="DialectBase.EmitReturning"/> 那一口（与金仓那一族同一个转交形状），
    /// 所以 INSERT 与 UPDATE 两档共用这一条文案。
    /// <b>【v0.34 起这一句在 INSERT 档已经走不到】</b>：单颗自增列的回填改走
    /// <see cref="SupportsPostStatementKeyRead"/> 那条真路；今天还撞到它的是带并发列的回填档与
    /// 多颗自增列 —— 两种都不是 <c>LAST_INSERT_ID()</c> 一次问得出的东西。
    /// <b>刻意不是 <c>virtual</c></b>：要让这一口成立，得换整颗策略对象（"某家 MySQL 血统库带了 <c>RETURNING</c>"
    /// 那种叶子 —— 例如本仓库已裁定不立的 MariaDB），那是在叶子 provider 里整颗换 <c>IKeyStrategy</c>，
    /// 不是在这里留一颗没人覆写的虚函数能解决的。</summary>
    public void EmitReturning(SqlWriter writer, IReadOnlyList<ColumnContract> returning)
        => throw new QuickSqlException($"MySQL 系没有可作为结果集发出的 OUTPUT/RETURNING，而本次请求要回填（{Columns(returning)}）。"
            + "单颗自增键的回填今天走语句后回读（每块逐条 + SELECT LAST_INSERT_ID()，v0.34 的口子）；"
            + "撞到这里的是回读句给不齐的形状：带并发列的回填、多颗自增列。多行 VALUES 的 id 连续性要连"
            + "innodb_autoinc_lock_mode 一起建模（interleaved 与冲突行都会断它），那一档仍记 §14，不在这里假装能用。"
            + "请自己生成主键（Guid/雪花）并直接用 ExecuteAffrowsAsync。");

    /// <summary><b>v0.34 立的"语句后回读"那一档，这一家是它的第一批客户之一</b>（另一家是虚谷，
    /// 而那一家有真库见证、这一家没有）。取 true 的理由与 <c>LAST_INSERT_ID()</c> 的厂商语义对齐：
    /// 它给的是<em>本会话最近一条 INSERT 产生的第一个</em>自增值 —— 而 Core 在这一档把每块压成
    /// <b>单行</b>语句且回读句接在同一条命令文本里（同会话有保证），于是"多行才需要连续性推断"那一整格
    /// 坑（<c>innodb_autoinc_lock_mode</c> 与冲突行）被形状绕开，不是被忽略。
    /// <b>而这一位的出处要说满：本机没有授权 MySQL 实例（§13.4 三台里没有它），今天全部凭据是
    /// 离线文本 + 厂商文档 —— 这一家不享有虚谷那本真库账。</b></summary>
    public bool SupportsPostStatementKeyRead => true;

    /// <summary>发 <c>SELECT LAST_INSERT_ID()</c>：不带参数、不引列名（那颗键由 Core 落到
    /// 同块唯一一行的实体上），前面的 <c>;</c> 与空格由 Core 补 —— 与 <see cref="EmitReturning"/>
    /// 的空格纪律同一条。</summary>
    public void EmitPostStatementKeyRead(SqlWriter writer, ColumnContract key) => writer.Append("SELECT LAST_INSERT_ID()");

    static string Columns(IReadOnlyList<ColumnContract> returning)
    {
        var names = new StringBuilder(returning.Count * 12);

        for (var i = 0; i < returning.Count; i++)
        {
            if (i > 0)
                names.Append(", ");

            names.Append(returning[i].ColumnName);
        }

        return names.ToString();
    }

    /// <summary>没有开关，而且这一口刻意不是 <c>virtual</c>（理由见类注释末段：Core 今天没有调用点）。
    /// 返回 null 让 Core 走"这条语句不需要前置/后置语句"那一支，与金仓、Oracle 两族同一条路
    /// （【v0.31】那句"两族"今天是三族：<c>IdentityInsertToggle</c> 五家实现里四家交回 <c>null</c>，
    /// 只有 <c>SqlServerKeys</c> 那一家发得出 <c>SET IDENTITY_INSERT … ON/OFF</c>）。</summary>
    public string? IdentityInsertToggle(SqlWriter writer, TableInfo table, bool on) => null;
}
