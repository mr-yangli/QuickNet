using System.Data.Common;
using QuickSql.Providers.OracleBase;

namespace QuickSql.Providers.ShenTong;

/// <summary>神通 Oscar 的驱动槽位（§9.1 行 902 的兑现）：Oracle 血统的第二颗叶子，而它是这一族
/// <b>第一颗"缝开着而没走过去"的壳</b>——今天它一个字都不覆写，连这一族唯一那道 <c>protected virtual</c>
/// 的 <see cref="OracleProviderBase.CreateCodeFirst"/> 也没有继承。
///
/// <para><b>与达梦那格的分别就是本笔的全部新读数</b>：PG 与 MySQL 两族的"零覆写者"都读作"从未有过可覆的路"
/// （三族血统只有这一族留了缝，§14 行 2044），而神通到场把第三档占住——<em>路有、门开、没走</em>。
/// 裁决沿四笔同一判据（文档明写的分岔才配覆写）：本行点名过的分岔只有"CREATE SCHEMA 语义特殊、用户即模式"
/// 两颗，都在发射面之外——本族"契约没写模式就什么都不写"那格恰恰是用户即模式的正常形（裸名解析进连接
/// 所带的那个模式），而本仓库不发 <c>CREATE SCHEMA</c>。IDENTITY 那一问在本家比 PG 两笔更"活着"——缝就是
/// 为它留的，达梦替自己那一半答了 <c>IDENTITY(1,1)</c>——而本行坑列没有它的读数，裁"不覆写"，
/// 产出仍是血统那一句 <c>GENERATED BY DEFAULT AS IDENTITY</c>（§9.1 行 902 与 §14）。</para>
///
/// <para><b>兄弟叶子的第一次异形对读</b>：此前仓库里所有跨叶对读都是恒等（同基类必同形）或只差 Kind 那颗词
/// （拒收文案），而本家与达梦同族<em>不同形</em>——CREATE TABLE 差在恰好缝所 carry 的那一句，其余各链逐字
/// 相同。那一格的可跑证据在 <c>ShenTongDialectTests</c>，"同族两叶各自与基类对"不再等于"两叶彼此对"。</para>
///
/// <para><b>内建表来路</b>：<c>shentong</c> 键的 assembly 写 <c>Oscar</c>——那是一颗文档口径的名字
/// （§9.1 行 902 第四列全文就这一个词），与 <c>Kdbndp</c>、<c>DmProvider</c> 同一处境：从未在一台机器上
/// 解析成功过、刻意不写 <c>factoryType</c>（走"扫第一个 <c>DbProviderFactory</c> 子类"的兜底，理由与达梦行
/// 逐字相同）、整行「未实测」。现场装上真驱动那天先按厂商读数改回，而不是让本行把它读成"已验证"。</para>
///
/// <para><b>"已适配"三句在本家一句都立不起来</b>（与 TiDB／OceanBase／openGauss／GaussDB／瀚高同档，
/// 只有文本层）：① 驱动解析、装载现场未核；② 零条语句在任何一台神通上执行过——而且这一家与另五颗
/// 文本层壳不同，它<em>同族</em>那位（达梦）也没有一台活库；③ 中文从未问过。真实例到场第一问：
/// 这台库认不认 <c>GENERATED BY DEFAULT AS IDENTITY</c>——缝的答案第一次要由第二颗叶子来验，
/// 因为本家没领缝，产的是 Oracle 12c+ 那一形（§14 行 2044 本笔注）。</para></summary>
[QuickSqlProvider(DbKind.ShenTong)]
public sealed class ShenTongProvider : OracleProviderBase
{
    /// <summary>内建表里的 <c>key</c>。assembly 那颗 <c>Oscar</c> 是 §9.1 行 902 第四列的原词，
    /// 从未解析成功过（见类注释第四段），所以内建表不写 <c>factoryType</c>——省略它走兜底扫描，
    /// 比猜一个全名更容易成（达梦行立的纪律，原文照用）。</summary>
    public const string DriverKey = "shentong";

    /// <summary><b>没有覆写</b>——连 <see cref="OracleProviderBase.CreateCodeFirst"/> 都不继承：
    /// 这一族的缝是为 IDENTITY 那颗分岔留的，而神通行对那颗分岔没有任何读数（类注释第一段）。
    /// 懒建与缓存都在基类（<c>_codeFirst ??=</c>），所以本家拿到的 <c>CodeFirst</c> 实例类型
    /// 就是血统自己的 <see cref="OracleCodeFirst"/>，与达梦的 <c>DamengCodeFirst</c> 第一次在
    /// "叶子发的 CodeFirst 类型"这一格上分出两种。</summary>
    public ShenTongProvider(DbProviderFactory driverFactory)
        : base(DbKind.ShenTong, driverFactory)
    {
    }
}
