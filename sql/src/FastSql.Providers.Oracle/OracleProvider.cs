/// 那两个"壳/程序集"的数按 §9.1 census 那一颗口径数（<b>本尊自己也算一层壳</b>），而这一颗口径上一笔
/// 没有对齐过——两读之间的差额与"本笔不裁它"的理由并排记在 <c>PostgreSqlProvider</c> 类注释的
/// 【v0.37 第三笔自纠】那一段，本家不复述。</para>
///
/// <para><b>"有缝而不走"这一档今天有了第二颗，而第二颗的理由与第一颗相反</b>：三族血统里只有这一族留着
/// <see cref="OracleProviderBase.CreateCodeFirst"/> 那道 <c>protected virtual</c>，神通（v0.36 第五笔）是
/// 第一颗到场而选择不走的——它的理由是"§9.1 那一行对 IDENTITY 一个字都没有，所以不赌"。本尊是第二颗，
/// 而它不走缝<em>不需要任何一条理由</em>：缝里那颗默认值 <c>GENERATED BY DEFAULT AS IDENTITY</c> 就是这一家
/// 自己的标准语法，走缝等于改自己的话。于是"文档明写的分岔才配覆写"这条判据在本族有了第三种落点：
/// 神通那一种是<em>没有读数可裁</em>，达梦那一种是<em>有读数而裁落</em>，本尊这一种是<em>默认即本尊，
/// 无事可裁</em>——前两种都是裁给别人的形状，第三种是那句判据第一次遇上"分岔根本不在场"。</para>
///
/// <para><b>上一笔那句"零覆写的正典叶第一次带代价"在本笔有了反例，而反例是本尊这一档自己交的</b>：
/// PG 本尊带代价的成因是它族里两格版本钉朝向相反（<c>IdentityClause</c> 要 PG 10+，那层
/// <c>CAST(… AS numeric)</c> 是 PG 14 之前的读法），于是产出被切成三段区间而"现场是几"必须有答案才判得了对错。
/// 这一族同样有两格版本读数（<c>OracleCodeFirst</c> 类注释末段：标识符上限在 12.1 之前是 30 字节；
/// 那颗 <c>IdentityClause</c> 要 12c 起），而它们<em>同向</em>——分界是同一颗 12.x，所以区间只有两段：
/// <b>&lt; 12.1 那句 IDENTITY 直接语法错而 30 字节上限同时成立，≥ 12.1 两句一起满足</b>【推断，
/// 两个界版本取自本仓库既有读数，分段是本笔自己算的】。本尊落在"两格一起满足"那一侧，所以它零覆写而零代价。
/// 这一格的可跑形状是"两格分界相等"，它在 <c>OracleDialectTests</c> 与 PG 那册同名格并排，两册各钉一个方向。
/// 判据因此要改读一次：<b>正典叶带不带代价，量的不是"它是正典"，是"它族里两格版本读数的朝向"</b>——
/// 上一笔把它写成了正典叶的通例，那一格本笔自纠（<c>MySqlProvider</c> 与 <c>PostgreSqlProvider</c> 两处措辞不动，
/// 因为它们量的仍是各自那一族的实情）。</para>
///
/// <para><b>这颗叶子还作废了一格探针的自辩</b>：<c>DamengDialectTests</c> 里血统基类靠一颗空壳探针
/// （<c>OracleFamilyProbe</c>）实例化，而此前那十颗探针里<em>只有那一颗</em>传的是一颗"有枚举值、
/// 没有 provider"的库种——<see cref="DbKind.Oracle"/>，其余各颗传的都是自家叶子自己的值。
/// 换句话说这一族的"空壳基线"今天一直是由一颗影子本尊量的，而本尊到场之后影子有了本体：
/// 两者今天只剩 CLR 类型名与清单键两颗可分辨的差异，产出的每一个字节都相同，
/// <em>连异常文案都相同</em>（<c>EmitJoinedSources</c> 那句带的是 <c>{Kind}</c>，两侧同为 Oracle）。
/// 所以"叶与基类逐字同形"这一格从今天起由一颗真 provider 守着，探针退为"abstract 基类可实例化"那一格的见证；
/// 那句"没有一种库种叫基类"的自辩（同一处注释）由本笔就地自纠——它字面仍真（枚举里没有一颗叫"基类"），
/// 但它作为"所以只能靠探针"的理由已经不成立了。</para>
///
/// <para><b>清单那颗 <c>assembly</c> 的来路是第四种，也是最薄的一种</b>：填 <c>Oracle.ManagedDataAccess</c>，
/// 而这颗名字在本仓库的出处既不是厂商文档（金仓的 <c>Kdbndp</c>、达梦的 <c>DmProvider</c>、神通的 <c>Oscar</c> 那一档），
/// 也不是邻家的兼容臂（openGauss／GaussDB 那两颗），更不是"血统协议自己实现的驱动"（Npgsql 那五颗），
/// 而是<em>本仓库自家类注释里的一句话</em>——<c>OracleProviderBase</c> 第二段那句"本程序集编译期不认识
/// <c>Oracle.ManagedDataAccess</c>"。它是清单里第一颗"名字的唯一出处在我们自己写的注释里"的键，
/// 而这一档薄到什么程度可以这么读：另三种来路都指向一个库外的权威（厂商、邻家行、协议），本行指向的那份权威
/// 是本页文档。处境照旧：从未解析成功过、刻意不写 <c>factoryType</c>（理由与达梦那一行逐字相同，
