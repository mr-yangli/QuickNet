/// 从 v0.23 起就写着"达梦/Oracle 本尊/人大金仓的那一支 Oracle 模式共享这一份"，三个住户里那一颗本尊
/// 挂了四版的账而没有人来填。所以这是本仓库第一次由一颗叶子<em>兑现自己家族层注释里的前瞻</em>，
/// 而那句前瞻到今天也只兑现一半：同一句里的第三颗住户（金仓的 Oracle 兼容模式）仍然没有对应物，
