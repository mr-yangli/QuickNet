/// 整行「未实测」，本机没有任何一台 Oracle。现场真装上那天第一件事是按厂商读数改回，而不是让本行读成"已验证"。</para>
///
/// <para><b>"已适配"三句在本家一句都立不起来</b>（与同族两颗、PG 六颗、MySQL 三颗同档）：① 驱动解析与装载
