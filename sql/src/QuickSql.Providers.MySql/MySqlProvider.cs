using System.Data.Common;
using QuickSql.Providers.MySqlBase;

namespace QuickSql.Providers.MySql;

/// <summary>MySQL 本尊的驱动槽位（§9.1 的 OceanBase/TiDB 那两行都往这一家挂）。
///
/// <para><b>它今天一个字都不覆写</b>，而这一格形状本身就是交付物，且是第三条血统的第一个叶子：
/// §2 那句"provider 之间禁止互引"禁的是兄弟 provider 互相伸手拿实现，共用的东西只能往上一层
/// （<c>DialectBase</c> 与 <c>MySqlProviderBase</c> 都在那一层）。挂上之后产出与基类逐字同形，
/// 于是 §9.1 那句"国产库里 70% 的方言是 PG 或 Oracle 的一个变体"第一次有了<b>第三种</b>可数的对照：
/// 剩下的那 30% 里最大的一族（GBase 8s、虚谷、时序那几家）今天仍然一层都没有。</para>
///
/// <para><b>三件已知会变的东西</b>（逐条对到今天的状态）：
/// <list type="bullet">
/// <item><b>MariaDB 10.5 起有 <c>INSERT … RETURNING</c></b>，但要老实支持它得换一颗 <c>IKeyStrategy</c>
/// （<c>MySqlKeys.EmitReturning</c> 那一抛在它下面才成立），而基类那一份是 <c>public sealed</c> 具体类型、
/// 没有换的口子 —— 那是一次 §4 公开形状改动。<b>本仓库裁"不立 MariaDB 这一档"</b>：<c>DbKind</c> 里原来的
/// <c>MariaDb</c> 值已撤下（理由与重开条件记设计文档 §14）；要 <c>RETURNING</c> 键回读的用户侧退路仍是自生成
/// 主键（Guid/雪花）+ <c>ExecuteAffrowsAsync</c>，与基类那颗抛的指路同一句。</item>
/// <item><b>TiDB 的自增是批量预分配的</b>（§9.1 那一行），所以"多行 <c>VALUES</c> 的 id 连续"这一条在
/// 它那一份上比 MySQL 更不成立；而它还需要 <c>SHARD_ROW_ID_BITS</c> 这类表选项。
/// <c>DbKind.TiDb</c> 同样挂着没有 provider，覆写点是 <c>MySqlCodeFirst</c> 那颗 <c>IdentityClause</c>
/// 与表选项那一段（今天它是 <c>const</c>，等真有叶子那天再虚化 —— 不留一颗没人覆写的虚函数）。
/// 【v0.35 第三笔：那天到了，而两处都裁成"没到场" —— <c>QuickSql.Providers.TiDb</c> 零覆写，
/// <c>IdentityClause</c> 与 <c>TableOptions</c> 仍是血统那一份；"同样挂着没有 provider"从那一笔起作废，
/// 原句留着记当时的分布。】</item>
/// <item><b>OceanBase 的 MySQL 模式</b>按 §9.1 那一行走的是"模式在连接上决定"，与金仓那一家
/// "兼容模式开关改变方言假设"是同一颗没有建模的缺口（§14 同一行，两个实例）。
/// 【v0.35 第四笔：这一家今天有了自己的叶子 <c>QuickSql.Providers.OceanBase</c>（零覆写、与 mysql/TiDb 逐字同形），
/// 而那句缺口<em>没有</em>被叶子的到场顺手建模——新叶子的正确性反过来<em>依赖</em>那颗没建模的格子：
/// 构造 <c>OceanBaseProvider</c> 就是在主张"这条连接建在 MySQL 模"，而 SPI 问不出这一问。
/// 两个"没建模"从今天起有了两种形状：金仓是<em>默认档没赌对会怎样</em>，这一家是<em>连赌的是哪一档都写不住</em>。】</item>
/// </list></para>
///
/// <para>版本这一格要单独说一句：这一族的语法在 5.7 与 8.0 之间真的分岔（<c>IS DISTINCT FROM</c> 要 8.0.29、
/// 窗口函数与 <c>WITH</c> 要 8.0、<c>DESC</c> 索引要 8.0 才生效），而 <see cref="DbKind"/> 与 SPI 里
/// 都没有"版本"这一格，所以本 provider 发的文本按 8.0 那一侧写，5.7 现场要自己知道差在哪 ——
/// 这条判断本身记进 §13.5 的出处台账（它是<em>今天唯一一处按版本选型</em>的 provider 决策）。</para>
///
/// <para><b>【v0.31】那句"唯一一处按版本选型"到五家数不出唯一了，而且打破它的不是第五家</b>：
/// 五家里"发的文本按某一版本侧写"这一档今天有三处——本家按 8.0（最新那一侧）、第二族按 PG 9.2 内核
/// （最老那一侧，就是 <c>PostgreSqlExpressions</c> 类注释里那三颗 <c>CAST(… AS numeric)</c>）、
/// 第三族按 12c（<c>OracleCodeFirst.IdentityClause</c> 那句 <c>GENERATED BY DEFAULT AS IDENTITY</c>，
/// 同一文件类注释末段还有一颗 12.1 之前的 30 字节上限没判）。
/// 仍然成立的是窄了一圈的那半句：<b>本家是三处里唯一一处把这件事写在 provider 叶子类注释上、
/// 并单记进 §13.5 台账的</b>，另两处的版本理由埋在家族层的模板串与列定义里，读产出看不出来。
/// 第五家没有带进新的版本分岔（它带的是四颗<em>会话/建库参数</em>，见 <c>XuguTypes</c> 与 §14 那一行），
/// 所以这一格的位数是"三处版本侧、一处明示"，不是"五家各自按版本"。</para>
///
/// <para><b>【v0.37 第二笔】上面那句窄了一圈的"一处明示"今天也不成立了，而打破它的不是派生库，是 PG 本尊</b>：
/// <c>PostgreSqlProvider</c> 类注释第三段把这一族的版本选型写在叶子自己身上，并顺带算出三段区间
/// （PG 10 之前那句建表语法错 ∶ 10–13 恰合 ∶ 14 起第二处冗余）——那是本仓库第一处由<em>自己算出来</em>的版本区间，
/// 而它写在叶子类注释上，与本家同一档。所以位数从"三处版本侧、一处明示"改读"四处版本侧、两处明示"，
/// 且两处明示都在<b>正典叶</b>上。更要紧的是这两颗正典叶的选型方向相反：本家按这一族<b>最新</b>那一侧写文本
/// （8.0，派生叶 TiDB／OceanBase 吃它），PG 本尊吃的是血统为<b>最老</b>那一侧攒下的形状（那三颗 <c>CAST</c> 包装）——
/// 同为零覆写的正典叶，一个把代价推给派生叶、一个把代价留给自己，而本家那一半在 v0.30 立项时并不是这么选的：
/// 它只是当时最新的那一侧刚好也最方便。判据与全文记 §14 那一行"三颗 <c>IdentityClause</c>"的本笔注。</para></summary>
[QuickSqlProvider(DbKind.MySql)]
public sealed class MySqlProvider : MySqlProviderBase
{
    /// <summary>清单里的 <c>key</c>。<c>assembly</c> 按 §9.1 的清单写 <c>MySqlConnector</c>（社区驱动，
    /// 这一家官方没有 ADO.NET 驱动，<c>MySQL.Data</c> 那一份是另一条血统），而这个名字与金仓、达梦那两格
    /// 同一处境：<b>从未在一台机器上解析成功过</b>。清单里因此同样刻意不写 <c>factoryType</c> ——
    /// 省略它走"扫导出类型里第一个 <c>DbProviderFactory</c> 子类"那条兜底，比猜一个全名更容易成。</summary>
    public const string DriverKey = "mysql";

    public MySqlProvider(DbProviderFactory driverFactory)
        : base(DbKind.MySql, driverFactory)
    {
    }
}
