    static GateRow Allocation(IEntitySchemaRegistry schemas)
    {
        var (perQuery, _) = FullPath(schemas);
        var (adoPerQuery, _) = AdoOnly(schemas);

        var quicksql = Math.Round(perQuery - adoPerQuery, 1);

        // 红行要能被动手修，所以拆开报：入口、发射、装配三段各花多少，再拿一个 8 列的实体同测一次
        // —— 两数一比就知道这笔钱是"每列一次"还是"每查询一次"，而那决定了该去哪一层省。
        var one = Harness.Table(schemas, typeof(WideRow), One);
        var orm = Harness.Orm(_ => one, schemas);
        var root = orm.Select<WideRow>();

        var entry = Measuring.Bytes(() => _ = orm.Select<WideRow>());
        var build = Measuring.Bytes(() => _ = root.ToSql());
        var narrow = Measuring.Bytes(() => _ = orm.Select<BenchOrder>().ToSql());

        // 列数从契约拿，不写死：这两个数字一改（加字段、或哪天有列被忽略），摊平的每列字节就得跟着变，
        // 而硬编码的 30 与 8 会安静地给出一个仍然"看着合理"的错数。
        var columns = schemas.Contract<WideRow>().Columns.Length;
        var narrowColumns = schemas.Contract<BenchOrder>().Columns.Length;
        var perColumn = (build - narrow) / (columns - narrowColumns);

        return new GateRow(
            "缓存命中路径下，单次简单查询除结果对象外的托管分配",
            "0 B（不含 ADO 驱动自身开销）",
            $"{N(quicksql)} B/查询（全路径截距 {N(perQuery)} B − 同形 ADO 基线 {N(adoPerQuery)} B）"
            + $"；其中 Select<T>() {N(entry)} B、ToSql() {N(build)} B、其余 {N(quicksql - entry - build)} B；"
            + $"同一段 ToSql() 在 {narrowColumns} 列实体上是 {N(narrow)} B，差值按列摊平 {N(perColumn)} B/列",
            quicksql <= 0 ? Verdict.Green : Verdict.Red,
            "基线那份是「开连接、造命令、绑两个参数、跑完 reader、逐样释放」，与 AdoExecutor.OpenAsync 逐项对齐，"
            + "所以差值里剩下的都是 QuickSql 自己的东西：SQL 文本、SqlWriter 缓冲、参数表、每场次一张取数票、闭包与 List 头。"
            + "这一行不给自己留容差（判据是 ≤ 0），因为截距是确定量：同样一条查询跑两遍，分配数不一样才是要查的事。"
            + "拆出来的方向性结论：这笔钱几乎全在 ToSql() 那一段，而它随列数走（每列 " + N(perColumn) + " B），"
            + "不是每查询一次的固定税 —— 省它的地方在方言发射与标识符策略，不在物化层（§12.7 C 那条零装箱改造动不到它）。"
            + "「每列」这个数是两点的除法：两个实体的列名长短不同，也被一并摊进了分子，所以它是量级不是单价。"
            + "原先留在这里的那句「真要按它省，先从一处下手」已经做掉了（v0.11 发射层第一刀，"
            + "钉从 11 688 掉到这一格的实测值，掉的量与每列斜率的变化对得上，归属写在 Baselines.PerQueryBytes 上）。"
            + "剩下的每列 115 B 里，最大的一块是每列一对 ColumnExpression + Projection（64 B），"
            + "它要等 §12.7 E 那条把 AST 改成 record struct 才能削 —— 所以这一格不会一直掉到 0，下一档在结构层。"
            + "**【上一句那句「零装箱改造动不到它」在 v0.38 第五笔丙之后要改判】**原文照抄在前：「省它的地方在方言发射与标识符策略，不在物化层」。"
            + "改判在后：丙确实动到了它，只动了 8 B（5 480→5 488，全在「其余」那一段，256→264），"
