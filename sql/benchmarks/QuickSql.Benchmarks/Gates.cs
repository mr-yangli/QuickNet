            "前半句按 §12.8 原样判；后半句是代理判据，比值阈值 1.5 是本文件定的、不是 §12.8 写的 —— "
            + "因为分配器只给字节不给类型，「零 string」在这里只能以「没有平方项」的形式被看到。"
            + "比值（就在上一格）小于 1 说明没有平方项，但每谓词 2 KB 这个常数本身不小，它与第 1 行量到的是同一笔钱（每列一次的标识符与片段分配）。",
