                new Pin("每谓词字节 100 档", Baselines.PredicateBytesLong, Math.Round(at100)),
            ]);

        double Slope(int predicates)
            => (Measuring.Bytes(() => build(predicates), warmup: 5, reps: 5)
              - Measuring.Bytes(() => build(1), warmup: 5, reps: 5)) / (predicates - 1);
