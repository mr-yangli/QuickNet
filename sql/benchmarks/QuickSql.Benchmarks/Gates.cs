    /// <summary>全路径两点法：同一个注册表、同一条查询，只把行数从 1 换到 10 001。
    /// <b>组装根本身必须在计时窗外</b>：把 <c>new QuickSqlOrm</c> 写进被测委托会把它内部那套
    /// （QueryCompiler、AdoExecutor）算成"每次查询的开销"，而真实用法里它是跨请求单例。</summary>
    static (double PerQuery, double PerRow) FullPath(IEntitySchemaRegistry schemas)
    {
        var one = Harness.Table(schemas, typeof(WideRow), One);
        var many = Harness.Table(schemas, typeof(WideRow), Many);

        var ormOne = Harness.Orm(_ => one, schemas);
        var ormMany = Harness.Orm(_ => many, schemas);

        return TwoPoint(
            () => ormOne.Select<WideRow>().ToListAsync(),
            () => ormMany.Select<WideRow>().ToListAsync());
    }

    /// <summary>与 <see cref="FullPath"/> 逐项对齐的 ADO 基线：连接、命令、两个参数、reader 走完全程、释放。
    /// 它自己也是两点的，所以两边的截距可以直接相减。</summary>
    static (double PerQuery, double PerRow) AdoOnly(IEntitySchemaRegistry schemas)
    {
        static Func<Task> Body(DataTable table)
            => async () =>
            {
                using var connection = new OfflineConnection(_ => table);

                await connection.OpenAsync();

                using var command = connection.CreateCommand();

                command.CommandText = "select * from [BenchWideRow]";
                command.CommandTimeout = 30;

                for (var i = 0; i < 2; i++)
                {
                    var parameter = command.CreateParameter();

                    parameter.ParameterName = "@p" + i.ToString();
                    parameter.Value = i;
                    parameter.DbType = DbType.Int32;

                    command.Parameters.Add(parameter);
                }

                using var reader = await command.ExecuteReaderAsync();

                while (await reader.ReadAsync()) { }
            };

        return TwoPoint(Body(Wide(schemas, One)), Body(Wide(schemas, Many)));
    }

    static (double PerQuery, double PerRow) TwoPoint(Func<Task> oneRow, Func<Task> manyRows)
    {
        var at0 = Measuring.BytesAsync(oneRow);
        var at1 = Measuring.BytesAsync(manyRows);

        var perRow = (at1 - at0) / (Many - One);

        return (at0 - perRow, perRow);
    }

    static DataTable Wide(IEntitySchemaRegistry schemas, int rows) => Harness.Table(schemas, typeof(WideRow), rows);

    /// <summary>结果对象本体：同进程实测，不手算字段表（手算会在第一次加字段之后变成假数字）。</summary>
    static double ResultObjectBytes()
    {
        const int n = 4096;

        var sink = new WideRow[n];
        var at = 0;

        var bytes = Measuring.Bytes(() =>
        {
            for (var i = 0; i < n; i++)
                sink[at = (at + 1) % n] = new WideRow();
        }, warmup: 3, reps: 3);

        GC.KeepAlive(sink);

        return bytes / (double) n;
    }

    static string? GeneratedArtifact()
    {
        // 两份配置各有一份生成物（obj/Debug、obj/Release）。按目录序取第一个会判到哪一份全看文件系统，
        // 2026-09-21 就撞上过：那次先出来的是 Debug 那份、比 Release 早 11 小时，而它照样"绿"
        // （旧内容也是零反射），于是这一行判的是一场上一次构建的交付物。按当前进程的配置取，
        // 并把判的是哪一份打进实测 —— 这条不重跑一次是看不出来的。
        var obj = Path.Combine(Repo.Root, "benchmarks", "QuickSql.Benchmarks", "obj"); // 并入 Quick 仓库时目录由 bench/ 改名为 benchmarks/

        if (!Directory.Exists(obj)) return null;

        var running = Configuration();

        return Directory.EnumerateFiles(obj, "QuickSqlGeneratedWideRow.g.cs", SearchOption.AllDirectories)
            .OrderByDescending(File.GetLastWriteTimeUtc)
            .OrderBy(f => f.Contains($"{Path.DirectorySeparatorChar}{running}{Path.DirectorySeparatorChar}") ? 0 : 1)
            .FirstOrDefault();

        static string Configuration()
        {
            var dir = Path.GetDirectoryName(typeof(Gates).Assembly.Location);

            return Path.GetFileName(Path.GetDirectoryName(dir!)!) is { Length: > 0 } config ? config : "Release";
        }
    }

