    static GateRow SqlBuild()
    {
        var orm = Harness.Orm(_ => null);

        Func<int, string> build = predicates =>
        {
            var query = orm.Select<BenchOrder>();

            for (var i = 0; i < predicates; i++)
                query = query.Where(o => o.Id > i);

            return query.ToSql();
        };

        var sql = build(100);

        var ms = Measuring.Nanoseconds(() => build(100), warmup: 5, reps: 9) / 1_000_000;

        // 「中间 string 分配 0」数不了字符串条数，于是钉它的必要条件：边攒边拼会退化成 O(n²)，
