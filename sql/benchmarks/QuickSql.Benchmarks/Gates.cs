        var at25 = Slope(25);
        var at100 = Slope(100);

        var growth = at100 == 0 ? 0 : at25 / at100;

        return new GateRow(
            "100 步 Where 链构建 → ToSql()",
            "≤ 1 ms，且中间 string 分配 0",
            $"{N(ms)} ms（100 个谓词，产出 {sql.Length:N0} 字符）；每谓词字节 25 档 {N(at25)} B vs 100 档 {N(at100)} B，比值 {N(growth)}",
