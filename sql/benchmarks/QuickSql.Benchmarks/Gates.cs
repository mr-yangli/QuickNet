    /// 它是判据 ② 的乘数，而"每行几颗参数"正是合并语句与逐条语句共同的那个形状。</summary>
    const int ParamsPerRow = 2;

    /// <summary>合并那一腿：13 只全脏在<em>同一列</em> ⇒ 一个掩码、一个桶、13 行 ⇒ 一句
    /// <c>UPDATE ... FROM (VALUES …)</c>。分块尺寸在这一式下是 945 行（<c>2100 × 9 ÷ 10 ÷ 2</c>，
    /// 每行 2 颗参数），13 行远不到一块，所以"一条语句"这件事不是碰巧没分块。</summary>
    static void DirtySameColumn(WideRow[] entities, int at)
    {
        foreach (var entity in entities)
            SingularSetters[0](entity, at);
    }

    /// <summary>逐条那一腿：第 i 只脏在第 i 列 ⇒ 13 个掩码、13 个各装一行的桶，
    /// 于是每个桶都走 <c>Rows.Count > 1</c> 那道分流之外的逐条档。
    /// <b>这一腿不是"关掉合并"</b>：同一段代码、同一道闸门，只是每桶一行所以合不起来 ——
    /// 它量的是"不合并时这条保存花多少"，与合并腿共用全部其余路径。</summary>
    static void DirtyEachColumn(WideRow[] entities, int at)
    {
        for (var i = 0; i < entities.Length; i++)
            SingularSetters[i](entities[i], at);
    }

    /// <summary>一次保存的读数。<b>字节与时间在测量窗内取，语句数与事务数在窗外单独再跑一轮取</b>：
    /// <see cref="Measuring"/> 那两件事各自要在循环里跑几十遍，而计数器只能读一次，
    /// 把计数塞进被测委托会往被测那一段里多塞一次空判断之外的东西。
    /// 参数数与操作数取自报告里那条 SQL 文本，也只有窗外那一轮能拿到报告（<c>Measuring</c> 不给返回值）。</summary>
    sealed record SaveRun(
        long Bytes,
        double Nanos,
        int Statements,
        int Transactions,
        int Reported,
        int Parameters,
        int Operations);

    /// <summary>三腿共用的那一个跑法：装配在窗外（与第 1 行同一句理由），会话上挂 13 只
    /// <b>键已定</b>的实体（<c>Attach</c> 而不是 <c>Add</c>：自增主键给 0 会被 <c>IsDefinite</c> 判成"没填"，
    /// 那一档的键回填要走 <c>OUTPUT</c>，而这一格要量的只有 UPDATE），然后按 <paramref name="dirty"/> 弄脏并保存。
    /// <para><b><paramref name="dirty"/> 传 null 就是地板腿</b>：一批从未弄脏的实体走一次保存，
    /// <c>WritesAreDue</c> 会先做完整的一轮逐列比较再答"没有欠着语句"，于是那一轮的字节就是三腿共付的那一块
    /// （侦测不看粘性位：粘性位只让 <c>AnyDue</c> 与发射段跳过整档，<c>DetectChanges</c> 自己是全员逐列比）。
    /// 地板腿因此可以给"减掉共付块"当数，也可以给"空会话收尾不发语句、不开事务"那一句当数。</para></summary>
    static SaveRun Save(IEntitySchemaRegistry schemas, Action<WideRow[], int>? dirty)
    {
        var (orm, counters) = Harness.OrmCounted(_ => null, schemas);

        try
        {
            var session = new DbContext(orm);
            var entities = new WideRow[MergedRows];

            for (var i = 0; i < MergedRows; i++)
                entities[i] = session.Attach(new WideRow { Id = i + 1 });

            var at = 1;

            // 非 async 的委托：写成 async lambda 会每次调用多一只状态机，而这一格钉的就是每次保存的字节。
            Func<Task> run = () =>
            {
                dirty?.Invoke(entities, at++);

                return session.SaveChangesAsync();
            };

            var bytes = Measuring.Bytes(run);
            var nanos = Measuring.Nanoseconds(run);

            counters.Reset();
            dirty?.Invoke(entities, at++);

            var report = session.SaveChangesAsync().GetAwaiter().GetResult();
            var parameters = 0;

            foreach (var operation in report.Operations)
                foreach (var mark in operation.Sql)
                    if (mark == '@')
                        parameters++;

            if (dirty is not null && (counters.Statements == 0 || report.Operations.Count == 0))
                throw new InvalidOperationException(
                    $"第 11 行这一腿一条语句都没发：会话被判定成「没有欠着语句」，那它量的就不是保存而是地板。"
                    + $"（弄脏那一步没生效，或分流被改过 —— 先把这一腿的脏列掩码查出来再读任何一格的数。）");

            return new SaveRun(bytes, nanos, counters.Statements, counters.Transactions, report.StatementCount, parameters, report.Operations.Count);
        }
        finally
        {
            // 计数器挂在假驱动的静态槽位上（理由见 OfflineAdo 类注释④），而槽位是全局的：
            // 摘掉它才使得"其余各行跑的时候槽位是 null"成为结构保证。v0.28 那一版第 11 行是最后一行，
            // 这一条还只是"不靠记得摘"的写法偏好；本版它后面多了第 12 行，这句就从偏好变成了必需 ——
            // 那一行量的正是"除了被测路径什么都不发生"的读侧整链。
            Harness.UnbindCounters();
        }
    }

