    /// <summary>恒真谓词三颗，<b>一颗比一颗挑得小心</b>：
    /// <c>Id &gt;= 0</c> / <c>Seq &gt;= 0</c> / <c>Money1 &gt;= 0</c> 三列在 <see cref="Harness.Table"/> 里
    /// 灌的都是行号（<c>Money1</c> 是行号 + 0.5），所以三腿物化的<em>行数必须相同</em> —— 那正是判据 ① 判的东西。
    /// <para><b>为什么不能用第 10 行那三颗</b>：那里有颗 <c>Flag1 == false</c>，而样本生成器给 <c>bool</c> 列灌的是
    /// <c>row % 2 == 0</c>，一半的行会被筛掉。第 10 行只 <c>ToSql()</c>、压根不物化，所以那里少一半行不发生；
    /// 本格量的就是物化那条链，"过滤器把行筛掉了"会把它想要的结论（贵）反着报成便宜。
    /// 假驱动不执行 WHERE，所以这一维不是"防万一"而是<b>唯一的现场</b>：真库上它由同一颗断言守住，
    /// 集成层接过滤器那天（§10.7 约束 1 第二半）这一句要跟着搬过去。</para>
    /// <para><b>三腿都用 >= 而不是 > 0</b>：<c>Sample</c> 给整数列灌的是行号，而第 0 行的 <c>Id</c> 就是 0，
    /// 用 <c>&gt; 0</c> 会在 1 001 行档上悄悄少物化一行 —— 于是"两腿比的是同一次物化"这句话当场不成立。</para></summary>
    static void RegisterAll(QuickSqlOrm orm, int count)
    {
        if (count >= 1) orm.Filters.Add<WideRow>(w => w.Id >= 0);
        if (count >= 2) orm.Filters.Add<WideRow>(w => w.Seq >= 0);
        if (count >= 3) orm.Filters.Add<WideRow>(w => w.Money1 >= 0);
    }

    /// <summary>第 12 行的一条腿：同一个组装根、同一张假表，只改注册颗数与行数。
    /// 四样观测一次拿齐 —— 整链字节、真物化出来的行数、单次出口的字节、语句文本长度 —— 因为判据 ①③④⑤
    /// 各自要一样，而把它们拆成四次测量就会分成四台机器状态。
    /// <para>出口那一腿排在整链之后，且挂法与第 10 行的 <c>PerExit</c> 逐字同式（现成根链 + 一次
    /// <c>ToSql()</c>，不造引擎）。同式不等于同值：第 10 行那段注释已经实测过绝对值会随进程位置漂 32 B，
    /// 所以本格只用同一次运行里的<em>增量</em>，链上/出口那个比值只作同场对照。</para></summary>
    static (long Bytes, int Rows, long Exit, int SqlLength, double Nanos) ReadChainLeg(
        IEntitySchemaRegistry schemas, int rows, int filters)
    {
        var table = Wide(schemas, rows);
        var orm = Harness.Orm(_ => table, schemas);

        RegisterAll(orm, filters);

        Func<Task> materialize = () => orm.Select<WideRow>().ToListAsync();

        var bytes = Measuring.Bytes(materialize);
        var nanos = Measuring.Nanoseconds(materialize);
        var counted = orm.Select<WideRow>().ToListAsync().GetAwaiter().GetResult().Count;

        var root = orm.Select<WideRow>();
        var exit = Measuring.Bytes(() => _ = root.ToSql());

        return (bytes, counted, exit, root.ToSql().Length, nanos);
    }

    /// <summary>§12.8 第 12 行：注册全局过滤器之后，<b>第 2 行那条物化链</b>多付多少。
    ///
    /// <para><b>它补的是 §10.7 那份清单末尾「另一半」</b>：v0.27 的第 10 行只量 <c>ToSql()</c>，
    /// 也就是「一次出口」那一笔；而「注册之后对第 2 行物化吞吐的影响」那一格当时仍写着未量 ——
    /// 第 2 行的基准链上一颗过滤器都没有。本格就是把同一批过滤器挂到那条真实的 <c>ToListAsync()</c> 链上，
    /// 问一句：出口之外还有没有第二处收钱的地方，以及这笔钱是按查询收还是按行收。</para>
    ///
    /// <para><b>钉的仍是增量而不是绝对值</b>：整链那一档的绝对值有三十万字节量级、且已由第 2 行钉着，
    /// 把它再钉一遍只是给第 2 行的钉找个会随机器状态翻色的邻居。两枚新钉与第 10 行那两枚同为「一颗 / 三颗」
    /// 的增量口径，但<em>不是同一个数</em>（这里多了整条执行与物化段），跨行搬会搬错。</para>
    ///
    /// <para><b>为什么跑两档行数</b>：1 001 行那一档给判据 ①②③④⑥，1 行那一档只为 ⑤ 服务 ——
    /// 只有把两档的增量放在一起，才分得出「每查询一笔」与「每行一笔」。两档各要一台组装根与一张表，
    /// 所以本格的腿是五腿而不是三腿。</para></summary>
    static GateRow FilterOnReadChain(IEntitySchemaRegistry schemas)
    {
        const int Registered = 3;
        const int ManyRows = 1_001;
        const int OneRow = 1;

        var none = ReadChainLeg(schemas, ManyRows, 0);
        var one = ReadChainLeg(schemas, ManyRows, 1);
        var many = ReadChainLeg(schemas, ManyRows, Registered);

        // 1 行那一档只为判据 ⑤ 服务：如果过滤器的代价里有任何一项是按行收的（每行重跑一遍谓词、
        // 每行多一次装箱），两档的增量就会差出量级；只量 1 001 行那一档就分不出"每查询一笔"与"每行一笔"。
        var noneAtOne = ReadChainLeg(schemas, OneRow, 0);
        var manyAtOne = ReadChainLeg(schemas, OneRow, Registered);

        var oneDelta = one.Bytes - none.Bytes;
        var manyDelta = many.Bytes - none.Bytes;
        var exitOneDelta = one.Exit - none.Exit;
        var exitManyDelta = many.Exit - none.Exit;
        var oneRowAtOne = manyAtOne.Bytes - noneAtOne.Bytes;

        var rowsOk = none.Rows == one.Rows && one.Rows == many.Rows && many.Rows == ManyRows
            && noneAtOne.Rows == manyAtOne.Rows && manyAtOne.Rows == OneRow;
        var existsOk = oneDelta > 0 && manyDelta > 0;
        var textOk = one.SqlLength > none.SqlLength && many.SqlLength > one.SqlLength
            && manyAtOne.SqlLength == many.SqlLength;
        var onceOk = exitManyDelta > 0 && manyDelta <= exitManyDelta * 1.5;
        var flatOk = Math.Abs(oneRowAtOne - manyDelta) < ManyRows - OneRow;
        var sublinearOk = manyDelta <= 3.5 * oneDelta;

        return new GateRow(
            $"注册全局过滤器之后，第 2 行那条物化链（{ManyRows:N0} 行 × 30 列一次 ToListAsync）的代价",
            "增量存在（为 0 是坏消息：过滤器没贴进语句）；三腿物化行数相等（谓词不许把行筛掉）；"
            + $"语句文本随注册数单调变长；整链增量 ≤ 同一次运行里单次出口增量 × 1.5（这条链上只翻译一次）；"
            + $"{Registered} 颗 ≤ 一颗 × 3.5（不超线性）；{OneRow} 行档与 {ManyRows:N0} 行档的增量之差 < 行数（代价不随行数放大）",
            $"一颗 +{N(oneDelta)} B、三颗 +{N(manyDelta)} B（整链 {N(none.Bytes)} B → {N(one.Bytes)} B → {N(many.Bytes)} B；"
            + $"÷ 行数 = {N((double) manyDelta / ManyRows)} B，那只是除法、不是每行代价，每行那一维由下面 ⑤ 那两个档之差判）；"
            + $"单次出口 +{N(exitOneDelta)} B / +{N(exitManyDelta)} B（与第 10 行同式但不同值，只作同场对照；链上 ÷ 出口 = {N((double) manyDelta / exitManyDelta)}）；"
            + $"{OneRow} 行档三颗 +{N(oneRowAtOne)} B（与 {ManyRows:N0} 行档之差 {N(oneRowAtOne - manyDelta)} B）；"
            + $"语句文本 {none.SqlLength} → {one.SqlLength} → {many.SqlLength} 字符；物化行数三腿都是 {none.Rows}；"
            + $"整链一次 {N(none.Nanos / 1000)} µs → {N(many.Nanos / 1000)} µs（三颗，每链多 {N((many.Nanos - none.Nanos) / Registered / 1000)} µs，不钉）",
            rowsOk && existsOk && textOk && onceOk && flatOk && sublinearOk ? Verdict.Green : Verdict.Red,
            "这一格是 §10.7 那份清单末尾<em>另一半</em>欠账的兑现：v0.27 第 10 行量的是每次出口的翻译增量，"
            + "而「注册之后对第 2 行物化吞吐的影响」当时还写着「未量」 —— 那一格的基准链上一颗过滤器都没注册。"
            + "六条判据各拦一种错：① 三腿物化<em>行数相等</em>，拦的是「谓词把行筛掉了所以看起来便宜」，"
            + "假驱动不执行 WHERE，所以这一维在这一格里只判得出<em>我挑的谓词有没有被谁在托管侧跑了一遍</em>"
            + "（§5.8 禁静默客户端求值，这条判据就是它在这一格的哨兵）；② 增量为 0 在这一格里是<em>坏</em>消息，"
            + "与第 10 行同一条理由 —— 它意味着过滤器压根没贴进这条链；③ 文本长度单调，是②的独立见证，"
            + "两条一起才不靠单一口径；④ 链上增量 ÷ 出口增量 ≤ 1.5，<b>这一条才是本格的新内容</b>："
            + "第 10 行已经证明每出口重翻译一遍，本格要证的是「这条链上没有第二处为过滤器付钱的地方」，"
            + "比值一旦到 2 以上，说明引擎或执行段也在重复翻译；⑤ 一行档与 1 001 行档的增量之差小于行数，"
            + "也就是每行的增量不到 1 B —— 这一条把「每查询一笔」与「每行一笔」分开，是这六条里唯一不能由第 10 行代替的；"
            + "⑥ 三颗 ≤ 一颗 × 3.5，沿用第 10 行那道超线性闸门。"
            + "<b>第 6 行那一半在本格量不到代价，而且这是设计而不是缺测</b>：§10.7 约束 1 的第二半"
            + "（<c>SaveChanges</c> 与批量两档的注入）今天没有实现，等的是「0 行算不算并发冲突」那道裁决。"
            + "写侧今天只有 <c>Update</c>/<c>Delete</c> 两档调 <c>Filters.ApplyTo</c>（<c>UpdateEngine</c> 两处），"
            + "批量插入那条链上没有这一句 —— 所以「注册之后语句文本与参数一字未变」这一句是<em>读代码得到的</em>，"
            + "不是本格量出来的，本格也不钉那个 0："
