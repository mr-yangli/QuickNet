using QuickSql.Metadata;
using QuickSql.Schema;
using QuickSql.TestInfra;
using Xunit;

namespace QuickSql.Tests.Integration;

/// <summary>§9.5 列级结构同步在<b>活库</b>上的那一半（离线那一半在 <c>StructureSyncTests</c>）。
///
/// <para><b>两册的分工在这里不是"离线测粗、活库测细"，而是各测一件不同的事</b>：离线那册手写的读数
/// 能穷举十几种形状，却<em>钉不到目录真的把那句 <c>ALTER</c> 收成了什么</em>——"发得出去"与"改成了我要的那一形"
/// 是两件事，中间隔着 T-SQL 的三处取值折叠（<c>numeric</c> 而不是 <c>DECIMAL</c>、时间精度落在 <c>scale</c>
/// 那一格而不在类型名里、<c>max_length</c> 是字节数）。所以本册的裁判全部问<em>目录</em>，不问产出文本。</para>
///
/// <para><b>幂等裁判（第二趟零动作）在这一册只有一份读数，而它量的是归一</b>：一张被人手改歪过的表，
/// 同步过一趟以后必须"再问一遍什么也不发"。它红一次就意味着下一版会在一张根本没变过的表上发 <c>ALTER</c>，
/// 而那种 <c>ALTER</c> 在生产库上是锁表。离线那册的同一条用例钉的是同一条判据的另一半：这里证明
/// <em>归一与真目录对得上</em>，那里证明<em>归一与手写的目录形状对得上</em>。</para>
///
/// <para><b>为什么本册从前只有 SQL Server 一家</b>：这一刀的裁决是"先一档打穿，其余六家按能读到的档位、
/// 读不到的进 <see cref="SchemaSyncResult.NotJudged"/> 清单并指名"。而本用例的"旧形状"是裸 T-SQL 建的
/// （<c>IDENTITY</c>、<c>sp_addextendedproperty</c>、<c>datetime2(3)</c> 三处没有跨家写法可折），
/// 换一家就要重写整段 arrange 而不是换一颗判据。<b>本册自这一笔起有三家</b>：PG 家与 MySQL 家各自补齐了
/// 读侧四档（<c>pg_description</c> 的备注 ∶ <c>pg_index</c> 的索引清单，与 <c>column_comment</c> ∶
/// <c>statistics</c> 的索引清单，外加两家的列形状判据与 <c>DROP INDEX</c> 的发射），
/// 于是这一格在它们上面都有了对象。arrange 因此按家分岔，而<em>裁判的分寸一句没改</em>：动作清单、幂等那两句
/// 是 Core 的返回值，家与家同一形状；只有"问目录"那一段每家各问自己那两张视图——名字不是一份，
/// 判据就不能写成一份。剩下四家（SQLite ∶ 虚谷 ∶ Oracle ∶ GBase 8s）读侧未接，
/// 它们在列级这一档只有离线册那份"判不了"报告，skip 消息里逐家点着名。</para>
///
/// <para><b>MySQL 那一支的 arrange 有两处与另两家对不上位，而那不是写法松散</b>：这一家没有
/// "具名主键约束"那颗目录对象（建表时写的名字被库换成 <c>PRIMARY</c>，实测·X-03），所以那一句
/// <c>CONSTRAINT [PK_…] PRIMARY KEY</c> 在这里根本没有对应物；而列注释是列定义的一部分
/// （这一家没有 <c>COMMENT ON COLUMN</c>），所以"旧标题"那颗备注写在 <c>CREATE TABLE</c> 里
/// 而不是跟着补一句。<b>这两处正是本家读侧那四档要还的债</b>：前者由 <c>statistics</c> 里那颗
/// 恒叫 <c>PRIMARY</c> 的索引回写主键列，后者由 <c>column_comment</c> 直接读回来。</para></summary>
public sealed class StructureSyncPathTests
{
    /// <summary>靶实体：五列里每一列各承担一格差。列序即 <see cref="SchemaSyncResult.AlteredColumns"/>
    /// 的顺序，所以下面那几句逐格的断言能写成清单全文而不是 <c>Contains</c>。</summary>
    [Table("QuickSqlShapeProbe", Comment = "形状探针表")]
    [Index("IX_QuickSqlShapeProbe_Title", "Title")]
    public sealed class ShapeProbe
    {
        public int Id { get; set; }

        /// <summary>库里那一份是 <c>nvarchar(64)</c> 而备注写着旧话 → 长度差 + 备注差。</summary>
        [Column(Length = 32, Comment = "标题")]
        public string? Title { get; set; }

        /// <summary>库里是 <c>decimal(18,2)</c> → 标度差，也就是用户点名的那一颗"小数长度"。</summary>
        public decimal Amount { get; set; }

        /// <summary>库里没有这一列，而它可空 → 补列，顺带补备注。</summary>
        [Column(Length = 40, Comment = "备注")]
        public string? Note { get; set; }

        /// <summary>形状（<c>datetime2(3)</c>）与库里一致，只差可空性 → 单独钉住"整列定义重写"那一句。</summary>
        public DateTime? PaidAt { get; set; }
    }

    /// <summary>这张靶表在<em>本家裸 SQL</em> 里怎么写。三家的写法不是同一串，而"取哪一颗名字"这件事
    /// 只有目录说了算：T-SQL 走 <c>[dbo].[…]</c>，PG 走 <c>"public"."…"</c> 且<em>必须带引号</em>——
    /// 不引的话 <c>QuickSqlShapeProbe</c> 会被折成 <c>quicksqlshapeprobe</c>，与 ORM 建出来的那一颗
    /// 不是同一张表（§9.2 那句"DDL 与运行时查询共用一份 <c>QuoteSqlName</c>"在这一格尤其看得见）。
    /// <b>MySQL 那一支不带模式限定</b>：这一家的"模式"就是连接串上 <c>Database=…</c> 那个库，
    /// 契约里没写模式时 <c>EmitTable</c> 什么都不写，本册的 arrange 跟着同一条形。
    /// 没接的四家<em>问不到这里</em>：三条用例第一件事就是 skip。</summary>
    static string Table
        => Database.Family switch
        {
            Database.Target.SqlServer => "[dbo].[QuickSqlShapeProbe]",
            Database.Target.PostgreSql => "\"public\".\"QuickSqlShapeProbe\"",
            Database.Target.MySql => "`QuickSqlShapeProbe`",
            var other => throw new InvalidOperationException($"{other} 这一家本册没有 arrange，问表名没有对象"),
        };

    /// <summary>这一家本册摆得出旧形状吗。三家各自点明为什么是这三家：<b>摆得出旧形状</b>才有
    /// "改了小数长度"这一问，而"改了"之后还得<em>读得回来</em>才判得出同步没同步——后者正是这两笔
    /// 给 PG 家与 MySQL 家补上的那四档。其余四家今天缺的是后者，不是前者。</summary>
    static void SkipUnlessArrangedHere()
        => Assert.SkipWhen(Database.Family is not (Database.Target.SqlServer or Database.Target.PostgreSql or Database.Target.MySql),
            "本用例的靶子表是按各家自己的裸 SQL 摆的旧形状（T-SQL 的 IDENTITY ∶ sp_addextendedproperty ∶ datetime2(3)，" +
            "PG 家的 GENERATED AS IDENTITY ∶ COMMENT ON ∶ timestamp(3)，MySQL 家的 AUTO_INCREMENT ∶ 列定义里的 COMMENT ∶ datetime(3)，" +
            "三处都没有跨家写法可折），而摆完之后还要读侧四档接上才判得出差别：今天这三家接齐了，" +
            "SQLite／虚谷／Oracle／GBase 8s 四家读侧未接，它们在列级这一档只有离线册那份\u201c判不了\u201d报告。");

    /// <summary>本册自造的靶表：<b>每次运行先按裸 SQL 摆回"旧形状"</b>，所以这一格不依赖上一次跑过什么。
    /// 摆的是一张<em>别人手工建的文件表</em>而不是 CodeFirst 的产物——这一档的题面正是"库里的形状
    /// 与契约不一样"，用自己的产出建出自己的目标形状就无从可判。
    ///
    /// <para>三家各摆各的句子，而<em>摆的是同一份旧形状</em>：六列五型一处旧备注一颗旧索引，
    /// 差在哪几格由下面的动作清单逐格点名。四处对位是这一份 arrange 的全部难度所在——
    /// <c>IDENTITY</c> 对 <c>GENERATED BY DEFAULT AS IDENTITY</c> 对 <c>AUTO_INCREMENT</c>
    /// （本家的自增<em>不是型而是列上的一句子句</em>，所以目录里也没有一颗布尔字段记着它，
    /// 读侧只能从 <c>extra</c> 那颗文本里包含着判）、
    /// <c>sp_addextendedproperty</c> 对 <c>COMMENT ON COLUMN</c> 对列定义里那句 <c>COMMENT '…'</c>
    /// （三家都是"改"而不是"加"，所以测得到"改一份已有的"而不是只测"补一份没有的"）、
    /// <c>datetime2(3)</c> 对 <c>timestamp(3)</c> 对 <c>datetime(3)</c>
    /// （位数写在型名里还是写在目录那一格，三家各不相同）、
    /// 以及主键那一句在第三家<em>压根没有名字可写</em>（见类注释那一段）。</para></summary>
    static void BuildOldShape(bool extraIndex = false)
    {
        switch (Database.Family)
        {
            case Database.Target.PostgreSql:
                BuildOldShapePg(extraIndex);

                return;
            case Database.Target.MySql:
                BuildOldShapeMySql(extraIndex);

                return;
        }

        Database.Execute($"IF OBJECT_ID(N'{Table}', N'U') IS NOT NULL DROP TABLE {Table}");

        Database.Execute($"""
            CREATE TABLE {Table}(
                [Id] int IDENTITY(1,1) NOT NULL,
                [Title] nvarchar(64) NULL,
                [Amount] decimal(18,2) NOT NULL,
                [PaidAt] datetime2(3) NOT NULL,
                [Legacy] nvarchar(10) NULL,
                CONSTRAINT [PK_QuickSqlShapeProbe] PRIMARY KEY CLUSTERED ([Id]))
            """);

        // 两处旧备注走的是同步那一句用的同一颗存储过程：不这么摆就只测了"补一份没有的"，测不到"改一份已有的"。
        Database.Execute($"""
            EXEC sys.sp_addextendedproperty @name=N'MS_Description', @value=N'旧标题',
                 @level0type=N'SCHEMA', @level0name=N'dbo', @level1type=N'TABLE', @level1name=N'QuickSqlShapeProbe',
                 @level2type=N'COLUMN', @level2name=N'Title'
            """);

        Database.Execute($"""
            EXEC sys.sp_addextendedproperty @name=N'MS_Description', @value=N'旧的表备注',
                 @level0type=N'SCHEMA', @level0name=N'dbo', @level1type=N'TABLE', @level1name=N'QuickSqlShapeProbe'
            """);

        // 一行旧数据：结构同步的底线是"改形状不搬数据"，而这只有带着行才判得出来。
        Database.Execute($"INSERT INTO {Table} ([Title],[Amount],[PaidAt],[Legacy]) VALUES (N'旧数据', 1.25, '2026-10-01 08:30:00', N'留着')");

        // 契约上<em>没有</em>的一条索引：删索引那一档的靶子。它建在 Legacy 那一列上，而那一列本来就要进
        // "要人工"名单（不删列），所以这一格摆出来的是"列留着、索引该不该跟着走"那一条判据。
        if (extraIndex)
            Database.Execute($"CREATE INDEX [IX_QuickSqlShapeProbe_Legacy] ON {Table} ([Legacy])");
    }

    /// <summary>PG 家那一份 arrange，与 T-SQL 那一支逐列对位。三件事是本家自己的：
    /// <b>删表要 <c>IF EXISTS</c></b>（这一家有这句，而它旁边的 <c>DROP INDEX</c> 偏偏没有 <c>IF EXISTS</c>，
    /// 所以本册不会去写那一句）；<b>主键约束与它的支撑索引同名</b>，那一条在下面 <see cref="Remarks"/>
    /// 的索引名单格里是看得见的；<b>时刻的位数在 <c>datetime_precision</c> 那一格</b>，
    /// 与 T-SQL 的 <c>scale</c> 同一处境、不同一颗字段。</summary>
    static void BuildOldShapePg(bool extraIndex)
    {
        Database.Execute($"DROP TABLE IF EXISTS {Table}");

        Database.Execute($"""
            CREATE TABLE {Table}(
                "Id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                "Title" varchar(64) NULL,
                "Amount" numeric(18,2) NOT NULL,
                "PaidAt" timestamp(3) NOT NULL,
                "Legacy" varchar(10) NULL,
                CONSTRAINT "PK_QuickSqlShapeProbe" PRIMARY KEY ("Id"))
            """);

        Database.Execute($"""COMMENT ON COLUMN {Table}."Title" IS '旧标题'""");
        Database.Execute($"""COMMENT ON TABLE {Table} IS '旧的表备注'""");

        Database.Execute($"""
            INSERT INTO {Table} ("Title","Amount","PaidAt","Legacy")
            VALUES ('旧数据', 1.25, '2026-10-01 08:30:00', '留着')
            """);

        if (extraIndex)
            Database.Execute($"""CREATE INDEX "IX_QuickSqlShapeProbe_Legacy" ON {Table} ("Legacy")""");
    }

    /// <summary>MySQL 家那一份 arrange，与前两支逐列对位，而<b>四处是本家自己的、折不出对应物的写法</b>：
    /// ① <b>主键没有名字可写</b>——这一家的目录里那一把恒叫 <c>PRIMARY</c>（实测·X-03），
    /// 所以这里连 <c>CONSTRAINT</c> 那一颗都不摆，而本册<em>要判的正是"库里的主键读不读得回来"</em>，
    /// 于是这一形恰好把读侧那一半逼到墙角：回写失败就落在 <c>NotJudged</c> 那句"主键列"上。
    /// ② <b>列注释写在列定义里</b>（这一家没有 <c>COMMENT ON COLUMN</c>），表注释则是<em>一句表选项</em>，
    /// 两句不是同一颗语法，与前两家的"同一套机制两档"不同。③ <b>自增是列上的一句子句而不是型</b>，
    /// 所以目录里 <c>column_type</c> 交回 <c>int</c> 而"自增"那件事只活在 <c>extra</c> 那颗文本里。
    /// ④ <b><c>Legacy</c> 这一列在本家取 <c>LONGTEXT</c> 而不是 <c>VARCHAR(10)</c></b>：那一档的
    /// <c>CHARACTER_MAXIMUM_LENGTH</c> 与 <c>CHARACTER_OCTET_LENGTH</c> 都交回 4294967295（4 GB − 1），
    /// 而 <c>GetInt32</c> 在那里抛 <c>OverflowException</c> —— 摆这一列的理由就是让 reader 每一趟都从那个数上
    /// 过一遍（读数记 <c>obj/logs/v38-my-recon-1.log</c>）。它多带走一条本家语法：<b>长文本列建索引必须给前缀长度</b>，
    /// 所以下面那句 <c>CREATE INDEX</c> 在本家多一颗 <c>(8)</c>，而列名与另两家逐字相同。
    /// 引擎与字符集显式写：这一家的默认引擎在有些部署里不是 InnoDB，而 arrange 的判据要的是"改形状不搬数据"，
    /// 那一句依赖事务引擎在场（与 <c>MySqlCodeFirst.TableOptions</c> 同一理由）。</summary>
    static void BuildOldShapeMySql(bool extraIndex)
    {
        Database.Execute($"DROP TABLE IF EXISTS {Table}");

        Database.Execute($"""
            CREATE TABLE {Table}(
                `Id` INT NOT NULL AUTO_INCREMENT,
                `Title` VARCHAR(64) NULL COMMENT '旧标题',
                `Amount` DECIMAL(18,2) NOT NULL,
                `PaidAt` DATETIME(3) NOT NULL,
                `Legacy` LONGTEXT NULL,
                PRIMARY KEY (`Id`)) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4
            """);

        Database.Execute($"ALTER TABLE {Table} COMMENT = '旧的表备注'");

        Database.Execute($"""
            INSERT INTO {Table} (`Title`,`Amount`,`PaidAt`,`Legacy`)
            VALUES ('旧数据', 1.25, '2026-10-01 08:30:00', '留着')
            """);

        if (extraIndex)
            Database.Execute($"CREATE INDEX `IX_QuickSqlShapeProbe_Legacy` ON {Table} (`Legacy`(8))");
    }

    /// <summary>只把 <see cref="ShapeProbe"/> 挂进册的一台 ORM。<b>不用 <see cref="Database.Orm"/></b>：
    /// 那一台的册里有夹具全部实体，<c>SyncStructure</c> 会把它们逐张比一遍——用例就成了替夹具查岗。
    /// <c>ForceSchemaSync</c> 开在这里的理由与 <c>DataSourcePathTests</c> 同一颗：这张表本册自造自管，环境名不归它管。</summary>
    static QuickSqlOrm Probe(bool diffColumns = true, bool dropIndexes = false)
    {
        var orm = new QuickSqlOrm(new QuickSqlOrmOptions
        {
            Provider = Database.Provider,
            ConnectionString = Database.ConnectionString,
            SchemaSync = SchemaSyncPolicy.Execute,
            ForceSchemaSync = true,
            SchemaSyncColumns = diffColumns,
            SchemaSyncDropIndexes = dropIndexes,
        });

        _ = orm.Schemas.Contract<ShapeProbe>();

        return orm;
    }

    /// <summary>备注的现值，按"表"与列名两个对象读回来。<b>这一格必须问目录而不能靠同步的返回值</b>：
    /// 返回值只能说"我发过那一句"，而 T-SQL 的 <c>ALTER COLUMN</c> 恰恰会把这一列的扩展属性<em>连带删掉</em>——
    /// "发过"与"还在"在那一句之后是两件事。
    ///
    /// <para>三家问的是三张目录，而<em>折回同一个词</em>（<c>&lt;table&gt;</c> 给表、列名给列）：
    /// T-SQL 走 <c>sys.extended_properties</c> 的 <c>class=1</c> 与 <c>minor_id</c>，PG 走
    /// <c>pg_description</c> 的 <c>objsubid</c>——那一颗在表上是 0、在列上等于 <c>attnum</c>，
    /// 与 T-SQL 的 <c>minor_id</c> 是同一颗意思的两个名字。<b>MySQL 家没有"对象→备注"那一层目录</b>：
    /// 两句备注是两张视图里各一颗字段（<c>columns.column_comment</c> 与 <c>tables.table_comment</c>），
    /// 所以这一支是一句 <c>UNION ALL</c> 而不是两向 JOIN。<b>三家都只交"写着备注"的那些行</b>，
    /// 所以"备注被清掉了"在这一格里读成"那一行没了"，而不是读成一个空串——这一条在 MySQL 家尤其要写明：
    /// 它那颗字段没写过时交的是<b>空串</b>，不加 <c>&lt;&gt; ''</c> 就会把每一列都读成"有一条空备注"，
    /// 而本册的 <c>Legacy</c> 那一列正是这种行。</para></summary>
    static Dictionary<string, string> Remarks()
        => Database.Family switch
        {
            Database.Target.MySql => Database.Rows(
                    "SELECT c.column_name AS target, c.column_comment AS remark FROM information_schema.columns c " +
                    "WHERE c.table_schema = DATABASE() AND c.table_name = 'QuickSqlShapeProbe' AND c.column_comment <> '' " +
                    "UNION ALL " +
                    "SELECT '<table>' AS target, t.table_comment AS remark FROM information_schema.tables t " +
                    "WHERE t.table_schema = DATABASE() AND t.table_name = 'QuickSqlShapeProbe' AND t.table_comment <> ''")
                .ToDictionary(r => r["target"], r => r["remark"], StringComparer.Ordinal),
            Database.Target.PostgreSql => Database.Rows(
                    "SELECT CASE WHEN d.objsubid = 0 THEN '<table>' ELSE a.attname END AS target, d.description AS remark " +
                    "FROM pg_description d " +
                    "JOIN pg_class c ON c.oid = d.objoid " +
                    "JOIN pg_namespace ns ON ns.oid = c.relnamespace " +
                    "LEFT JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = d.objsubid " +
                    "WHERE ns.nspname = 'public' AND c.relname = 'QuickSqlShapeProbe'")
                .ToDictionary(r => r["target"], r => r["remark"], StringComparer.Ordinal),
            _ => Database.Rows(
                    "SELECT CASE WHEN ep.minor_id = 0 THEN N'<table>' ELSE c.name END AS target, " +
                    "CAST(ep.value AS nvarchar(4000)) AS remark " +
                    "FROM sys.extended_properties ep " +
                    "LEFT JOIN sys.columns c ON c.object_id = ep.major_id AND c.column_id = ep.minor_id " +
                    $"WHERE ep.major_id = OBJECT_ID('{Table}') AND ep.class = 1 AND ep.name = N'MS_Description'")
                .ToDictionary(r => r["target"], r => r["remark"], StringComparer.Ordinal),
        };

    static Dictionary<string, string> Column(string name)
        => Database.Columns("dbo.QuickSqlShapeProbe").Single(r => r["name"] == Database.CatalogueName(name));

    /// <summary>本家目录里那颗"声明的字符宽度"。<b>只有 PG 家与 MySQL 家有这一颗</b>：
    /// <c>sys.columns.max_length</c> 量的是字节而这两家压根没有字节那一档（§10.4 那张对照表里 PG 就是
    /// "问不出第二把"那一行，而 MySQL 家问得出第二把、那一颗叫 <c>character_octet_length</c>，
    /// 见 <c>MySqlSchemaReader</c> 类注释），所以 T-SQL 那一支的宽度断言走 <see cref="Column"/> 的
    /// <c>max_length</c>，这两支走这一颗。它不是 <see cref="Database.Columns"/> 那四词的第五颗，
    /// 是因为四词的形状由 <c>DdlTests</c> 那三句逐列断言承诺着，多一颗就把那三份裁判也一起改了。
    /// <b>MySQL 那一支在这里是<em>第二颗</em>裁判而不是唯一颗</b>：本家 <c>Database.Columns</c> 交的
    /// <c>store_type</c> 来自 <c>column_type</c>（名与量纲写在同一串里，是厂商自己的渲染），
    /// 所以下面那一支两句都问一遍——渲染与结构化字段同数才算数。</summary>
    static string DeclaredChars(string name)
    {
        Assert.SkipUnless(Database.Family is Database.Target.PostgreSql or Database.Target.MySql,
            "只有这两家问得出这颗字符宽度（T-SQL 那一颗是字节数，走 Column 的 max_length）");

        // 两句的差只在那一颗模式谓词上：PG 家按名字筛，而 MySQL 家的"模式"是连接带来的那颗
        // DATABASE()（契约里没写模式时两家都落到各自那个默认库，与两家 EmitTable 同一条判据）。
        return Database.Family == Database.Target.MySql
            ? Database.Rows(
                    "SELECT c.character_maximum_length AS width FROM information_schema.columns c " +
                    "WHERE c.table_schema = DATABASE() AND c.table_name = 'QuickSqlShapeProbe' AND c.column_name = @col",
                    ("@col", Database.CatalogueName(name))).Single()["width"]
            : Database.Rows(
                    "SELECT c.character_maximum_length AS width FROM information_schema.columns c " +
                    "WHERE c.table_schema = 'public' AND c.table_name = 'QuickSqlShapeProbe' AND c.column_name = @col",
                    ("@col", Database.CatalogueName(name))).Single()["width"];
    }

    /// <summary>库里那一行的现值，三家各问一句而<em>取的是同一三格</em>：改形状的底线是"不搬数据"，
    /// 而那一行里的中文与那颗小数就是判据。T-SQL 的 <c>N'…'</c> 前缀在另两家没有对应物（这两家没有
    /// 按字节存的那一种字符型），所以三句不是照抄关系而是对位关系。<b>MySQL 那一句写了别名</b>：
    /// 不写时本家把结果集表头折成大写（实测·X-02），而本层 <c>Rows</c> 的键比较器在这一家是
    /// <c>Ordinal</c>，两句凑一起会把"取到了"读成"键不存在"（<c>Database.Columns</c> 本家那一段同条纪律）。</summary>
    static Dictionary<string, string> SurvivingRow()
        => Database.Family switch
        {
            Database.Target.PostgreSql => Database.Rows($"""
                SELECT "Title", "Amount", "Legacy" FROM {Table} ORDER BY "Id"
                """).Single(),
            Database.Target.MySql => Database.Rows($"""
                SELECT `Title` AS Title, `Amount` AS Amount, `Legacy` AS Legacy FROM {Table} ORDER BY `Id`
                """).Single(),
            _ => Database.Rows($"SELECT [Title], [Amount], [Legacy] FROM {Table} ORDER BY [Id]").Single(),
        };

    /// <summary>用户点名的那一格：改了表备注、小数长度、索引，同步要真的把它们落到库里，
    /// <b>并且第二趟一个字节都不发</b>。一份 arrange，五格动作清单逐格点名，裁判全部问目录。</summary>
    [Fact]
    public void A_stale_table_is_synced_column_by_column_and_the_second_pass_sends_nothing()
    {
        SkipUnlessArrangedHere();

        Database.Ready();

        BuildOldShape();

        var first = Probe().SyncStructure();

        // ── 动作清单：哪一格发了哪一句，逐格点名 ──────────────────────
        Assert.Equal(["QuickSqlShapeProbe.Note"], first.AddedColumns);
        Assert.Equal(["QuickSqlShapeProbe.Title", "QuickSqlShapeProbe.Amount", "QuickSqlShapeProbe.PaidAt"], first.AlteredColumns);
        Assert.Equal(["QuickSqlShapeProbe.Title", "QuickSqlShapeProbe.Note", "QuickSqlShapeProbe"], first.AppliedComments);
        Assert.Equal(["QuickSqlShapeProbe.IX_QuickSqlShapeProbe_Title"], first.CreatedIndexes);
        Assert.Empty(first.CreatedTables);
        Assert.True(first.Executed);

        // 这一家五档全读得回来，所以"判不了"必须是空——它非空就是"这一趟有几档根本没同步过"。
        Assert.Empty(first.NotJudged);

        // 库里多出的那一列只在名单里出现，不发一句：不删列是这一档唯一的硬拒（删了会把那一列的数据带走）。
        Assert.Single(first.Refused, r => r.Contains("Legacy", StringComparison.Ordinal) && r.Contains("不删列", StringComparison.Ordinal));

        // ── 裁判问目录：形状真的改成了契约那一形 ──────────────────────
        CatalogSaysTheNewShape();

        // 旧数据还在，而且改完形状读回来还是那一句中文（改形状不能搬数据，也不能把中文改坏）。
        var row = SurvivingRow();

        Assert.Equal("旧数据", row["Title"]);
        Assert.Equal("留着", row["Legacy"]);

        // 那颗值读回来是 <c>1.2500</c> 而不是 <c>1.25</c>：这一格正是"标度真的改成了 4"的旁证，
        // 而库里那一行<em>没有被换掉</em>——它带着同一颗数、换了存储位数活过了 ALTER。
        Assert.Equal("1.2500", row["Amount"]);

        // 备注三处：被 ALTER 过的那一列<em>仍然</em>带着新备注——这就是"ALTER 之后备注还在"的那一句。
        // 少了同步里的那一次连带重发，这里读到的是空，而幂等裁判照样绿（要发的东西已经不在库里了）。
        var remarks = Remarks();

        Assert.Equal("标题", remarks["Title"]);
        Assert.Equal("备注", remarks["Note"]);
        Assert.Equal("形状探针表", remarks["<table>"]);

        Assert.Contains("IX_QuickSqlShapeProbe_Title", Database.IndexNames("dbo.QuickSqlShapeProbe"));

        // ── 幂等裁判：第二趟零动作 ────────────────────────────────────
        var second = Probe().SyncStructure();

        Assert.True(second.IsEmpty, $"第二趟还在发动作，归一就没对上：{string.Join(" ∶ ", second.AddedColumns.Concat(second.AlteredColumns).Concat(second.AppliedComments).Concat(second.CreatedIndexes))}");
        Assert.Empty(second.CreatedTables);

        // 拒的那一格两趟都在名单里（它是给人看的话，不是动作），所以"零动作"与"仍有待人工的格"同时成立。
        Assert.Single(second.Refused, r => r.Contains("Legacy", StringComparison.Ordinal));
        Assert.Empty(second.NotJudged);
    }

    /// <summary>同步以后<em>目录里</em>那一形。三家各一份，而问的是同一四件事：那颗宽度、那颗标度、
    /// 那一格可空性、以及"库有没有把 <c>ALTER</c> 收成我要的样子"。
    ///
    /// <para>T-SQL 一支的三处折叠在本格最贵：<c>max_length</c> 是字节数（UTF-16 下契约那颗 32 读回 64）、
    /// 精度与标度拆在两颗字段里、时刻的位数落在 <c>scale</c> 而不是型名里。PG 一支问的同样是这四格，
    /// 而<em>没有一颗字段是同一颗</em>：宽度是 <c>character_maximum_length</c>（字符数，与契约那颗 32
    /// 直接相等，没有乘 2 这一说）、标度是 <c>numeric_scale</c>、时刻位数是 <c>datetime_precision</c>，
    /// 可空性那一颗在这两家是文本 <c>'YES'/'NO'</c> 而已经由 <see cref="Database.Columns"/> 折成
    /// <c>'1'/'0'</c>。MySQL 一支比 PG 一支又多一处不干净：<b>它的型名与量纲在目录里写在同一颗字段</b>
    /// （<c>column_type</c> 交 <c>varchar(32)</c> ∶ <c>decimal(18,4)</c> ∶ <c>datetime(3)</c>），
    /// 所以那四格在这里是<em>一颗字段加一颗标度</em>——本家因此两颗都问：渲染那一颗证明"同步改成的形"，
    /// 结构化的 <c>character_maximum_length</c> 证明那颗渲染里的数字不是排版而是宽度。</para>
    ///
    /// <para><b>把三支并成一句的可能性在这里排除</b>：并了就两边都只能断言到交集那一格，
    /// 而这一档的题面恰恰是各家那几颗字段。</para></summary>
    static void CatalogSaysTheNewShape()
    {
        if (Database.Family == Database.Target.MySql)
        {
            Assert.Equal("varchar(32)", Column("Title")["store_type"]);
            Assert.Equal("32", DeclaredChars("Title"));
            Assert.Equal("1", Column("Title")["is_nullable"]);
            Assert.Equal("decimal(18,4)", Column("Amount")["store_type"]);
            Assert.Equal("4", Column("Amount")["scale"]);
            Assert.Equal("datetime(3)", Column("PaidAt")["store_type"]);
            Assert.Equal("1", Column("PaidAt")["is_nullable"]);
            Assert.Equal("varchar(40)", Column("Note")["store_type"]);
            Assert.Equal("40", DeclaredChars("Note"));

            return;
        }

        if (Database.Family == Database.Target.PostgreSql)
        {
            Assert.Equal("32", DeclaredChars("Title"));
            Assert.Equal("40", DeclaredChars("Note"));
            Assert.Equal("1", Column("Title")["is_nullable"]);
            Assert.Equal("4", Column("Amount")["scale"]);
            Assert.Equal("1", Column("PaidAt")["is_nullable"]);
            Assert.Equal("3", Column("PaidAt")["scale"]);

            return;
        }

        // max_length 是字节数，nvarchar 是 UTF-16，所以契约里那颗 32 在目录里读回来是 64；
        // 而标度与精度拆在两颗字段里（目录交 numeric ∶ precision 18 ∶ scale 4），只看类型名会放走退化。
        Assert.Equal("64", Column("Title")["max_length"]);
        Assert.Equal("1", Column("Title")["is_nullable"]);
        Assert.Equal("18", Column("Amount")["precision"]);
        Assert.Equal("4", Column("Amount")["scale"]);
        Assert.Equal("1", Column("PaidAt")["is_nullable"]);
        Assert.Equal("3", Column("PaidAt")["scale"]);
        Assert.Equal("80", Column("Note")["max_length"]);
    }

    /// <summary>用户定的那一颗 opt-out：关掉列级同步以后，<b>这一格回到"见表即返"</b>——
    /// 一句 <c>ALTER</c> 都不发，而库里的一切保持原样。这一条钉的是"默认全同步"的反面：
    /// 生产库上不想让同步动列的人，要拿到的是"什么都不发生"，不是"发生一半"。</summary>
    [Fact]
    public void The_opt_out_bit_leaves_the_existing_table_untouched()
    {
        SkipUnlessArrangedHere();

        Database.Ready();

        BuildOldShape();

        var result = Probe(diffColumns: false).SyncStructure();

        Assert.True(result.IsEmpty);
        Assert.Empty(result.CreatedTables);

        // 一句没发 = 目录里还是那个旧形状，而不是"发了但没改成"。
        if (Database.Family == Database.Target.MySql)
        {
            Assert.Equal("varchar(64)", Column("Title")["store_type"]);
            Assert.Equal("64", DeclaredChars("Title"));
            Assert.Equal("2", Column("Amount")["scale"]);
            Assert.Equal("0", Column("PaidAt")["is_nullable"]);
        }
        else if (Database.Family == Database.Target.PostgreSql)
        {
            Assert.Equal("64", DeclaredChars("Title"));
            Assert.Equal("2", Column("Amount")["scale"]);
            Assert.Equal("0", Column("PaidAt")["is_nullable"]);
        }
        else
        {
            Assert.Equal("128", Column("Title")["max_length"]);
            Assert.Equal("2", Column("Amount")["scale"]);
            Assert.Equal("0", Column("PaidAt")["is_nullable"]);
        }

        Assert.Equal("旧标题", Remarks()["Title"]);
        Assert.DoesNotContain("IX_QuickSqlShapeProbe_Title", Database.IndexNames("dbo.QuickSqlShapeProbe"));
        Assert.DoesNotContain("Note", Database.Columns("dbo.QuickSqlShapeProbe").Select(r => r["name"]));
    }

    /// <summary>用户 2026-10-06 加的那颗 opt-in：库里多出一条契约上没有的索引时，<b>默认只进"要人工"，
    /// 开了那一档才真 <c>DROP</c></b>。三趟接在同一张表上跑，判据问的是目录而不是返回值——
    /// "我发过 DROP INDEX"与"那条索引现在不在目录里"是两件事，而这一格要的正是后者。
    ///
    /// <para><b>靶子摆在 <c>Legacy</c> 那一列上</b>：那一列本来就要进"要人工"（不删列），所以这份读数同时钉住
    /// "删索引不会顺带把那一列或那一列的数据带走"。第二趟删掉索引之后第三趟必须零动作——它红一次就意味着
    /// 下一版会在每次同步里把同一颗索引删了又建、建了又删。</para></summary>
    [Fact]
    public void An_extra_index_is_dropped_only_when_that_switch_is_on()
    {
        SkipUnlessArrangedHere();

        Database.Ready();

        BuildOldShape(extraIndex: true);

        const string Extra = "IX_QuickSqlShapeProbe_Legacy";

        Assert.Contains(Extra, Database.IndexNames("dbo.QuickSqlShapeProbe"));

        // ── 第一趟：默认那一档，一条不删，只在名单里指名 ──────────────
        var defaultBit = Probe().SyncStructure();

        Assert.Empty(defaultBit.DroppedIndexes);
        Assert.Single(defaultBit.Refused, r => r.Contains(Extra, StringComparison.Ordinal) && r.Contains("要人工", StringComparison.Ordinal));
        Assert.Contains(Extra, Database.IndexNames("dbo.QuickSqlShapeProbe"));

        // ── 第二趟：开了那一档，目录里从此没有它 ──────────────────────
        var optedIn = Probe(dropIndexes: true).SyncStructure();

        Assert.Equal(["QuickSqlShapeProbe." + Extra], optedIn.DroppedIndexes);
        Assert.DoesNotContain(optedIn.Refused, r => r.Contains(Extra, StringComparison.Ordinal));
        Assert.DoesNotContain(Extra, Database.IndexNames("dbo.QuickSqlShapeProbe"));

        // 只少了那一条索引：契约上声明的还在，那一列与它的值也还在（删索引不顺带动列）。
        Assert.Contains("IX_QuickSqlShapeProbe_Title", Database.IndexNames("dbo.QuickSqlShapeProbe"));
        Assert.Equal("留着", SurvivingRow()["Legacy"]);

        // ── 第三趟：同一颗开关下零动作，"库里多出一条"这件事已经不存在了 ──
        var third = Probe(dropIndexes: true).SyncStructure();

        Assert.True(third.IsEmpty, $"第三趟还在发：{string.Join(" ∶ ", third.DroppedIndexes.Concat(third.CreatedIndexes).Concat(third.AlteredColumns))}");
    }
