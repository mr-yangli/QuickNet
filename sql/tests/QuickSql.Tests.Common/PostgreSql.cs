using System.Data.Common;
using QuickSql.DriverLoading;
using QuickSql.Providers.PostgreSql;

namespace QuickSql.TestInfra;

/// <summary>PostgreSQL 本尊这一系的组装根，与 <see cref="SqlServer"/>、<see cref="Kingbase"/>、<see cref="Dameng"/>、
/// <see cref="MySql"/>、<see cref="TiDb"/>、<see cref="OceanBase"/>、<see cref="OpenGauss"/>、<see cref="GaussDb"/>、
/// <see cref="Highgo"/>、<see cref="ShenTong"/>、<see cref="Gbase8c"/>、<see cref="Gbase8s"/> 同形：
/// <b>provider 由调用方直接构造并交进来</b>（§12.7 F），内核不做 <c>Type.GetType(string)</c>。
///
/// <para>它是 PG 血统的第六颗叶子、也是这一族<b>第一颗本尊</b>（v0.37 第二笔，§9.1 那张表里 PG 本尊从来没有过
/// 一行）。存在的理由与另十一份同档而多两格：① 它是第二颗"正典叶"，而它与第一颗（<see cref="MySql"/>）方向相反
/// ——MySQL 本尊按这一族<em>最新</em>那一侧写文本、派生叶吃它，本尊吃的是血统为<em>最老</em>那一侧攒下的形状，
/// 于是"零覆写的正典叶"在本家第一次带代价（两格选型在同族内方向相反，全文在 <c>PostgreSqlProvider</c> 类注释第三段）；
/// ② 它对 IDENTITY 那一问是这一族里唯一一颗<em>不需要转引</em>的——那一型就是从本尊的版本线上进的标准，
/// 所以真实例第一问从"认不认"换成"现场那台是几"。</para>
///
/// <para>本机没有任何一台 PostgreSQL，清单里那颗 <c>postgresql</c> 键的 assembly（Npgsql，本族五颗键共用的那一份，
/// 而本行是第一颗<em>本尊键</em>）与 <c>Kdbndp</c>、<c>DmProvider</c>、<c>MySqlConnector</c> 一样从未被解析成功过
/// （§13.5 台账整行「未实测」），所以这里同样<em>没有</em> <see cref="SqlServer.DriverFromManifest"/> 的对应物，
/// 有了就会被误读成"这条解析路径验过"。</para>
///
/// <para><b>【2026-09-29 改判 —— 原文照抄在前，改判在后】</b>上面那一段两句今天都不成立了：
/// 本机有了一台可达的 PostgreSQL（用户提供的一台公网实例，凭据只落仓库根那颗本地文件，见
/// <see cref="LocalConnectionFile"/>），而 <c>Npgsql</c> 经 <c>DriverRegistry</c> 解析成功——
/// <c>version()</c> 交回 <c>PostgreSQL 18.3 on x86_64-pc-linux-musl</c>、UTF8、en_US.utf8，
/// <c>GENERATED BY DEFAULT AS IDENTITY</c> 与 <c>RETURNING</c> 当场收（出处
/// <c>obj/logs/v37-pg-recon-1.log</c>）。于是这一档与 <see cref="Xugu"/> 走过的是同一道改判：
/// 这一颗组装根现在有身份了，验的是"清单里那一行能解析出工厂、工厂能连上"，
/// <em>不</em>验"这一家已适配"—— 后者由集成层那条家族缝与集成册的逐条读数证。</para>

/// <para>连接串占位符复用 <see cref="SqlServer.OfflineConnectionString"/>：
/// 这条串永远不被任何驱动解析（<see cref="SqlServer.NoDriverFactory"/> 让碰它的第一行代码就变红）。
/// 第十三家不需要第十三种假配置。<b>本家自本版起也有了自己的真配置</b>（<see cref="TestConnectionString"/>），
/// 两句各走各的：<c>factory</c> 为 null 才落占位串。</para></summary>
public static class PostgreSql
{
    public static PostgreSqlProvider Provider(DbProviderFactory factory) => new(factory);

    /// <summary>离线组装根：<paramref name="factory"/> 为 null 时用 <see cref="SqlServer.NoDriverFactory"/>，
    /// 于是"只生成 SQL"这一条约束在本家与前十二家享有同一个探针。给了 <paramref name="factory"/>
    /// 却不给连接串时取 <see cref="TestConnectionString"/>，与 <see cref="SqlServer.Orm"/> 同一套三分岔
    /// （没配置就问出来，不退回某个"肯定连得上"的库）。</summary>
    public static QuickSqlOrm Orm(DbProviderFactory? factory = null, string? connectionString = null)
        => new(new QuickSqlOrmOptions
        {
            Provider = Provider(factory ?? SqlServer.NoDriverFactory.Instance),
            ConnectionString = connectionString ?? (factory is null ? SqlServer.OfflineConnectionString : TestConnectionString),
        });

    /// <summary>走完整的运行期驱动解析链（清单 → 独立 <c>AssemblyLoadContext</c> → 工厂），与
    /// <see cref="SqlServer.DriverFromManifest"/>、<see cref="Xugu.DriverFromManifest"/>、
    /// <see cref="Sqlite.DriverFromManifest"/> 同一条路、同一条"不许直接 <c>new</c> 工厂"的理由。
    ///
    /// <para><b>本行验的三件事</b>：清单里 <c>"postgresql"</c> 那一颗键读得出、程序集名 <c>Npgsql</c>
    /// 解析得出、交回来的工厂 <c>CreateConnection()</c> 连得上。它<em>不</em>验这一层写的任何一个字
    /// （那是集成册那批用例的活），也<em>不</em>把清单那一行读成"已验证"—— 那一行填的 <c>Npgsql</c>
    /// 是本族协议自己实现的驱动，所以本行不需要"按厂商读数改回程序集名"那一步，这是它与
    /// <c>opengauss</c>／<c>gaussdb</c>／<c>highgo</c>／<c>gbase8c</c> 四颗派生键唯一的差别。</para></summary>
    public static DbProviderFactory DriverFromManifest()
        => DriverRegistry.Load().Factory(PostgreSqlProvider.DriverKey);

    /// <summary>集成测试的第四台目标库：<b>没有默认值</b>，与 <see cref="SqlServer.TestConnectionString"/>、
    /// <see cref="Xugu.TestConnectionString"/> 同一条判据。环境变量 <c>QUICKSQL_POSTGRES_CONNECTION</c> 优先，
    /// 其次仓库根的 <see cref="LocalConnectionFile"/>。两处都没有就抛，消息本身就是配置说明。
    ///
    /// <para><b>为什么要单开一颗变量名</b>：与 <see cref="Xugu.TestConnectionString"/> 那段同一颗理由 ——
    /// 各家目标库共用一颗变量名会让"换一家跑"变成"覆盖另一家的配置"，而 §13.4 要的是
    /// "同一批用例在各家上分别跑一遍"那种可并排的账。</para></summary>
    public static string TestConnectionString
        => ResolveConnectionString() ?? throw new InvalidOperationException(
               $"没有配置 PostgreSQL 集成测试目标库：设环境变量 QUICKSQL_POSTGRES_CONNECTION，或在仓库根放 {LocalConnectionFile}" +
               "（第一行非 # 内容即连接串，形如 Host=…;Port=…;Database=…;Username=…;Password=…）。该文件含本机凭据，不要提交。");

    const string LocalConnectionFile = "quicksql-test.postgres.connection.local.txt";

    static string? ResolveConnectionString()
    {
        var fromEnv = Environment.GetEnvironmentVariable("QUICKSQL_POSTGRES_CONNECTION");

        if (!string.IsNullOrWhiteSpace(fromEnv)) return fromEnv.Trim();

        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            var file = Path.Combine(dir.FullName, LocalConnectionFile);

            if (!File.Exists(file)) continue;

            var line = File.ReadLines(file).FirstOrDefault(l => !l.StartsWith('#') && !string.IsNullOrWhiteSpace(l));

            return line?.Trim();
        }

        return null;
    }
}
