/// <summary>瀚高 HighGo 这颗叶子的 SQL <b>文本</b>（§9.1 行 907 的兑现，PG 血统的第四颗叶子）。
/// 全程 <see cref="SqlServer.NoDriverFactory"/>，与另外八处离线套件同一分工。
///
/// <para><b>这一族没有 golden/highgo/ 目录，判据与 <c>OpenGaussDialectTests</c>／<c>GaussDbDialectTests</c>
/// 同一条</b>：§13.3 那句"同形交给对拍"在这里是<b>五方</b>逐字同形（血统基类、金仓壳、openGauss 壳、
/// GaussDB 壳、本家），再抄一份基线只会多一处要同步的地方。对拍链这一册从四段长成五段，
/// 而本文件相对上一册<em>唯一新增的形状</em>是把血统四叶的两两互读<b>补满</b>
/// （<see cref="The_pairwise_mutual_reads_across_the_PG_lineage_are_now_six_edges_of_six"/>）——
/// 四颗叶子 C(4,2)=6 条边，此前各册只钉住四条（金仓↔openGauss、金仓↔GaussDB、分叉↔分叉、各叶对血统），
/// 本册交出瀚高↔两颗分叉叶的两条。"必然彼此同形"上一笔已经不许只当必然，这一格把那句纪律执行到底。</para>
///
/// <para><b>这份套件证明什么、不证明什么</b>：它证"本仓库没有为瀚高重写一字"，
/// 不证"瀚高接受金仓或另两家的那一字"——本机无一枚实例可问。而本家在这一点上比前三家都<b>空</b>：
/// §9.1 行 907 的坑列一颗方言级分岔都没点名（权限模型、审计策略都在方言层之外），所以它对血统的
/// <c>GENERATED BY DEFAULT AS IDENTITY</c> 既没裁过"落"也没裁过"不落"——那颗问题整个挂在行 904
/// 的 9.2 内核代数上，本行没有代数可挂（<see cref="The_identity_clause_is_emitted_verbatim_on_a_line_that_never_asked"/>）。
/// 真实例到场的第一问因此是"这一家'兼容 PG'兼容的是哪一代 PG"。所以本文件一切断言停在
/// 「离线已钉」档；逐位出处记在 <see cref="CapabilityLedgerTests"/> 的第九本台账。</para>
///
/// <para>这里不进 <c>DialectParityTests</c>：highgo↔另三叶今天<em>零处不同</em>（LEFT JOIN 写句的
/// 拒收文案只差 Kind 那颗词，由 <see cref="The_outer_joined_write_refusal_differs_from_the_sibling_leaf_only_in_the_kind_word"/>
/// 单独点名），把恒等式并进两两配对只会稀释对拍的判据——与 tidb/oceanbase/opengauss/gaussdb 四册同一条处置。</para></summary>
public sealed class HighgoDialectTests
{
    static readonly IDbProvider Provider = Highgo.Provider(SqlServer.NoDriverFactory.Instance);

    static readonly IDbProvider OpenGaussLeaf = OpenGauss.Provider(SqlServer.NoDriverFactory.Instance);

    static readonly IDbProvider GaussDbLeaf = GaussDb.Provider(SqlServer.NoDriverFactory.Instance);

    static readonly IDbProvider KingbaseLeaf = Kingbase.Provider(SqlServer.NoDriverFactory.Instance);

    /// <summary>血统基类的可实例化形态（与 <c>GaussDbFamilyProbe</c> 同一写法）。
    /// <b>Kind 取 <see cref="DbKind.Highgo"/></b>：探针要和叶逐字同形才有意义，而 Kind 会进
    /// <c>EmitJoinedSources</c> 的异常文案 —— 两侧同 Kind、比的恰好是"叶子有没有给基类添一字"。</summary>
    static readonly IDbProvider Family = new HighgoFamilyProbe(DbKind.Highgo, SqlServer.NoDriverFactory.Instance);

    static QuickSqlOrm orm() => Highgo.Orm();

    static QuickSqlOrm openGauss() => OpenGauss.Orm();

    static QuickSqlOrm gaussDb() => GaussDb.Orm();

    static QuickSqlOrm kingbase() => Kingbase.Orm();

    /// <summary>同一颗占位串、同一颗假工厂，provider 换人 —— 让 DDL 段能按 <see cref="IDbProvider"/> 参数化。</summary>
    static QuickSqlOrm ormFor(IDbProvider provider)
        => new(new QuickSqlOrmOptions { Provider = provider, ConnectionString = SqlServer.OfflineConnectionString });

    /// <summary>手搭链取契约的组装根按 provider 换人（本册的参战方是四家：本家、两颗分叉叶、金仓叶）。</summary>
    static QuickSqlOrm ormOf(IDbProvider provider)
        => ReferenceEquals(provider, Provider) ? orm()
            : ReferenceEquals(provider, OpenGaussLeaf) ? openGauss()
            : ReferenceEquals(provider, GaussDbLeaf) ? gaussDb()
            : kingbase();

    /// <summary>带模式的模型：与 <c>GaussDbDialectTests</c> 那一份同一手法（Fluent 覆写而不是新建实体）——
    /// PG 血统的默认模式本来就是 <c>public</c>，这一格量的不是"限定不折叠"而是"契约写 public 时
    /// 产出与契约不写时逐字同"（同一份默认落进同一条发射），它随 DDL 五段一起进对拍。</summary>
    static QuickSqlOrm ormWithSchema(IDbProvider provider)
    {
        var model = new ModelConfiguration();

        model.Entity<Order>().ToTable("QuickSqlOrder", "app");

        return new QuickSqlOrm(
            new QuickSqlOrmOptions { Provider = provider, ConnectionString = SqlServer.OfflineConnectionString },
            new EntitySchemaRegistry(new ContractResolver(provider, model)));
    }

    static Order row(int n) => new()
    {
        CustomerName = "客户" + n,
        CustomerId = n,
        Amount = 10m + n,
        State = OrderState.Paid,
        CreatedAt = new DateTime(2026, 3, 4, 5, 6, 7, 890),
    };

