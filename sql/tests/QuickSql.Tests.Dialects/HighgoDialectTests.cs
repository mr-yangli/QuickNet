    public void Guid_maps_to_the_native_uuid_here_too_as_the_fourth_provider_of_that_claim()
    {
        // 金仓那两条 Guid 用例从 v0.22 起曾是这一格在全仓库唯一的一份主张，v0.36 三笔各来一个复件，
        // 本笔是第四个：同一个类型名、同一个位、来自同一份血统类型表——"3∶4" 的分布里 PG 血统
        // 这边从三家变四家，比值翻成 4∶4，而四边说的仍然同一句话：有原生 uuid，char(36) 是给
        // 没有的库留的退路。它不证"瀚高的 uuid 是 16 字节存"——那一半与另三家同样欠着，
        // 而且第四份复件仍然量不出那一问的答案（"复件涨到第四本仍然量不出新事实"是同一格的形状本身）。
        var id = orm().Schemas.Contract<SessionToken>().Columns
            .Single(c => c.MemberName == nameof(SessionToken.Id));

        Assert.Equal("UUID", Provider.Types.GetStoreType(id));
        Assert.True(Provider.Capabilities.HasFlag(DbCapabilities.Guid_Raw16));
    }

