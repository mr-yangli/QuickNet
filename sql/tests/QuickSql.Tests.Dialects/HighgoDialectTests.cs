    [Fact]
    public void The_identity_clause_is_emitted_verbatim_on_a_line_that_never_asked()
    {
        // 本册措辞与前两册不同档的一格：对 openGauss 与 GaussDB，"IDENTITY 要 PG 10+ 而 9.2 内核
        // 不认"是一颗点过的【推断】、逐笔重裁仍不落；对瀚高，那颗问题<em>不成立</em>——它整个挂在
