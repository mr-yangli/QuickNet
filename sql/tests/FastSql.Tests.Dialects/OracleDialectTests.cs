/// <para><b>这份套件证明什么、不证明什么</b>：它证"本仓库没有为 Oracle 重写一字，且这一族第一次有两颗
/// 逐字同形的真 provider"（本尊与神通），也证"血统那份默认对<em>它自己</em>而言不需要覆写"——
/// 这一格与神通那册的<code>The_seam_was_offered_and_this_leaf_walked_past_it</code> 同一形状而理由相反：
