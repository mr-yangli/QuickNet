    static FastSqlOrm ormWithSchema(IDbProvider provider)
        => LongNamed(provider, "FastSqlOrder", "app");

    /// <summary>改名用的组装根：模式槽位可空，而表名长到 30 字节之上——那是
    /// <see cref="The_two_version_pinned_slots_point_the_same_way_on_one_leaf"/> 的载荷，
