    /// <summary>同一条链在两家各跑一遍、逐字对读（对拍对象是血统探针——本家的主张是"零覆写"，
    /// 与神通那册同一对读方向；同族异形叶由专门的用例量）。<b>不许折任何字形</b>。</summary>
    static void AssertSame(Func<FastSqlOrm, string> chain, string label)
    {
        var familySql = chain(ormFor(Family));
        var oracleSql = chain(orm());

        Assert.True(familySql == oracleSql, $"{label} 这一格同形破了：family = {familySql} ／ oracle = {oracleSql}");
    }

    static void AssertSameProvider(Func<IDbProvider, string> chain, string label)
    {
        var familySql = chain(Family);
        var oracleSql = chain(Provider);

        Assert.True(familySql == oracleSql, $"{label} 这一格同形破了：family = {familySql} ／ oracle = {oracleSql}");
    }

    /// <summary>本家的 CREATE TABLE 换成达梦那一形：只替换缝所 carry 的那一句，别的一个字不动。
    /// <see cref="The_identity_question_on_the_canonical_leaf_asks_a_version_that_settles_two_slots_at_once"/>
    /// 用它做"两颗叶子差的恰好是那一格"的可跑形状。</summary>
    static string oracle_as_dameng(string createTable)
        => createTable.Replace("GENERATED BY DEFAULT AS IDENTITY", "IDENTITY(1,1)");

    /// <summary>血统基类的可实例化形态（与 <c>OracleFamilyProbe</c> 同一写法：空壳）。本册留它而不是改去引用
    /// 达梦那册那一颗，理由与"本尊到场之后还要不要探针"这一格是同一件事：探针量的是 abstract 基类
    /// <em>可实例化</em>，本尊量的是那一族的正典——两格各自要一颗，而今天它们产出相同正是这一册的断言本体。</summary>
    sealed class OracleLeafProbe(DbKind kind, DbProviderFactory factory) : OracleProviderBase(kind, factory);

    static SqlWriter NewWriter(IDbProvider? provider = null)
        => new(new StringBuilder(), [], (provider ?? Provider).Dialect.ParameterPrefix);

    static string Statement(Action<SqlWriter> emit, IDbProvider? provider = null)
    {
        var writer = NewWriter(provider);

        emit(writer);

        return writer.ToSqlString();
    }
