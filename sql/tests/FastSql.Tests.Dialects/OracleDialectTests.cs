/// <para>这里不进 <c>DialectParityTests</c>，而<em>不进的理由与另两册不同向</em>：神通与 PG 本尊不进，
/// 是因为它们与自家基线恒等（并进两两配对没有可判的格子）；本家与对拍里 Oracle 那一格的<em>现任代表</em>
