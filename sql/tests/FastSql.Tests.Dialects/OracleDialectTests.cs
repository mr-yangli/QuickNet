    [Fact]
    public void The_canonical_leaf_enters_no_parity_row_because_the_divergence_is_off_that_ruler()
    {
        // 对拍里 Oracle 那一格站着的是派生叶（达梦）。本家与它在<em>查询面</em>逐字同形，所以配对没有新格子可判；
        // 而那一句真差异在 DDL 面（缝 carry 的 IDENTITY），对拍不比 DDL——于是这把尺子第一次遇到
        // "本格代表与本尊的差异恰好落在它量不到的那一面"。两半都要能跑，否则这句只是修辞。
        (string Label, Func<FastSqlOrm, string> Chain)[] chains =
        [
            ("select", o => o.Select<Order>().ToSql()),
            ("paging", o => o.Select<Order>().OrderBy(x => x.Id).Skip(10).Take(5).ToSql()),
            ("update", o => o.Update<Order>().Set(x => x.Amount, x => x.Amount + 1m).Where(x => x.Id == 7).ToSql()),
            ("plain insert", o => o.Insert(row(1)).ToSql()),
        ];

        foreach (var (label, chain) in chains)
            Assert.True(chain(orm()) == chain(dameng()), $"{label} 这一格本尊与对拍代表应当逐字同形：oracle = {chain(orm())} ／ dameng = {chain(dameng())}");

        // 反面那一半：差异确实存在，只是不在查询面上。
        var oracleCreate = Statement(w => Provider.CodeFirst.EmitCreateTable(w, orm().Schemas.Contract<Order>()));
        var damengCreate = Statement(w => DamengLeaf.CodeFirst.EmitCreateTable(w, dameng().Schemas.Contract<Order>()));

        Assert.NotEqual(oracleCreate, damengCreate);
        Assert.Equal(oracleCreate.Replace("GENERATED BY DEFAULT AS IDENTITY", "IDENTITY(1,1)"), damengCreate);
    }

