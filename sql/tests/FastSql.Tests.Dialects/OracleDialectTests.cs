/// <para><b>这一族没有 golden/oracle/ 目录</b>：判据与 <c>ShenTongDialectTests</c>／<c>PostgreSqlDialectTests</c>
/// 同一条——同形交给逐字对读，再抄一份基线只会多一处要同步的地方。而本家比 PG 那一笔多一层：<b>这一族的
