    [Fact]
    public void The_family_now_has_two_identical_leaves_where_it_used_to_have_only_differing_ones()
    {
        // 此前 Oracle 血统的两两对读只有一种形状：达梦与神通<em>异形</em>（差缝所 carry 的那一句），
        // 另两边各自与基类对。本尊到场补上第一种"两颗真 provider 逐字同形"，于是这一族的三叶比今天变成
        // 同形一对 ∶ 异形一对（本尊—神通同、本尊—达梦差一句），而 PG 与 MySQL 两族的"多颗同形叶"
        // 在那两族是常态、在这一族是第一次——第一次不是因为数量，是因为这一族此前只有两颗叶子而它们不同形。
        var oracleCreate = Statement(w => Provider.CodeFirst.EmitCreateTable(w, orm().Schemas.Contract<Order>()));
        var shenTongCreate = Statement(w => ShenTongLeaf.CodeFirst.EmitCreateTable(w, shenTong().Schemas.Contract<Order>()));

        Assert.Equal(shenTongCreate, oracleCreate);

        (string Label, Func<FastSqlOrm, string> Chain)[] chains =
        [
            ("select", o => o.Select<Order>().ToSql()),
            ("paging", o => o.Select<Order>().OrderBy(x => x.Id).Skip(10).Take(5).ToSql()),
            ("update", o => o.Update<Order>().Set(x => x.Amount, x => x.Amount + 1m).Where(x => x.Id == 7).ToSql()),
            ("plain insert", o => o.Insert(row(1)).ToSql()),
        ];

        foreach (var (label, chain) in chains)
            Assert.True(chain(orm()) == chain(shenTong()), $"{label} 这一格同族两叶应当逐字同形却不同");
    }

    [Fact]
    public void The_seam_was_offered_and_this_leaf_walked_past_it_because_the_default_is_its_own_words()
    {
        // 与神通那册同名而反向的一格：那一颗不走缝的理由是"§9.1 那一行对 IDENTITY 一个字都没有，所以不赌"，
        // 本颗不走缝<em>不需要理由</em>——缝里那颗默认就是这一家自己的标准语法，走它是改自己的话。
        // 于是"文档明写的分岔才配覆写"这条判据在本族有了第三种落点：没有读数可裁（神通）∶ 有读数而裁落（达梦）∶
        // 分岔根本不在场（本尊）。这一格的可跑形状仍是实例类型，不反射 IL。
        Assert.Same(typeof(OracleCodeFirst), Provider.CodeFirst.GetType());
        Assert.Equal("DamengCodeFirst", DamengLeaf.CodeFirst.GetType().Name);

        // 缝每叶子只走一次（基类那颗 ??= 的懒建缓存），本家拿到的实例两次同源。
        Assert.True(ReferenceEquals(Provider.CodeFirst, Provider.CodeFirst));

        // 覆写者数照旧一颗，而"到场而验过这道缝的叶子"从一颗涨到两颗。
        Assert.True(ReferenceEquals(Family.CodeFirst.GetType(), Provider.CodeFirst.GetType()));
    }

    [Fact]
    public void The_two_version_pinned_slots_point_the_same_way_on_one_leaf()
    {
        // 上一笔（v0.37 第二笔）在 PG 本尊上量出"两格版本钉朝向相反 → 三段区间"，并把"零覆写的正典叶带代价"
        // 写成了正典叶的通例。本笔交反例：这一族同样两格版本读数，而分界是同一颗 12.x ——
        // ① 那句 IdentityClause 要 12c 起（本册第 6 格的绝对形状），② 标识符上限在 12.1 之前是 30 字节
        // （<c>OracleCodeFirst</c> 类注释末段那一格今天<em>不判</em>）。同向所以区间两段：
        // < 12.1 那句 IDENTITY 语法错而 30 字节上限同时成立；≥ 12.1 两句一起满足。
        // 可跑的那一半：本仓库对第二格一字不剪——长表名生成的约束名原样发出去。
        var longNamed = Statement(w => Provider.CodeFirst.EmitCreateTable(w, LongNamed(Provider, "FastSqlOrderWithAVeryLongNameForIdentifierLimit").Schemas.Contract<Order>()));

        Checks.Has("GENERATED BY DEFAULT AS IDENTITY", longNamed);
        Checks.Has("CONSTRAINT \"PK_FASTSQLORDERWITHAVERYLONGNAMEFORIDENTIFIERLIMIT\" PRIMARY KEY", longNamed);
        Assert.True(longNamed.IndexOf("PK_FASTSQLORDERWITHAVERYLONGNAMEFORIDENTIFIERLIMIT", StringComparison.Ordinal) > 0);

        // 两格同界的反面：PG 那一族做不到"一次版本读数结清两格"，因为那里两格反向。这里能做到的意思就落在
        // 同一句产出上——本家长名这一句既<em>要</em> ≥12.1 才成立（IDENTITY 那一型），也<em>要</em> ≥12.1 才安全
        // （标识符上限），而它两样都不必分开问。
        Assert.DoesNotContain("IDENTITY(1,1)", longNamed, StringComparison.Ordinal);
    }

    [Fact]
    public void The_identity_question_on_the_canonical_leaf_asks_a_version_that_settles_two_slots_at_once()
    {
        // IDENTITY 那一问的第八次换主语，而它是第一次"问的对象与答案的来源是同一家"：那一型是从本尊的
        // 版本线上进的标准，所以这里既不问"认不认"（神通那一问）、也不问"像到哪一层"（8c 那一问），
        // 只问"现场那台是几"。比 PG 本尊那一问多做一件事：一个版本号回答完，两格一起结清
        // （上一格的可跑形状就是这句）——PG 本尊拿到版本号只结清一格，另一格翻成风险。
        var sql = Statement(w => Provider.CodeFirst.EmitCreateTable(w, orm().Schemas.Contract<Order>()));

        Checks.Has("\"ID\" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL", sql);
        Checks.Absent("IDENTITY(1,1)", sql);
        Checks.Absent("SERIAL", sql);

        // 本尊与派生叶在这一问上的形状差：达梦那一格换了写法，而那一写法与 T-SQL 同形不是巧合；
        // 本家这一格是那句"巧合"的<em>另一端</em>——它发的是标准自己那一形。
        var damengCreate = Statement(w => DamengLeaf.CodeFirst.EmitCreateTable(w, dameng().Schemas.Contract<Order>()));

        Assert.Equal(oracle_as_dameng(sql), damengCreate);
    }

    [Fact]
    public void The_read_side_is_byte_identical_to_the_family_across_five_chains()
    {
        var none = Array.Empty<int>();

        // 五条链挑的全是 Oracle 血统站自家一边的格子：双引号折大写、ROWNUM 一层与两层、恒假 1 = 0、
        // 布尔谓词吃 = 1。本家的绝对形状另钉四枚（相等之外还要知道<em>是什么</em>，否则两边一起漂量不出来）。
        AssertSame(o => o.Select<Order>().ToSql(), "plain select");

        AssertSame(o => o.Select<Order>().OrderBy(x => x.Id).Take(5).ToSql(), "paging take-only one layer");

        AssertSame(o => o.Select<Order>().OrderBy(x => x.Id).Skip(10).Take(5).ToSql(), "paging skip-take two layers");

        AssertSame(o => o.Select<Order>().Where(x => none.Contains(x.Id)).ToSql(), "empty-set 1=0 predicate");

        AssertSame(o => o.Select<Ticket>().Where(t => t.Deleted).ToSql(), "bool predicate = 1");

        var select = orm().Select<Order>().ToSql();

        Checks.Has("FROM \"FASTSQLORDER\" \"T0\"", select);
        Checks.Has("SELECT \"T0\".\"ID\", \"T0\".\"CUSTOMERNAME\"", select);

        var skipTake = orm().Select<Order>().OrderBy(x => x.Id).Skip(10).Take(5).ToSql();

        Checks.Has("SELECT \"FASTSQL$PAGE\".*, ROWNUM \"FASTSQL$ROWNUM\" FROM (", skipTake);
        Checks.Absent("LIMIT", skipTake);
        Checks.Absent("OFFSET", skipTake);
        Checks.Absent("FETCH", skipTake);

        Checks.Has("WHERE 1 = 0", orm().Select<Order>().Where(x => none.Contains(x.Id)).ToSql());
        Checks.Has("\"T0\".\"DELETED\" = 1", orm().Select<Ticket>().Where(t => t.Deleted).ToSql());
    }

    [Fact]
    public void The_write_side_and_the_key_readback_refusal_come_from_the_family_unchanged()
    {
        AssertSame(o => o.Update<Order>().Set(x => x.Amount, x => x.Amount + 1m).Where(x => x.Id == 7).ToSql(), "update");

        AssertSame(o => o.Delete<Order>().Where(x => x.Id == 7).ToSql(), "delete");

        AssertSame(o => o.Insert(row(1)).ToSql(), "plain insert");

        // 写目标自引用：这一族不给 UPDATE 起别名，等号左边两次都是表名自己。
        var update = orm().Update<Order>().Set(x => x.Amount, x => x.Amount + 1m).Where(x => x.Id == 7).ToSql();

        Checks.Has("UPDATE \"FASTSQLORDER\" SET \"AMOUNT\" = \"FASTSQLORDER\".\"AMOUNT\" + :p0 WHERE \"FASTSQLORDER\".\"ID\" = :p1", update);

        // 键回读的拒绝文案在本家换了分量：与前两笔一样逐字出自 OracleKeys，而那句话里的"Oracle 血统"
        // 从今天起是<em>本尊自己</em>的行为——同族另两颗用它时是复述，本颗是用自己的名字说。
        var failure = Checks.Raised<FastSqlException>(() => orm().Insert(row(1)).ExplainKeys());

        Checks.Has("没有可作为结果集发出的", failure.Message);
        Checks.Has("AdoParameter 没有方向位", failure.Message);
        Checks.Absent("RETURNING", orm().Insert(row(1)).ToSql());
        Checks.Absent("OUTPUT", orm().Insert(row(1)).ToSql());
    }

