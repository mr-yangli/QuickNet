        Checks.Has("CREATE TABLE \"public\".\"FastSqlOrder\"", sql);
        Checks.Has("CONSTRAINT \"PK_FastSqlOrder\" PRIMARY KEY", sql);
    }

    [Fact]
    public void The_two_version_pinned_slots_point_in_opposite_directions_on_one_leaf()
    {
        // 本册的裁决格。这一族今天有<em>两格</em>按版本号写文本，而它们的方向相反：
        // IdentityClause 那句 GENERATED BY DEFAULT AS IDENTITY 要 PG 10+（更早的内核上是语法错，
        // PostgreSqlCodeFirst 类注释自陈），而 ROUND/CEIL/FLOOR 上那层 CAST(… AS numeric) 是为
        // PG 14 之前那一档只吃 numeric 才包的（PostgreSqlExpressions 类注释第二段）。
        // 五颗派生叶拿着这两格读出的是"我这台内核认不认"——openGauss 与 GaussDB 是 9.2 一线所以第一格
        // 悬着，瀚高与 8c 连内核代数都没有读数。本尊拿着它们读出的是三段区间：
        // < 10 语法错、10~13 恰合、≥ 14 能跑而那层 CAST 不再必要【推断，两个数都取自厂商文档、区间是本仓库算的】。
        // 于是这一格第一次可指认：<b>同一颗叶子同时发着"要新版本才有的一型"与"为老版本而包的一层"</b>，
        // 而"零覆写的正典叶"的代价就落在后半句——本家一个字都没有为最新那一侧简化。
        var ddl = Statement(w => Provider.CodeFirst.EmitCreateTable(w, orm().Schemas.Contract<Order>()));

        Checks.Has("GENERATED BY DEFAULT AS IDENTITY", ddl);
        Checks.Absent("SERIAL", ddl);

        var functions = orm().Select<Order>()
            .Where(o => Math.Round(o.Amount, 2) > 1m)
            .ToSql();

        Checks.Has("ROUND(CAST(\"t0\".\"Amount\" AS numeric), @p0)", functions);

        // 逐字同形那一半：这两格在本家与在金仓叶上不是"各自绿"，而是同一串字节——
        // 代价因此不是本尊独有的代价，而是整族六份产出共担的（对拍里读不出来，只有本家在场才数得出"六份"）。
        AssertSame(o => o.Select<Order>().Where(x => Math.Round(x.Amount, 2) > 1m).ToSql(), "round with the numeric cast");
    }

    [Fact]
    public void The_identity_question_on_the_canonical_leaf_asks_a_version_not_an_algebra()
    {
        // IDENTITY 那一问在六家这里有第六种形状。金仓行名点过 SERIAL vs IDENTITY 而它的内核版本没有证据；
        // openGauss／GaussDB 共行自己写着 9.2 内核代数（一跳、那一型在 9.x 上是语法错）；瀚高行什么也没写
        // （问都不成立）；8c 行不答、只把自己转引到邻家（两跳、前件是借来的）。本家那颗问题的前件
        // <em>就是这一族自己的定义</em>：那一型是从本尊的版本线上进的 SQL 标准，所以这里既不问"认不认"
        // 也不问"像到哪一层"，只问"现场那台是几"。
        // 判据不因此改：文档明写的分岔才配覆写，而本行没有任何一处明写的分岔——产出仍是血统那一份，
        // 既不钉"这台库认得"也不钉"最新那一代才认得"。
        var sql = Statement(w => Provider.CodeFirst.EmitCreateTable(w, orm().Schemas.Contract<Order>()));

