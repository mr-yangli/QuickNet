        Assert.NotEqual(FastSql.Providers.Highgo.HighgoProvider.DriverKey, FastSql.Providers.PostgreSql.PostgreSqlProvider.DriverKey);
        Assert.NotEqual(FastSql.Providers.Gbase8c.Gbase8cProvider.DriverKey, FastSql.Providers.PostgreSql.PostgreSqlProvider.DriverKey);
