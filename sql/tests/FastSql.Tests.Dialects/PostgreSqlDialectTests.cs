        Checks.Absent("IDENTITY(1,1)", sql);

        // 与 8c 那一册对读一次：两家的产出逐字同，而<b>那一问在两家的形状不同</b>——这一格是本册唯一
        // 一处"同形而不同问"的见证（同掩码不同形是 v0.36 第五笔在 Oracle 血统里立的账，本册是它在
        // <em>同形</em>那一侧的对应物）。
        Assert.Equal(
            Statement(w => Gbase8cLeaf.CodeFirst.EmitCreateTable(w, ormFor(Gbase8cLeaf).Schemas.Contract<Order>())),
            sql);
    }

