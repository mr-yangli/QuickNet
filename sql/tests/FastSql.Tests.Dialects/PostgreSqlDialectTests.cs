/// <summary>PostgreSQL 本尊这颗叶子的 SQL <b>文本</b>（v0.37 第二笔，PG 血统的第六颗叶子、第一颗本尊）。
/// 全程 <see cref="SqlServer.NoDriverFactory"/>，与另外十一处离线套件同一分工。
///
/// <para><b>这一族没有 golden/postgresql/ 目录</b>，而这一格与另五册同判据而<em>理由不同一条</em>：
/// 另五册不添目录是因为"同形交给对拍"（§13.3），本册还多一句——这一族的基线早在 v0.22 就由金仓那份占了
/// （<c>golden/kingbase/</c>，18 份），所以"正典叶要不要自带基线"量的从来不是"它是不是本尊"，
/// 而是"它是不是这一族第一份产出"。反例在同一仓库里躺着：MySQL 那一族的正典叶<em>有</em>目录
/// （<c>golden/mysql/</c>，11 份），因为它是那一族第一颗落地的。这一格由
/// <see cref="The_canonical_leaf_adds_no_baseline_because_the_family_already_has_one"/> 钉住。</para>
///
/// <para><b>本册的裁决格在量什么</b>：同一颗叶子在同一个模型上同时发两格<b>方向相反的版本选型</b>——
/// 建表句里的 <c>GENERATED BY DEFAULT AS IDENTITY</c> 那一型要 PG 10+ 才有【文档】，
/// 而 <c>ROUND</c>/<c>CEIL</c>/<c>FLOOR</c> 上那层 <c>CAST(… AS numeric)</c> 是为了 PG 14 之前那一档
/// 只吃 <c>numeric</c> 才包的【文档】。两格各钉一个版本号，而它们在同一族里第一次相遇：
/// 派生叶拿着这两格时读出的是"我这台内核认不认"，本尊拿着它们读出的是三段区间
/// （&lt; 10 语法错、10~13 恰合、≥ 14 能跑而带一层不再必要的 CAST）【推断，本仓库自己算的】。
/// 见 <see cref="The_two_version_pinned_slots_point_in_opposite_directions_on_one_leaf"/>。
/// 这也是"零覆写的正典叶第一次带代价"那句的可跑形态：本家一个字都没为最新版本简化，
/// 那层 CAST 在本尊上今天是<em>多余而正确</em>的一层。</para>
///
/// <para><b>这份套件证明什么、不证明什么</b>：它证"本仓库没有为 PostgreSQL 本尊重写一字"，
/// 不证"这台库接受它今天发的那一字"——本机无一枚实例可问。而本家在 IDENTITY 那一问上占一种新档：
/// 它是这一族六颗里唯一一颗<em>不需要转引</em>的（那一型就是从本尊的版本线上进的标准，
/// 见 <see cref="The_identity_question_on_the_canonical_leaf_asks_a_version_not_an_algebra"/>）。
/// 真实例第一问因此第七次换主语，而这是第一次换在<b>版本</b>上：另五家问"这台库认不认"，
/// 本家问"这台库是那一型引入之前还是之后"。一切断言停在「离线已钉」档，逐位出处记在
/// <see cref="CapabilityLedgerTests"/> 的第十三本台账。</para>
///
/// <para>这里不进 <c>DialectParityTests</c>：本尊对另五叶今天<em>零处不同</em>，把恒等式并进两两配对
/// 只会稀释对拍的判据——与 tidb／oceanbase／opengauss／gaussdb／highgo／shentong／gbase8c 七册同一条处置。
/// 对拍链的六家（每族一份产出）因此照旧不动：PG 那一份仍是金仓那一份。</para></summary>
public sealed class PostgreSqlDialectTests
{
    static readonly IDbProvider Provider = PostgreSql.Provider(SqlServer.NoDriverFactory.Instance);

    static readonly IDbProvider KingbaseLeaf = Kingbase.Provider(SqlServer.NoDriverFactory.Instance);

    static readonly IDbProvider OpenGaussLeaf = OpenGauss.Provider(SqlServer.NoDriverFactory.Instance);

    static readonly IDbProvider GaussDbLeaf = GaussDb.Provider(SqlServer.NoDriverFactory.Instance);

    static readonly IDbProvider HighgoLeaf = Highgo.Provider(SqlServer.NoDriverFactory.Instance);

    static readonly IDbProvider Gbase8cLeaf = Gbase8c.Provider(SqlServer.NoDriverFactory.Instance);

    /// <summary>血统基类的可实例化形态（与 <c>Gbase8cFamilyProbe</c> 同一写法）。
    /// <b>Kind 取 <see cref="DbKind.PostgreSql"/></b>：探针要和叶逐字同形才有意义，而 Kind 会进
    /// <c>EmitJoinedSources</c> 的异常文案 —— 两侧同 Kind、比的恰好是"叶子有没有给基类添一字"。</summary>
    static readonly IDbProvider Family = new PostgreSqlFamilyProbe(DbKind.PostgreSql, SqlServer.NoDriverFactory.Instance);

    static FastSqlOrm orm() => PostgreSql.Orm();

    static FastSqlOrm kingbase() => Kingbase.Orm();

    static FastSqlOrm openGauss() => OpenGauss.Orm();

    static FastSqlOrm gaussDb() => GaussDb.Orm();

    static FastSqlOrm highgo() => Highgo.Orm();

    static FastSqlOrm gbase8c() => Gbase8c.Orm();

    /// <summary>同一颗占位串、同一颗假工厂，provider 换人 —— 让 DDL 段能按 <see cref="IDbProvider"/> 参数化。</summary>
    static FastSqlOrm ormFor(IDbProvider provider)
        => new(new FastSqlOrmOptions { Provider = provider, ConnectionString = SqlServer.OfflineConnectionString });

    /// <summary>手搭链取契约的组装根按 provider 换人（本册的参战方是六家：本尊与五颗派生叶）。</summary>
    static FastSqlOrm ormOf(IDbProvider provider)
        => ReferenceEquals(provider, Provider) ? orm()
            : ReferenceEquals(provider, OpenGaussLeaf) ? openGauss()
            : ReferenceEquals(provider, GaussDbLeaf) ? gaussDb()
            : ReferenceEquals(provider, HighgoLeaf) ? highgo()
            : ReferenceEquals(provider, Gbase8cLeaf) ? gbase8c()
            : kingbase();

    /// <summary>带模式的模型：与 <c>Gbase8cDialectTests</c> 那一份同一手法（Fluent 覆写而不是新建实体）——
    /// PG 血统的默认模式本来就是 <c>public</c>，这一格量的不是"限定不折叠"而是"契约写 public 时
    /// 产出与契约不写时逐字同"。</summary>
    static FastSqlOrm ormWithSchema(IDbProvider provider)
    {
        var model = new ModelConfiguration();

        model.Entity<Order>().ToTable("FastSqlOrder", "app");

        return new FastSqlOrm(
            new FastSqlOrmOptions { Provider = provider, ConnectionString = SqlServer.OfflineConnectionString },
            new EntitySchemaRegistry(new ContractResolver(provider, model)));
    }

    static Order row(int n) => new()
    {
        CustomerName = "客户" + n,
        CustomerId = n,
        Amount = 10m + n,
        State = OrderState.Paid,
        CreatedAt = new DateTime(2026, 3, 4, 5, 6, 7, 890),
    };

