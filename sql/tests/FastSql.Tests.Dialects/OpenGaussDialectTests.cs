    [Fact]
    public void Guid_maps_to_the_native_uuid_here_too_as_the_second_provider_of_that_claim()
    {
        // 金仓那两条 Guid 用例（CapabilityLedgerTests）从 v0.22 起是这一格在全仓库<em>唯一</em>的一份
        // 主张，今天第一个复件到场：同一个类型名、同一个位、来自同一份血统类型表——
        // "1 ∶ 4" 的分布里 PG 血统这边从一家变两家，而两边说的仍然同一句话：有原生 uuid，
