    [Fact]
    public void The_named_fork_lands_outside_everything_the_provider_emits()
    {
        // 行 902 点名过的分岔只有两颗："CREATE SCHEMA 语义特殊"与"用户即模式"。这一格把它们钉在发射面上：
        // 本仓库不发 CREATE SCHEMA（DDL 三条发射口是建表/加列/改精度/注释，没有建模式那一句），
        // 而"契约没写模式就什么都不写"的默认产出恰是用户即模式的正常形——裸名解析进连接所带的那个模式。
        // 于是这是"文档明写的分岔"判据的第三种落点：分岔明写了，但它落在发射面之外，缝也无从 carry 它
        // （缝 carry 的是列定义那一句）。与达梦"明写分岔而裁不落"（IDENTITY 那颗的 openGauss 侧读法）
        // 与瀚高"无明写分岔可裁"并成三档。
        var sql = Statement(w => Provider.CodeFirst.EmitCreateTable(w, orm().Schemas.Contract<Order>()));

        Checks.Absent("CREATE SCHEMA", sql);
        Checks.Absent("\"PUBLIC\".", sql);
        Checks.Absent("\"DBO\".", sql);

        // 用户即模式的反面那半：契约<em>写了</em>模式时本族照写（限定与折叠同口，"app" 出成 "APP"）——
        // "用户即模式"不禁止限定，它只说裸名归谁。所以这颗分岔对两种产出都不构成覆写理由。
        var qualified = Statement(w => Provider.CodeFirst.EmitCreateTable(w, ormWithSchema(Provider).Schemas.Contract<Order>()));

        Checks.Has("CREATE TABLE \"APP\".\"FASTSQLORDER\" (", qualified);
    }

    // ── 内部 ─────────────────────────────────────────────────────────

    /// <summary>同一条链在两家各跑一遍、逐字对读（对拍对象是血统探针——本家的主张是"零覆写且用了类型级
    /// 继承"，与达梦那册的 leaf vs Family 同一对读方向；同族叶异形由专门的用例量）。
    /// <b>不许折任何字形</b>——引号都不差才是这一对的断言。</summary>
    static void AssertSame(Func<FastSqlOrm, string> chain, string label)
    {
        var familySql = chain(ormFor(Family));
        var shenTongSql = chain(orm());

        Assert.True(familySql == shenTongSql, $"{label} 这一格同形破了：family = {familySql} ／ shentong = {shenTongSql}");
    }

    static void AssertSameProvider(Func<IDbProvider, string> chain, string label)
    {
        var familySql = chain(Family);
        var shenTongSql = chain(Provider);

        Assert.True(familySql == shenTongSql, $"{label} 这一格同形破了：family = {familySql} ／ shentong = {shenTongSql}");
    }

    /// <summary>血统基类的可实例化形态（与 <c>OracleFamilyProbe</c> 同一写法：空壳，
    /// 探针存在的唯一理由是上面那两条"叶子没给基类添一字"与"拒绝文案同血统词"的空壳证据。</summary>
    sealed class ShenTongFamilyProbe(DbKind kind, DbProviderFactory factory) : OracleProviderBase(kind, factory);

    static SqlWriter NewWriter(IDbProvider? provider = null)
        => new(new StringBuilder(), [], (provider ?? Provider).Dialect.ParameterPrefix);

    static string Statement(Action<SqlWriter> emit, IDbProvider? provider = null)
    {
        var writer = NewWriter(provider);

        emit(writer);

        return writer.ToSqlString();
    }

    /// <summary>手搭带 JOIN 的合并 UPDATE（形状与 <c>DamengDialectTests</c> 的 MergedUpdate 同构，
    /// 按 provider 参数化供两家互读）。<b>在这一族它唯一的用途是"抛得准不准"</b>：前两族（T-SQL、PG）
    /// 拿它量文本，这里发射必然在 <c>EmitJoinedSources</c> 那一句上红——JOIN 种类在这一族不构成差异
    /// （LEFT 与 INNER 同拒），所以这里只喂 INNER 一种。</summary>
    static FastSqlException MergedUpdateFailure(IDbProvider owner)
        => Checks.Raised<FastSqlException>(() => MergedUpdate(nameof(Order.Amount), owner, JoinKind.Inner));

    static DialectSql MergedUpdate(string member, IDbProvider owner, JoinKind kind)
    {
        var contract = ormFor(owner).Schemas.Contract<Order>();

        var stored = new TableRef(0, owner.Dialect.WriteTargetAlias(contract.Table), contract.Table, contract);
        var side = new TableRef(1, "t1", contract.Table);

        var key = contract.PrimaryKey[0];
        var set = contract.Columns.Single(c => c.MemberName == member);
        ColumnContract[] columns = [key, set];

        var rows = new IReadOnlyList<SqlExpression>[2];

        for (var r = 0; r < rows.Length; r++)
            rows[r] = [new ParameterValue(7 + r, key), new ParameterValue("值", set)];

        var on = new SqlBinaryExpression(BinaryOperator.Equal,
            new ColumnExpression(stored, key), new ColumnExpression(side, key));

        var ast = new UpdateStatement
        {
            Table = stored,
            Sets = [new SetClause(set, new ColumnExpression(side, set))],
            Where = new SqlBinaryExpression(BinaryOperator.Equal, new ColumnExpression(stored, key), new ParameterValue(7, key)),
            Joins = [new JoinClause(kind, new SourceRows(side, columns, rows), on)],
        };

        var writer = NewWriter(owner);

        owner.Dialect.Emit(in ast, writer);

        return new DialectSql(writer.ToSqlString(), writer.Parameters);
    }
