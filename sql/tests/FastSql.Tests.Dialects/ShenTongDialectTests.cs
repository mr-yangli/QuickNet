/// <summary>神通 Oscar 这颗叶子的 SQL <b>文本</b>（§9.1 行 902 的兑现，v0.36 第五笔「到场、有缝、不覆」
/// 裁决的落地日套件）。全程 <see cref="SqlServer.NoDriverFactory"/>，与另外九处离线套件同一分工。
///
/// <para><b>这一族没有 golden/shentong/ 目录</b>：判据与 <c>TiDbDialectTests</c>／<c>OpenGaussDialectTests</c>
/// 那几册同一条——同形交给对拍，再抄一份基线只会多一处要同步的地方。但本册的对拍链与 PG 四叶那一族<em>不同向</em>：
/// leaf == 血统逐字同形（缝开着而没走过去），而同族的另一颗叶子（达梦）与它<em>不同形</em>——
/// 这是本仓库第一次有同族两叶的异形对读（<see cref="The_sibling_leaf_under_the_same_seam_differs_by_exactly_the_clause_the_seam_carries"/>）。
/// 此前所有跨叶对读都是恒等或只差 Kind 那颗词，"同族两叶各自与基类对"不再等于"两叶彼此对"。</para>
///
/// <para><b>这份套件证明什么、不证明什么</b>：它证"本仓库没有为神通重写一字，且这道缝第一次被一颗到场
/// 的叶子<em>选择</em>不走"——注意这个"选择"的分量：PG 与 MySQL 两族的零覆写里有一半是结构决定的
/// （从来没有可覆的缝），本家是不覆写第一次真的是一种裁决而不是既成事实。它不证"神通认得
/// <c>GENERATED BY DEFAULT AS IDENTITY</c>"——本行坑列对 IDENTITY 一个字都没有，那一形能否落进
/// 这台库是真实例到场的第一问（§14 行 2044 本笔注）。</para>
///
/// <para>这里不进 <c>DialectParityTests</c>：shentong↔血统是恒等式（并进两两配对会稀释判据，与 tidb／
/// oceanbase／opengauss／gaussdb／highgo 五册同一条处置），而 shentong↔dameng 是"恰好差一句"的
/// 替换式——那格由下面点名的用例逐字钉住，恒等与替换两种判据不混进同一张对拍表。
/// 逐位出处记在 <see cref="CapabilityLedgerTests"/> 的第十本台账。</para></summary>
public sealed class ShenTongDialectTests
{
    static readonly IDbProvider Provider = ShenTong.Provider(SqlServer.NoDriverFactory.Instance);

    static readonly IDbProvider DamengLeaf = Dameng.Provider(SqlServer.NoDriverFactory.Instance);

    /// <summary>血统基类的可实例化形态（与 <c>OracleFamilyProbe</c> 同一写法，见 <c>DamengDialectTests</c>）。
    /// <b>Kind 取 <see cref="DbKind.ShenTong"/></b>：探针要和叶逐字同形才有意义，而 Kind 会进
    /// <c>EmitJoinedSources</c> 的异常文案——两侧同 Kind、比的恰好是"叶子有没有给基类添一字"。</summary>
    static readonly IDbProvider Family = new ShenTongFamilyProbe(DbKind.ShenTong, SqlServer.NoDriverFactory.Instance);

    static FastSqlOrm orm() => ShenTong.Orm();

    static FastSqlOrm dameng() => Dameng.Orm();

    /// <summary>同一颗占位串、同一颗假工厂，provider 换人——让 DDL 段能按 <see cref="IDbProvider"/> 参数化。</summary>
    static FastSqlOrm ormFor(IDbProvider provider)
        => new(new FastSqlOrmOptions { Provider = provider, ConnectionString = SqlServer.OfflineConnectionString });

    /// <summary>带模式的模型：与 <c>DamengDialectTests</c> 那一份同一手法（Fluent 覆写而不是新建实体）。
    /// 这一格在 Oracle 血统量的不是"限定不折叠"而是"限定与折叠同口"（模式名 app 出来必须是 "APP"），
    /// 而它对本家多带一层意思：契约写模式时产出的正是行 902 那颗"用户即模式"分岔之外的第二种形状（见
    /// <see cref="The_named_fork_lands_outside_everything_the_provider_emits"/>）。</summary>
    static FastSqlOrm ormWithSchema(IDbProvider provider)
    {
        var model = new ModelConfiguration();

        model.Entity<Order>().ToTable("FastSqlOrder", "app");

        return new FastSqlOrm(
            new FastSqlOrmOptions { Provider = provider, ConnectionString = SqlServer.OfflineConnectionString },
            new EntitySchemaRegistry(new ContractResolver(provider, model)));
    }

    static Order row(int n) => new()
    {
        CustomerName = "客户" + n,
        CustomerId = n,
        Amount = 10m + n,
        State = OrderState.Paid,
        CreatedAt = new DateTime(2026, 3, 4, 5, 6, 7, 890),
    };

    [Fact]
    public void Kind_and_driver_key_are_the_only_two_things_this_leaf_brings_of_its_own()
    {
        // 这一条钉的是"叶子到底带了什么进来"：一颗枚举值（v0.x 就占着位，本笔零 Core 改动）、
        // 一颗清单键，其余全部继承。清单键 "shentong" 的 assembly 是 §9.1 行 902 第四列的原词（Oscar）——
        // 与 Kdbndp／DmProvider 同一档的文档口径名，而它连"是不是程序集名"都只有那一列支持（来路全文在
        // 清单 $comment 与 <c>ShenTongProvider</c> 类注释第四段）。达梦的键同族而不同源：两颗 Oracle 血统的键，
        // 两份互不相同的文档口径名——这一格与 PG 血统"三颗键一份 assembly"正好对面。
        Assert.Equal(DbKind.ShenTong, Provider.Kind);
        Assert.Equal("shentong", FastSql.Providers.ShenTong.ShenTongProvider.DriverKey);
        Assert.NotEqual(FastSql.Providers.Dameng.DamengProvider.DriverKey, FastSql.Providers.ShenTong.ShenTongProvider.DriverKey);
    }

    [Fact]
    public void The_capability_mask_is_inherited_verbatim_six_bits_not_one_less_not_one_more()
    {
        // 三段链的掩码半：leaf == 同族分叉叶 == 血统。Oracle 血统这一档只有 6 位，
        // 每一位都是"代码今天真的走到那条语句"攒出来的（基类注释那份逐位对账），本家今天一位不翻案也不添。
        Assert.Equal(DamengLeaf.Capabilities, Provider.Capabilities);
        Assert.Equal(Family.Capabilities, Provider.Capabilities);

        Assert.Equal(
            DbCapabilities.Paging_RowNum | DbCapabilities.Guid_Char36 | DbCapabilities.Schemas |
            DbCapabilities.CaseSensitive_Identifiers | DbCapabilities.Comment_On_Column |
            DbCapabilities.Alter_Column_Precision,
            Provider.Capabilities);

        // 这一族"刻意不声明"的那几位同样不翻案：Returning 抛在 OracleKeys（本册第 4 格量它），
        // Boolean_Type 声明了就等于让 IS TRUE 走错分支（第 9 格量 = 1 那一形），
        // Upsert_MergeInto 库里存在而本仓库一行没发过，MultiStatement 与 PG 系同一条理由。
        Assert.False(Provider.Capabilities.HasFlag(DbCapabilities.Returning));
        Assert.False(Provider.Capabilities.HasFlag(DbCapabilities.Boolean_Type));
        Assert.False(Provider.Capabilities.HasFlag(DbCapabilities.Upsert_MergeInto));
        Assert.False(Provider.Capabilities.HasFlag(DbCapabilities.MultiStatement));
        Assert.False(Provider.Capabilities.HasFlag(DbCapabilities.MultiResultSets));
    }

    [Fact]
    public void The_read_side_is_byte_identical_to_the_family_across_five_chains()
    {
        var none = Array.Empty<int>();

        // 五条链挑的全是 Oracle 血统站自家一边的格子：双引号折大写（select）、ROWNUM 一层包装（take）、
        // ROWNUM 两层伪列（skip+take）、恒假是 1 = 0（这一族没有布尔字面量）、真布尔谓词吃 = 1
        // （PG 那四家发 IS TRUE，这里反过来）。逐字相等比"各自绿"多证一件事：
        // 这一家没有任何一处会跟着血统那一份样本一起漂。
        AssertSame(o => o.Select<Order>().ToSql(), "plain select");

        AssertSame(o => o.Select<Order>().OrderBy(x => x.Id).Take(5).ToSql(), "paging take-only one layer");

        AssertSame(o => o.Select<Order>().OrderBy(x => x.Id).Skip(10).Take(5).ToSql(), "paging skip-take two layers");

        AssertSame(o => o.Select<Order>().Where(x => none.Contains(x.Id)).ToSql(), "empty-set 1=0 predicate");

        AssertSame(o => o.Select<Ticket>().Where(t => t.Deleted).ToSql(), "bool predicate = 1");

        // 本家侧各钉一枚绝对形状（相等之外还要知道<em>是什么</em>，否则两边一起漂就量不出来）。
        var select = orm().Select<Order>().ToSql();

        Checks.Has("FROM \"FASTSQLORDER\" \"T0\"", select);
        Checks.Has("SELECT \"T0\".\"ID\", \"T0\".\"CUSTOMERNAME\"", select);

        var skipTake = orm().Select<Order>().OrderBy(x => x.Id).Skip(10).Take(5).ToSql();

        Checks.Has("SELECT \"FASTSQL$PAGE\".*, ROWNUM \"FASTSQL$ROWNUM\" FROM (", skipTake);
        Checks.Absent("LIMIT", skipTake);
        Checks.Absent("OFFSET", skipTake);

        Checks.Has("WHERE 1 = 0", orm().Select<Order>().Where(x => none.Contains(x.Id)).ToSql());
        Checks.Has("\"T0\".\"DELETED\" = 1", orm().Select<Ticket>().Where(t => t.Deleted).ToSql());
    }

    [Fact]
    public void The_write_side_is_byte_identical_to_the_family_including_the_key_readback_refusal()
    {
        AssertSame(o => o.Update<Order>().Set(x => x.Amount, x => x.Amount + 1m).Where(x => x.Id == 7).ToSql(), "update");

        AssertSame(o => o.Delete<Order>().Where(x => x.Id == 7).ToSql(), "delete");

        AssertSame(o => o.Insert(row(1)).ToSql(), "plain insert");

        // 写目标自引用（这一族不能起别名，UPDATE/DELETE 用自己的表名）——本家族 WriteTargetAlias 的形状半。
        var update = orm().Update<Order>().Set(x => x.Amount, x => x.Amount + 1m).Where(x => x.Id == 7).ToSql();

        Checks.Has("UPDATE \"FASTSQLORDER\" SET \"AMOUNT\" = \"FASTSQLORDER\".\"AMOUNT\" + :p0 WHERE \"FASTSQLORDER\".\"ID\" = :p1", update);
        Checks.Absent("\"FASTSQLORDER\" \"T0\"", update);

        // 键回读的拒绝：leaf 与血统的文案逐字同（消息里带的是"Oracle 血统"那一词而不是 Kind——与
        // EmitJoinedSources 那句"{Kind} 的写语句…"正对面，两种拒绝文案的取名法在这一族第一次被同一册分开钉住）。
        var leafFailure = Checks.Raised<FastSqlException>(() => ShenTong.Orm().Insert(row(1)).ExplainKeys());
        var familyFailure = Checks.Raised<FastSqlException>(() => ormFor(Family).Insert(row(1)).ExplainKeys());

        Assert.Equal(familyFailure.Message, leafFailure.Message);
        Checks.Has("没有可作为结果集发出的", leafFailure.Message);
        Checks.Has("AdoParameter 没有方向位", leafFailure.Message);

        var plain = orm().Insert(row(1)).ToSql();

        Checks.Absent("RETURNING", plain);
        Checks.Absent("OUTPUT", plain);
    }

    [Fact]
    public void The_DDL_side_is_byte_identical_to_the_family_whole_statements_including_the_identity_clause()
    {
        // 与达梦那册的《The_leaf_changes_only_the_identity_clause》同一格而裁向相反：那颗叶改了 DDL，
        // 本家连 DDL 都不改——缝开着，整段 CREATE TABLE 原样出自血统。
        AssertSameProvider(
            p => Statement(w => p.CodeFirst.EmitCreateTable(w, ormFor(p).Schemas.Contract<Order>()), p),
            "create table");

        AssertSameProvider(
            p => Statement(w => p.CodeFirst.EmitCreateTable(w, ormWithSchema(p).Schemas.Contract<Order>()), p),
            "create table with explicit schema");

        AssertSameProvider(
            p =>
            {
                var contract = ormFor(p).Schemas.Contract<Order>();
                var note = contract.Columns.Single(c => c.MemberName == nameof(Order.Note));

                return Statement(w => p.CodeFirst.EmitAddColumn(w, contract.Table, note), p);
            },
            "add column");

        AssertSameProvider(
            p =>
            {
                var contract = ormFor(p).Schemas.Contract<Order>();
                var amount = contract.Columns.Single(c => c.MemberName == nameof(Order.Amount));

                return Statement(w => p.CodeFirst.EmitAlterColumnPrecision(w, contract.Table, amount), p);
            },
            "alter column precision");

        AssertSameProvider(
            p =>
            {
                var contract = ormFor(p).Schemas.Contract<Order>();
                var commented = contract.Columns.Single(c => c.MemberName == nameof(Order.CustomerName)) with { Comment = "客户名" };

                return Statement(w => Assert.True(p.CodeFirst.TryEmitColumnComment(w, contract.Table, commented)), p);
            },
            "column comment");

        // 绝对形状四枚：IDENTITY 那一形（本笔的裁决本体）、类型名、默认不写模式、CONSTRAINT 主键折大写。
        var sql = Statement(w => Provider.CodeFirst.EmitCreateTable(w, orm().Schemas.Contract<Order>()));

        Checks.Has("\"ID\" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL", sql);
        Checks.Absent("IDENTITY(1,1)", sql);
        Checks.Absent("SERIAL", sql);
        Checks.Has("CREATE TABLE \"FASTSQLORDER\" (", sql);
        Checks.Has("CONSTRAINT \"PK_FASTSQLORDER\" PRIMARY KEY (\"ID\")", sql);
    }

    [Fact]
    public void The_sibling_leaf_under_the_same_seam_differs_by_exactly_the_clause_the_seam_carries()
    {
        // 本文件的第一格新形状：同族两叶的<em>异形</em>对读。此前仓库里所有跨叶对读都是恒等
        // （同基类必同形）或只差 Kind 那颗词（拒收文案），而这一格是"替换一处恰好等于另一处"——
        // 达梦的 CREATE TABLE 就是本家的 CREATE TABLE 换掉缝所 carry 的那一句，别的一个字不差。
        // "必然同形"在这个仓库从来不算断言，"必然异形且差在已知那一格"同样不算——所以两条都要落成可跑。
        var shenTongCreate = Statement(w => Provider.CodeFirst.EmitCreateTable(w, orm().Schemas.Contract<Order>()));
        var damengCreate = Statement(w => DamengLeaf.CodeFirst.EmitCreateTable(w, dameng().Schemas.Contract<Order>()));

        Assert.Equal(shenTongCreate.Replace("GENERATED BY DEFAULT AS IDENTITY", "IDENTITY(1,1)"), damengCreate);

        // 另一半：差的只有 DDL 那一段——读、写两条链在两叶之间逐字同形（Kind 不进这些产出）。
        var shenTongOrm = orm();
        var damengOrm = dameng();

        (string Label, Func<FastSqlOrm, string> Chain)[] chains =
        [
            ("select", o => o.Select<Order>().ToSql()),
            ("paging", o => o.Select<Order>().OrderBy(x => x.Id).Skip(10).Take(5).ToSql()),
            ("update", o => o.Update<Order>().Set(x => x.Amount, x => x.Amount + 1m).Where(x => x.Id == 7).ToSql()),
            ("plain insert", o => o.Insert(row(1)).ToSql()),
        ];

        foreach (var (label, chain) in chains)
            Assert.True(chain(shenTongOrm) == chain(damengOrm), $"{label} 这一格同族两叶应当逐字同形却不同：shentong = {chain(shenTongOrm)} ／ dameng = {chain(damengOrm)}");
    }

    [Fact]
    public void The_seam_was_offered_and_this_leaf_walked_past_it()
    {
        // "零覆写者"的第三档第一次到场：PG 与 MySQL 两族的叶子是"从未有过可覆的路"（构造直 new 具体类），
        // 这一族的缝一直是开的（达梦走进去过）。所以本家钉的不是"没有缝"而是"有缝而没过"——
        // 能跑的形态是：叶子的 CodeFirst 实例类型就是血统那颗 OracleCodeFirst（不反射 IL，比对象本身），
        // 与达梦叶子的 DamengCodeFirst（internal，只能按名读）第一次在"叶子发的 CodeFirst 类型"上分出两种。
        Assert.Same(typeof(OracleCodeFirst), Provider.CodeFirst.GetType());
        Assert.Same(typeof(OracleCodeFirst), Family.CodeFirst.GetType());
        Assert.Equal("DamengCodeFirst", DamengLeaf.CodeFirst.GetType().Name);

        // 基类那颗懒建缓存（??=）：两次取必须是同一实例——缝每叶子只走一次，不是每次访问重走。
        Assert.True(ReferenceEquals(Provider.CodeFirst, Provider.CodeFirst));

        // 产出仍出自血统：叶与探针逐字同形（与上面 DDL 格互为正反：那格比语句，这格比类型与实例）。
        var leaf = Statement(w => Provider.CodeFirst.EmitCreateTable(w, orm().Schemas.Contract<Order>()));
        var family = Statement(w => Family.CodeFirst.EmitCreateTable(w, ormFor(Family).Schemas.Contract<Order>()));

        Assert.Equal(family, leaf);
    }

    [Fact]
    public void The_joined_write_refusal_differs_from_the_sibling_leaf_only_in_the_kind_word()
    {
        // 这一族的合并档对 INNER 也拒（OracleDialect.EmitJoinedSources 不看 JoinKind，SupportsJoinedWrites 为 false
        // 的一族任何 JOIN 都到不了发射——日常路径在 EntityTracker 第一道闸就退桶），所以与 PG 血统那两册
        // "INNER 成功侧 + LEFT 拒收"的形状不同：这里只有拒收侧，达梦那册的 MergedUpdate 就是先例。
        // Kind 例外的形状与 GaussDb 那册同一：两家同闸、差异恰好一颗词。对读对象是同族叶——
        // 血统词写进消息的那一格（键回读）在同一条用例的反面：这里进消息的是 Kind。
        var familyFailure = MergedUpdateFailure(Family);
        var shenTongFailure = MergedUpdateFailure(Provider);
        var damengFailure = MergedUpdateFailure(DamengLeaf);

        Assert.Equal(familyFailure.Message, shenTongFailure.Message);
        Assert.StartsWith("ShenTong ", shenTongFailure.Message, StringComparison.Ordinal);
        Assert.Equal(damengFailure.Message.Replace("Dameng", "ShenTong", StringComparison.Ordinal), shenTongFailure.Message);
        Checks.Has("MERGE INTO", shenTongFailure.Message);
    }

    [Fact]
    public void Slot_shapes_and_the_null_bulk_slot_come_from_the_family_unchanged()
    {
        // 血统在这一家的形状半：恒假/恒真不是布尔字面量（五家里 PG 那族改写了这两颗，这一族不）、
        // 参数前缀是冒号（两家 ∶ 三家，基类注释那格）、LIKE 转义跟着多数派、Bulk 交回 null 而预算走兜底。
        Assert.Equal("1 = 0", Provider.Dialect.EmptySetPredicate);
        Assert.Equal("1 = 1", Provider.Dialect.AlwaysTruePredicate);
        Assert.Equal(':', Provider.Dialect.ParameterPrefix);
        Assert.Equal('\\', Provider.Expressions.LikeEscapeCharacter);
        Assert.Null(Provider.Bulk);

        // 兜底分支的第二个消费者（虚谷是第一个）：600 行 × 7 列按预算 100 切 → 每块 12 行、50 块。
        // 这一格与达梦册同名数字逐一对读——本家到场让"没有可举证的预算数字"这一档在这一族有了第二份产出，
        // 而两份产出的<em>理由</em>同出一源（基类注释那一段），不像 Oracle ∶ 虚谷那两份各有各路。
        var plan = orm().InsertRange(Enumerable.Range(1, 600).Select(static n => row(n)).ToArray()).Explain();

        Assert.Equal(100, plan.ParameterBudget);
        Assert.Equal(7, plan.ColumnsPerRow);
        Assert.Equal(12, plan.RowsPerStatement);
        Assert.Equal(50, plan.Chunks.Count);

        var damengPlan = dameng().InsertRange(Enumerable.Range(1, 600).Select(static n => row(n)).ToArray()).Explain();

        Assert.Equal(damengPlan.Chunks.Count, plan.Chunks.Count);
        Assert.Equal(damengPlan.ParameterBudget, plan.ParameterBudget);
    }

