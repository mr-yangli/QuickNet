    {
        // 这一条是本档存在的全部理由，而离线册一条都判不到：那句文本在真驱动上执行得过吗，
        // 以及"库里没有的那一颗键"到底落成了新行还是什么都没落。MySQL 那一支还捎带一个版本地板
        // ——行别名写法要 8.0.19+，本家活库（8.4.8）跑绿才算落过地，TiDB ∶ OceanBase 那两家仍然记未实测。
        Database.Ready();
        Assert.SkipWhen(!DeclaresUpsert, NoUpsertTail);

        var note = tag("upsert");
        var landed = await Seed(note, 4);
        var absent = landed[^1];

        // 那颗"库里没有的键"取<em>刚刚还在、现在已经不在了</em>的那一颗，而不是往键空间顶上造一颗新的：
        // <c>INSERT</c> 里写显式键<em>不会推进</em> PG 那颗 identity 序列（GENERATED BY DEFAULT 只在不给值时取值），
        // 顶上那一颗因此悬在序列前面，同一座表后来一次批量插入撞上它就是 <c>23505 duplicate key</c>。
        // 本条第一趟红的就是这一格，而红的是<em>另一册</em>的用例（插入那一族的 2000 行 COPY）
        // 【实测·obj/logs/v40-postgresql-upsert-full.log 那次 BulkPathTests.The_wall_clock 一支】。
        // MySQL 那一支没有这一格：AUTO_INCREMENT 收到更大的显式值会把计数器一起顶上去。
        await Orm.DeleteRange(Keys([absent])).WithBulk(BulkWriteMethod.Merged)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken);

