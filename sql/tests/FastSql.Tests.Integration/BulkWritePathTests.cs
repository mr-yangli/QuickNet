/// <summary>批量写链（<c>orm.UpdateRange</c> / <c>orm.DeleteRange</c>，§12.1 的写侧扩展）在活库上的读数。
///
/// <para><b>这一册存在的理由全是"文本层看不见的那几件事"</b>：离线册 <c>BulkWriteLayerTests</c> 已经钉死了
/// 档位判据、SET/WHERE 的列归属、IN 清单的形状、十六家表态的手写台账与复合键拒收 —— 那些在零驱动的产物上
/// 就能判。这里判的是它判不到的三件：并进来的多条语句<em>在真驱动上执行得过吗</em>、落进库里的每一格是不是
/// 入参那一格、以及全局过滤器折进谓词之后<em>真的筛掉了行</em>（离线册的抬头那句"库里筛掉了什么行归集成套件"
/// 欠的就是这一格）。</para>
///
/// <para><b>本册最重的一条是 <see cref="Auto_takes_the_merged_tier_only_where_the_family_declared_it"/></b>：
/// <c>IBulkStrategy.SupportsMergedStatements</c> 那一句表态在十六家手册里是<em>声称</em>，只有活库把它跑红或跑绿
/// 才算落过地。哪一家跑红，改的是那一家的表态而不是这条断言（§13.4 的纪律：读数说话）。</para>
///
/// <para><b>姿势与 <see cref="BulkPathTests"/> 同一条：只碰自己那一批</b>。每条用例带本次运行独占的标签前缀
/// （<see cref="Batch"/>），断言一律按标签或按自增键过滤，所以库里别人（包括上一轮的自己）留下的行不影响本册。
/// <see cref="DeleteRange"/> 那几条删的是<em>本用例刚种下去</em>的那几行 —— 那不是"删夹具"，
/// 而是那条链唯一的判法；人工清理按 <c>LIKE 'fastsql-writebulk/%'</c>。</para>
///
/// <para><b>裁判取数：一条用例一次开连接</b>。第一趟不是这样写的（逐行 <c>Row(id)</c>），而它在虚谷那一家
/// 把<em>整套件</em>打红了：<c>XuguClient.XGConnection.Open()</c> 抛 <c>[E34305] InValidConnectionException:
/// 指定的连接串无效</c>，从本册起一路红到后面五个类，而那台实例的会话上限就在本册那一段被顶穿
/// 【实测·<c>obj/logs/v40-xugu-integration-full.log</c> 37 红 ∶ 把本册从套件里取出去同一趟 147 条全绿】。
/// <b>下面这段是把那次红追到底以后添的，上面那句"被顶穿"留着当案底而它的原因不在本册</b>：
/// 上限是真的，顶穿它的不是"连接开得多了"。五支探针各问一件事，同一串、同一进程
/// 【实测·<c>obj/probe-xugu/Program.cs</c>，读数在 <c>obj/logs/v40-xugu-release-shapes.log</c>】：
/// ① 用完即还（<c>Open → Close → Dispose</c>）累计 7 500 次不红；② 300 条<em>同时</em>在场不红；
/// ③ 只换"还"的写法：<c>Close()</c> 单用与 <c>Close()</c>+<c>DisposeAsync()</c> 两支各跑满 3 000 轮不红，
/// 而 <c>Dispose()</c> 单用与 <c>DisposeAsync()</c> 单用两支都<b>正好在第 1000 次 Open 红</b>，
/// 红的位置与第五支"开完根本不还、只交给终结器"同一颗数。<b>这一族驱动的 <c>Dispose</c> 覆写不还会话，
/// 只有 <c>Close</c> 还</b>，会话要等终结器跑过才交回 —— 而内核的会话走的正是 <c>await using</c>
/// （<c>AdoExecutor.Session.DisposeAsync</c>），于是整套件每发一句就留一条在场未还的会话：
/// 147 条那一趟是<em>贴着</em>那道线过的，本册 13 条把它推过去。
/// 当场证一次的中间读数：在本册里塞一条 <c>GC.Collect()</c> 再跑同一趟，3 红变 1 红
/// 【<c>obj/logs/v40-xugu-gcprobe.log</c>】—— 红不红取决于终结器什么时候跑，这正是"没还"而不是"不能登"的形状。
/// 修法在释放那一步：<c>ConnectionRelease</c>（<c>src/FastSql.Core/Execution/AdoExecutor.cs</c> 末尾）
/// 先 <c>Close</c> 再 Dispose，六处自有连接的释放点全走它；改后本册留在套件里，五家各 160 条 0 红
/// 【实测·<c>obj/logs/v40-{xugu,sqlserver,mysql,postgresql,sqlite}-integration-fix1.log</c>】。
/// 上面"裁判姿势"那半句仍然成立并保留：一条按标签的 SELECT 就能读完一批，逐行读只是多开十条连接，
/// 而<em>在没有那修法的那一版上</em>，多开的每一条都是一条在场未还的会话。于是这里的取数全走
/// <see cref="Stored"/>，而共用那一颗低预算包装也进字段（<see cref="Tight"/>）：每一颗新 orm
/// 都是一颗可能新开的会话，姿势与修法两道一起成立，这一家才跑得动整套件。</para>
///
/// <para><b>连接串那道闸门与本册无关</b>：装载通道（L1）在 MySQL 血统要 <c>AllowLoadLocalInfile</c>，
/// 而写链发的永远是文本，用的是缝给的那颗原始串（<see cref="Database.Orm"/>）。这一句写在这里是因为
/// 上一册把它记成了本册的前置。</para>
///
/// <para><b>五家的读数（2026-10-07 第一趟 ∶ 复跑）</b>：合并档落地的两家 —— MySQL 200 行整行更新
/// 第一趟 <c>merged 701 ms ∶ single 871 ms</c>，复跑三趟 640 ∶ 883、654 ∶ 910、661 ∶ 853；
/// SQL Server 第一趟 <c>193 ∶ 137</c>，复跑 277 ∶ 151、322 ∶ 174、250 ∶ 174。
/// <b>方向各自都是稳的而两家相反</b>：并档省的是往返、添的是解析，MySQL 那一台（远程、往返贵）净赢，
/// 本机 SQL Server 那一台净输【实测·<c>obj/logs/v40-my-bulk-repeat-{1,2,3}.log</c> ∶
/// <c>v40-ss-write-repeat-{1,2}.log</c> ∶ <c>v40-sqlserver-integration-fix1.log</c>。
/// 这几颗数按 §13.4 那句"不要把一次现场读数钉成断言"只记账、不进断言】。
/// 没表过态的三家（PG 血统、虚谷、SQLite）Auto 确实落逐条、
/// 点名 Merged 确实降级、<c>FallbackPolicy.Never</c> 确实响在连接之前。IN 清单删 200 颗键在五家都是 5~20 ms，
/// 而它在全五家走的都是同一档。<b>MySQL 那颗 <c>SupportsMergedStatements=true</c> 因此保住</b>：
/// 真库把这四句并成的一条命令执行过了【实测·<c>obj/logs/v40-{mysql,sqlserver,postgresql,xugu,sqlite}-bulkwrite-2.log</c>】。
/// 第一趟另有三颗红在<em>裁判</em>上而不是写侧：<c>CreatedAt</c> 取的是裸列（丢毫秒，五家都要走
/// <see cref="Millis"/>）、把 <c>RowsPerCommand</c> 当行数读（它是预算算出来的块宽）、
/// 以及在没有策略的三家拿 <c>Around</c> 掰预算（掰不动，读到的仍是 100 的兜底 —— 那一格改用
/// <see cref="LowBudgetProvider.BudgetOnly"/>）。</para>
///
/// <para><b>一句 upsert 档的五家读数（2026-10-07 本档落地那一趟）</b>：接了句尾的两家各跑绿一遍 ——
/// MySQL 血统那一支在活库 8.4.8 上跑过，<b>行别名形状要的 8.0.19 地板因此算落过地</b>；
/// PG 血统那一支的 <c>ON CONFLICT … DO UPDATE</c> 也在活库执行过。没交句尾的三家（SQL Server、虚谷、SQLite）
/// 由 <see cref="DeclaresUpsert"/> 那一句 <c>Assert.SkipWhen</c> 跳过而不是红 —— 那三家的"点名才降级"
/// 归离线册 <c>Naming_upsert_lands_the_tier</c> 判，本册只判接了句尾那一边在活库上的样子。
/// <b>TiDB ∶ OceanBase 两家仍然记未实测</b>：它们共用同一颗 <c>MySqlBulk</c>，文本与 MySQL 逐字同形状，
/// 而这条缝没有那两家的活库端点【实测·<c>obj/logs/v40-{mysql,postgresql,sqlserver,xugu,sqlite}-upsert-full*.log</c>，
/// 五家各 165 条】。</para>
///
/// <para><b>PG 那一趟前两遍是红的，而红不在本册</b>：第一版的 <see cref="ghost"/> 取"比库里最大键还大一千"
/// 那一颗键，本册因此跑绿而下一册的 COPY 撞 <c>23505 duplicate key value violates unique constraint PK_FastSqlOrder</c>
/// 【实测·<c>v40-postgresql-upsert-full{,2}.log</c> 各 1 红 ∶ 红的是 <c>BulkPathTests.The_wall_clock_gap_is_printed_not_asserted</c>】。
/// 根因在这一家的 <c>GENERATED BY DEFAULT AS IDENTITY</c>：写进一颗比已发号还大的显式键<b>不推进序列</b>，
/// 于是后来一次不带键的批量插入会撞上那颗被顶高的行 —— MySQL 的 <c>AUTO_INCREMENT</c> 会一并顶高，没有这一格
/// 【只读探针·<c>obj/probe-seq/Program.cs</c>，量的是 <c>pg_get_serial_sequence</c> ∶ <c>last_value</c> ∶
/// 比已发号还大的行数】。改判后的 <c>ghost</c> 用"刚被本用例删掉的那一颗键"，先把库里只剩三行断死再插，
/// 不碰键空间的上沿【实测·<c>v40-postgresql-upsert-full3.log</c> 165 条 0 红】。</para></summary>
public sealed class BulkWritePathTests
{
    static FastSqlOrm Orm => Database.Orm;

    /// <summary>本册唯一那颗掰预算的包装，进字段复用：<b>每一颗新 orm 都可能是一条新会话</b>，
    /// 而虚谷那一台把这件事量过（类注释那一段）。两条用例要的数一样（3），所以共用一颗。</summary>
    static FastSqlOrm? _tight;

    static FastSqlOrm Tight => _tight ??= Database.OrmWith(provider: LowBudgetProvider.BudgetOnly(Database.Provider, 3));

    readonly string Batch = "fastsql-writebulk/" + Guid.NewGuid().ToString("N")[..8];

    static readonly DateTime Moment = new(2026, 9, 1, 2, 3, 4, 567);

    string tag(string part) => $"{Batch}/{part}";

    /// <summary>一批行：每行的每一列都<em>互不相同</em>（中文名、金额、状态、可空时间交错），
    /// 这样"第 n 行落进第 n 格"才有可数的证据 —— 全同的行集会让整块串位也照样绿。</summary>
    static Order[] rows(string note, int count)
        => [.. Enumerable.Range(1, count)
               .Select(i => new Order
               {
                   CustomerName = "客户" + i,
                   CustomerId = 7,
                   Amount = i + 0.25m,
                   State = i % 2 == 0 ? OrderState.Paid : OrderState.Cancelled,
                   CreatedAt = Moment,
                   PaidAt = i % 3 == 0 ? null : Moment,
                   Note = note,
               })];

    /// <summary>把键填回<em>改过</em>的那一份：除了 <c>Note</c>（它是找回这批行的唯一线索）与 <c>Id</c>，
    /// 其余列全部换了值 —— 没换的列在等价性那一条里等于没判。</summary>
    static Order[] changed(int[] landedIds, string note)
        => [.. landedIds.Select((id, i) => new Order
        {
            Id = id,
            CustomerName = "改了" + (i + 1),
            CustomerId = 70 + i,
            Amount = i + 9.5m,
            State = OrderState.Shipped,
            CreatedAt = Moment.AddMinutes(i + 1),
            PaidAt = i % 2 == 0 ? Moment : null,
            Note = note,
        })];

    /// <summary>只带键的一批（<c>DeleteRange</c> 读的是主键那一列，其余列交什么都不看 ——
    /// 这一点本身就是那条链的形状：<c>WHERE 键 IN (…)</c> 里没有第二颗参数）。</summary>
    static Order[] Keys(int[] landedIds) => [.. landedIds.Select(id => new Order { Id = id })];

    /// <summary>种一批并交回自增键（升序）。<b>走的是 <c>InsertRange</c> 的文本口</b>
    /// （<c>ExecuteAffrowsAsync</c>）：本册不许拿被测的那条链去准备被测的行。一次开连接读完。</summary>
    async Task<int[]> Seed(string note, int count)
    {
        Assert.Equal(count, await Orm.InsertRange(rows(note, count)).ExecuteAffrowsAsync(TestContext.Current.CancellationToken));

        return [.. Stored(note).Keys.Order()];
    }

    /// <summary>按标签一次读完这批行，按自增键索引。<b>一条用例一次开连接</b>：见类注释里虚谷那一颗读数。</summary>
    Dictionary<int, Dictionary<string, string>> Stored(string note)
    {
        var landed = new Dictionary<int, Dictionary<string, string>>();

        foreach (var one in Database.Rows(
            "SELECT [Id], [CustomerName], [CustomerId], [Amount], [State], " + Millis("[CreatedAt]") + " AS CreatedAt, " + Millis("[PaidAt]") + " AS PaidAt, [Note] " +
            "FROM [dbo].[FastSqlOrder] WHERE [Note] = @note ORDER BY [Id]", ("@note", note)))
            landed[int.Parse(one["Id"], CultureInfo.InvariantCulture)] = one;

        return landed;
    }

    /// <summary>带毫秒的两列一律取成<em>看得见小数秒的文本</em>再比（<see cref="Database.MillisText"/>：
    /// T-SQL 那一家的 <c>reader.GetValue().ToString()</c> 会丢小数秒，MySQL 那一支 <c>CAST(… AS CHAR)</c> 才留）。
    /// 本册第一趟在 MySQL 上红的就是这一格——红在裁判的取法上，而不是写侧丢了毫秒。</summary>
    static string Millis(string column) => Database.MillisText(column);

    /// <summary>逐列比"库里这一格"与"入参那一格"。<b>五类值各有其塌法</b>（中文看排序规则、毫秒看 1/300 秒、
    /// decimal 看标度、枚举看有没有折成底层整数、可空列看落的是 <c>NULL</c> 还是空串），而整行更新这一档
    /// 把七列全写了一遍，所以这里一列都不许省。</summary>
    static void SameWritten(Order one, Dictionary<string, string> landed)
    {
        Assert.Equal(one.CustomerName, landed["CustomerName"]);
        Assert.Equal(one.CustomerId, int.Parse(landed["CustomerId"], CultureInfo.InvariantCulture));
        Assert.Equal(one.Amount, decimal.Parse(landed["Amount"], CultureInfo.InvariantCulture));
        Assert.Equal((int) one.State, int.Parse(landed["State"], CultureInfo.InvariantCulture));
        Assert.Equal(one.CreatedAt, DateTime.Parse(landed["CreatedAt"], CultureInfo.InvariantCulture));

        if (one.PaidAt is null)
            Assert.Equal("NULL", landed["PaidAt"]);
        else
            Assert.Equal(one.PaidAt.Value, DateTime.Parse(landed["PaidAt"], CultureInfo.InvariantCulture));

        Assert.Equal(one.Note, landed["Note"]);
    }

    /// <summary>两批逐列比，红的话说得出是哪一列：<b>v3 的 <c>Assert.Equal</c> 没有 userMessage 重载</b>，
    /// 所以把不等的那几列攒成一句话再交出去。</summary>
    static void SameColumns(Dictionary<string, string> one, Dictionary<string, string> other, int ordinal)
    {
        var differs = new List<string>();

        foreach (var column in new[] { "CustomerName", "CustomerId", "Amount", "State", "CreatedAt", "PaidAt" })
            if (!string.Equals(one[column], other[column], StringComparison.Ordinal))
                differs.Add($"{column}：{one[column]} ∶ {other[column]}");

        Assert.True(differs.Count == 0, $"第 {ordinal + 1} 行的 {string.Join("；", differs)} 两档不等");
    }

    /// <summary>本家有没有在 <see cref="IBulkStrategy.SupportsMergedStatements"/> 上表过态 —— <b>问 provider，
    /// 不查家族名</b>：这一颗问句与内核选档用的是同一句判据，写死家族名会在下一家表态时变成一句假话。
    /// （离线册 <c>BulkWriteLayerTests.FamilyRows</c> 那张十六行手写的表是<em>台账</em>，职责不同：
    /// 那张表要能在有人改表态时红，这一颗要在真库上绿。）</summary>
    static bool DeclaresMerged => Database.Provider.Bulk?.SupportsMergedStatements == true;

    static string Posture => Database.Provider.Kind.ToString();

    // ── 整行更新落库（§12.1 写侧、§12.4 的等价性） ────────────────────

    [Fact]
    public async Task A_merged_update_lands_every_row_of_the_batch_in_one_command()
    {
        Database.Ready();
        Assert.SkipWhen(!DeclaresMerged,
            $"{Posture} 没在 SupportsMergedStatements 上表过态，合并档在这里不可达（Auto 会走逐条、" +
            "点名 Merged 会降级）—— 那两格由下面两条判，本条只判合并档真跑起来的样子。");

        var note = tag("merge");
        var landed = await Seed(note, 4);
        var batch = changed(landed, note);

        var report = await Orm.UpdateRange(batch).WithBulk(BulkWriteMethod.Merged)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken);

        Assert.Equal(BulkWriteMethod.Merged, report.Requested);
        Assert.Equal(BulkWriteMethod.Merged, report.Method);
        Assert.Equal(4, report.RowCount);

        // 一次往返是本条的全部内容：四颗语句并成一条命令文本，靠的正是这一家收多语句。
        Assert.Equal(1, report.RoundTrips);
        Assert.False(report.Degraded);

        // 四行逐列读回来：并档最容易串的是"第 n 行落进第 m 格"，而每行每列都不同才看得见串位。
        var stored = Stored(note);

        for (var i = 0; i < landed.Length; i++)
            SameWritten(batch[i], stored[landed[i]]);
    }

    [Fact]
    public async Task The_merged_tier_and_the_row_by_row_tier_land_the_same_rows()
    {
        // §12.4 的等价性在写侧的形状：同一个改动从两档出去，库里读回来必须逐格相同。
        // 两批用两把不相交的键，所以比的<em>就是</em>那两批各自的那一格。
        Database.Ready();

        var merged = tag("same-merged");
        var single = tag("same-single");

        var mergedIds = await Seed(merged, 3);
        var singleIds = await Seed(single, 3);

        Order[] mergedBatch = changed(mergedIds, merged);
        Order[] singleBatch = changed(singleIds, single);

        var viaMerged = await Orm.UpdateRange(mergedBatch).WithBulk(BulkWriteMethod.Merged)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken);
        var viaSingle = await Orm.UpdateRange(singleBatch).WithBulk(BulkWriteMethod.SingleRow)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken);

        Assert.Equal(3, viaMerged.RowCount);
        Assert.Equal(3, viaSingle.RowCount);
        Assert.Equal(3, viaSingle.RoundTrips);

        var copied = Stored(merged);
        var typed = Stored(single);

        for (var i = 0; i < mergedIds.Length; i++)
        {
            // 两批的内容除 Note 外逐字相同（同一份 changed(...) 配方），所以这里比的是<em>两档之间</em>：
            // 并档没有把哪一格改掉、也没有多改哪一格。
            SameColumns(copied[mergedIds[i]], typed[singleIds[i]], i);

            // 各自再与入参比一遍：两档一起错的话上面那一环是看不见的。
            SameWritten(mergedBatch[i], copied[mergedIds[i]]);
            SameWritten(singleBatch[i], typed[singleIds[i]]);
        }
    }

    [Fact]
    public async Task A_key_that_is_not_in_the_library_moves_nothing_and_raises_nothing()
    {
        // 这条判的是"整行更新没有回包"那一格：ExecuteBulkAsync 交回的是决策不是命中数，
        // 所以"键不中"在现场既不像错误也没有计数可看 —— 唯一的证人是库里那一格动没动。
        Database.Ready();

        var note = tag("missing-key");
        var landed = await Seed(note, 2);

        var batch = changed(landed, note);
        var ghost = new Order
        {
            Id = int.MaxValue / 2,
            CustomerName = "不存在的键",
            CustomerId = 7,
            Amount = 1m,
            State = OrderState.Draft,
            CreatedAt = Moment,
            Note = note,
        };

        Order[] withGhost = [.. batch, ghost];

        var report = await Orm.UpdateRange(withGhost).WithBulk(BulkWriteMethod.Merged)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken);

        Assert.Equal(3, report.RowCount);

        var stored = Stored(note);

        for (var i = 0; i < landed.Length; i++)
            SameWritten(batch[i], stored[landed[i]]);

        // 那颗哨兵键没有落进库：更新不建行，而那批的计数因此还是两颗。
        Assert.Equal(2, stored.Count);
    }

