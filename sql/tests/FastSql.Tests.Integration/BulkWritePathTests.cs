        // 今天仍然没有能稳定造出来的第二块失败，所以不在这里装判——那一格由提交次数的现场读数负责
        // 【实测·<c>obj/logs/fscompare-C.txt</c> S3 诊断档】。
        //
        // <b>用的是删除那一档而不是更新</b>：一句 IN 清单在每一家都可达（它不欠多语句表态），
        // 所以"拆成两块"这一形在活库上五家都判得到；换成 UpdateRange 的话，没表过态的三家会退成
        // 逐条三块，那条链上"块"就不是块了（本条第一趟在 PostgreSQL 上红的就是这一格）。
        Database.Ready();

        var note = tag("tran");
        var doomed = await Seed(note, 3);

        // 预算 3 ⇒ 每块 2 颗键 ⇒ 三行两块。
        using (var tran = Tight.BeginTransaction())
        {
            var report = await Tight.DeleteRange(Keys(doomed)).WithBulk(BulkWriteMethod.Merged)
                .ExecuteBulkAsync(TestContext.Current.CancellationToken);

            Assert.Equal(BulkWriteMethod.Merged, report.Method);
            Assert.Equal(2, report.ChunkSize);
            Assert.Equal(2, report.RoundTrips);

            // 环境事务在场时这一批<em>不自开</em>一条：提交归开它的人（这条用例下面要 rollback，
            // 自己提交过的话那句 Rollback 就只剩个形状）。
            Assert.False(report.UsedTransaction);

            // 未提交的自己看得见：两块都挂在同一条连接的那条事务上（§6 (3)）。
            Assert.Equal(0, await Tight.Select<Order>().Where(o => o.Note == note)
                .CountAsync(TestContext.Current.CancellationToken));

            tran.Rollback();
        }

        // 回滚必须由"三行都还在"背书：只断"没报错"的话，两块各自提交了也照样绿。
        Assert.Equal(3, Stored(note).Count);
    }

    [Fact]
    public async Task A_split_batch_opens_its_own_transaction_unless_the_caller_turns_it_off()
    {
        // 改判那一格的现场面：默认一批一事务（UsedTransaction 报真），关掉那颗开关就各交各的。
        // <b>这一条判的不是"库里回不回滚"</b>——第二块失败没法稳定造出来，回滚那一半由上面
        // A_rollback 那条与量具的提交次数读数各自负责；这里判的是执行段<em>真的</em>开了那条事务、
        // 而驱动那侧照样把两块都落库（五家都要绿，否则"包一条事务"在某家根本走不通）。
        Database.Ready();

        var note = tag("atomic");
        var doomed = await Seed(note, 3);

        var wrapped = await Tight.DeleteRange(Keys(doomed)).ExecuteBulkAsync(TestContext.Current.CancellationToken);

        Assert.Equal(2, wrapped.RoundTrips);
        Assert.True(wrapped.UsedTransaction);
        Assert.Empty(Stored(note));

        var other = tag("noatomic");
        var others = await Seed(other, 3);

        var plain = await Tight.DeleteRange(Keys(others)).WithBatchTransaction(false)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken);

        Assert.Equal(2, plain.RoundTrips);
        Assert.False(plain.UsedTransaction);
        Assert.Empty(Stored(other));

        // 一句就删完的那一种不包：包它只多付两次往返，而一条语句本身就原子。
        var single = tag("oneblock");
        var only = await Seed(single, 2);

        Assert.False((await Tight.DeleteRange(Keys(only)).ExecuteBulkAsync(TestContext.Current.CancellationToken))
            .UsedTransaction);
        Assert.Empty(Stored(single));
    }

    // ── 耗时：只报数，不判（§13.4 那句"不要把一次现场读数钉成断言"） ──

    [Fact]
    public async Task The_wall_clock_gap_is_printed_not_asserted()
    {
        // 只有表过态的一家才有两个数可比：没表态的三家在这里点 Merged 会退成逐条，
        // 于是"合并 200 次往返 ∶ 逐条 200 次往返"比的是同一件事，而代价是白跑 400 次往返
        //（虚谷那一台的会话上限就是被这 400 次顶穿的，见类注释）。
        Database.Ready();
        Assert.SkipWhen(!DeclaresMerged,
            $"{Posture} 不并语句，两个数会退成同一串往返（400 次往返换一个 n/a），本条在本家没有可比的两侧。");

        const int Count = 200;

        var merged = tag("clock-merged");
        var single = tag("clock-single");
        var deleted = tag("clock-delete");

        var mergedBatch = changed(await Seed(merged, Count), merged);
        var singleBatch = changed(await Seed(single, Count), single);
        var doomed = await Seed(deleted, Count);

        async Task<long> Measured(Func<Task> action)
        {
            var watch = System.Diagnostics.Stopwatch.StartNew();
            await action();
            watch.Stop();

            return watch.ElapsedMilliseconds;
        }

        var mergedMs = await Measured(async () => await Orm.UpdateRange(mergedBatch).WithBulk(BulkWriteMethod.Merged)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken));

        var singleMs = await Measured(async () => await Orm.UpdateRange(singleBatch).WithBulk(BulkWriteMethod.SingleRow)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken));

        var inListMs = await Measured(async () => await Orm.DeleteRange(Keys(doomed)).WithBulk(BulkWriteMethod.Merged)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken));

        Assert.Empty(Stored(deleted));

        Console.WriteLine($"[bulk-write-timing] rows={Count} merged_ms={mergedMs.ToString(CultureInfo.InvariantCulture)} " +
                          $"single_ms={singleMs} in_list_ms={inListMs} posture={Posture}");
    }
