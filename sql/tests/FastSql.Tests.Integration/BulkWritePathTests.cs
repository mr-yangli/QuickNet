        Assert.Equal(3, Stored(note).Count);

        Order[] batch = [.. changed(landed[..3], note), ghost(absent, note)];

        var report = await Orm.UpdateRange(batch).WithBulk(BulkWriteMethod.Upsert)
            .ExecuteBulkAsync(TestContext.Current.CancellationToken);

        Assert.Equal(BulkWriteMethod.Upsert, report.Requested);
        Assert.Equal(BulkWriteMethod.Upsert, report.Method);
        Assert.False(report.Degraded);
        Assert.Equal(4, report.RowCount);

        // 四行装得进一块 ⇒ 一次往返；而一条命令就是一句语句，所以默认那颗事务在这里不包（判据是语句数）。
        Assert.Equal(1, report.RoundTrips);
        Assert.False(report.UsedTransaction);

        var stored = Stored(note);

        // 那颗缺席的键落成了新行：这一格与 A_key_that_is_not_in_the_library 那条正对面，
        // 而两条合起来才是这一档与 Merged 档的语义差——离线册只能说到那句话，插没插归库里数。
        Assert.Equal(4, stored.Count);

